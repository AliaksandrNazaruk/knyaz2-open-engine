// Функции, которые зовут, а они ничего не делают.
//
//     node tools/idle_calls.js
//
// Мёртвый экспорт (dead_exports.js) ловит то, что никто не зовёт. Здесь
// обратное и более коварное: функцию зовут, она отрабатывает — и не делает
// ничего. Такие остаются после снятой подсистемы: тело выпотрошили, а вызов
// оставили, чтобы «не трогать сцену».
//
// Ищем три вида:
//
//   пустышка   тело пустое или только `return` без значения
//   заглушка   тело — единственный `return <постоянная>`; вызывающие при
//              этом ничего не проверяют, то есть значение никому не нужно
//   мёртвая ветка  `if (ИМЯ)` при `const ИМЯ = false` на уровне модуля —
//              так у нас лежал выключенный кэш выпечки построек
//
// Разбирать JS по-настоящему тут незачем: это список кандидатов, который
// человек просмотрит глазами. Показать лишнее дешевле, чем умолчать.
import { readFileSync, readdirSync } from "node:fs";

const КАТАЛОГ = "knyaz2/web/static";
const файлы = readdirSync(КАТАЛОГ).filter((n) => n.endsWith(".js"));
const тексты = new Map(файлы.map((имя) => [имя, readFileSync(`${КАТАЛОГ}/${имя}`, "utf8")]));

//: Комментарии и строки выкидываем: в них полно скобок и слов `return`.
function голыйКод(текст) {
  return текст
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/(^|[^:])\/\/[^\n]*/g, "$1 ")
    .replace(/`(?:\\.|[^`\\])*`/g, "``")
    .replace(/"(?:\\.|[^"\\])*"/g, '""')
    .replace(/'(?:\\.|[^'\\])*'/g, "''");
}

//: Тело функции по фигурным скобкам — НАЧИНАЯ ПОСЛЕ СПИСКА ПАРАМЕТРОВ.
//
//: Здесь стояло «первая скобка после объявления», и средство врало: в
//: `playPositional(slot, row, col, options = {})` первой оказывалась `{}`
//: значения по умолчанию, тело выходило пустым, и живая функция с шестью
//: вызовами объявлялась пустышкой. Считаем круглые скобки и берём фигурную
//: уже за ними.
function тело(код, от) {
  let глубинаСкобок = 0;
  let i = код.indexOf("(", от);
  if (i < 0) return null;
  for (; i < код.length; i += 1) {
    if (код[i] === "(") глубинаСкобок += 1;
    else if (код[i] === ")") {
      глубинаСкобок -= 1;
      if (глубинаСкобок === 0) { i += 1; break; }
    }
  }
  const открывающая = код.indexOf("{", i);
  if (открывающая < 0) return null;
  let глубина = 0;
  for (let i = открывающая; i < код.length; i += 1) {
    if (код[i] === "{") глубина += 1;
    else if (код[i] === "}") {
      глубина -= 1;
      if (глубина === 0) return код.slice(открывающая + 1, i).trim();
    }
  }
  return null;
}

const находки = [];
const заглушки = new Map();          // имя -> файл, чтобы потом найти вызовы

for (const [имя, текст] of тексты) {
  const код = голыйКод(текст);
  for (const m of код.matchAll(/(?:export\s+)?(?:async\s+)?function\s+(\w+)\s*\(/g)) {
    const внутри = тело(код, m.index);
    if (внутри === null) continue;
    const строки = внутри.split(";").map((s) => s.trim()).filter(Boolean);
    if (!внутри) {
      находки.push([имя, m[1], "пустышка: тело пустое"]);
      заглушки.set(m[1], имя);
    } else if (строки.length === 1 && /^return\s*$/.test(строки[0])) {
      находки.push([имя, m[1], "пустышка: только return"]);
      заглушки.set(m[1], имя);
    } else if (строки.length === 1 &&
               //: Шаблонной строки здесь НЕТ намеренно: `голыйКод` выел её
               //: содержимое, и строитель ключа `${row}:${col}` выглядел бы
               //: постоянной. Так средство трижды оболгало живые функции.
               /^return\s+(-?\d+|null|true|false|""|''|\[\]|\{\})$/.test(строки[0])) {
      находки.push([имя, m[1], `заглушка: всегда ${строки[0].slice(7)}`]);
      заглушки.set(m[1], имя);
    }
  }
  //: Мёртвая ветка по постоянному флагу модуля.
  for (const f of код.matchAll(/^const (\w+)\s*=\s*false\s*;/gm)) {
    const польз = [...код.matchAll(new RegExp(`if\\s*\\(\\s*!?${f[1]}\\b`, "g"))];
    if (польз.length) находки.push([имя, f[1], `мёртвая ветка: ${польз.length} проверок при const false`]);
  }
}

for (const [файл, имя, чем] of находки) console.log(`${файл}: ${имя} — ${чем}`);

//: У заглушек показываем, кто их зовёт: без вызывающих это просто мёртвый
//: экспорт, а с вызывающими — работа, которую можно снять целиком.
if (заглушки.size) {
  console.log("\nкто их зовёт:");
  for (const [имя, где] of заглушки) {
    const зовут = [];
    for (const [файл, текст] of тексты) {
      if (файл === где) continue;
      const n = (голыйКод(текст).match(new RegExp(`\\b${имя}\\s*\\(`, "g")) || []).length;
      if (n) зовут.push(`${файл}×${n}`);
    }
    console.log(`  ${имя}: ${зовут.length ? зовут.join(", ") : "никто"}`);
  }
}
console.log(находки.length ? `\nкандидатов: ${находки.length}` : "\nпустышек не нашлось");
process.exit(0);
