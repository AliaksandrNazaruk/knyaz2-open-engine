# -*- coding: utf-8 -*-
"""Заглянуть в сохранение ОРИГИНАЛЬНОЙ игры: прилавки поселений.

    python tools/savepeek.py                 # все найденные сейвы
    python tools/savepeek.py KONUNG2.SA9     # один

Раскладка снята с самой записи сохранения (VA 0x423CB8): она пишет память
подряд, блок за блоком, и размеры там названы числами. Сумма блоков даёт
837 423 байта — ровно размер файла, так что гадать не о чем.

Прилавок поселения — три списка номеров записей предметов:

    +0x3D0  пять слов: должности (место+1 = роль: 2 знахарь, 3 купец, 4 кузнец)
    +0x3E0  22 слова — прилавок ЗНАХАРЯ
    +0x40E  32 слова — прилавок КУПЦА
    +0x44E  39 слов — прилавок КУЗНЕЦА

Имя вещи берётся из exe: запись класса лежит по 0x45DAF0 + класс*0x20, и
первое поле записи — указатель на строку названия.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

СЕЙВЫ = Path(r"C:\Users\User\AppData\Local\VirtualStore\Program Files (x86)"
             r"\Князь - Коллекционное издание\02. Князь 2 - Кровь Титанов")

#: Блоки сохранения по порядку записи (VA 0x423CB8): имя и размер.
БЛОКИ = [
    ("такт", 4), ("особый", 4), ("снарядов", 4), ("_1", 4), ("шаг_x", 4),
    ("шаг_y", 4), ("поход", 4), ("точка_x", 4), ("точка_y", 4),
    ("цель_x", 4), ("цель_y", 4),
    ("состояния", 0x4B0), ("снаряды", 0xC80), ("предметы", 0x20000),
    ("_2", 0x4EE8), ("отряды", 0xC800), ("кучи", 0x18A88),
    ("юниты", 0x7D000), ("поселения", 0x378C), ("знание", 0x37),
    ("глобальная", 0xC00), ("_3", 0xA0),
]

ЗАПИСЬ_ПОСЕЛЕНИЯ = 0x4A1
ПОСЕЛЕНИЙ = 12
ЗАПИСЬ_ПРЕДМЕТА = 0x10
ПРИЛАВКИ = (("знахарь", 0x3E0, 22), ("купец", 0x40E, 32), ("кузнец", 0x44E, 39))


def смещения() -> dict[str, tuple[int, int]]:
    из, где = {}, 0
    for имя, размер in БЛОКИ:
        из[имя] = (где, размер)
        где += размер
    return из


def имена_классов() -> dict[int, str]:
    """Название класса предмета прямо из exe."""
    from konung2.exetables import ExeTables
    from konung2.paths import game_file

    данные = ExeTables.from_game().data
    pe = struct.unpack_from("<I", данные, 0x3C)[0]
    секций = struct.unpack_from("<H", данные, pe + 6)[0]
    заголовок = struct.unpack_from("<H", данные, pe + 20)[0]
    база = struct.unpack_from("<I", данные, pe + 24 + 28)[0]
    секции = []
    for i in range(секций):
        о = pe + 24 + заголовок + i * 40
        vsz, va, rsz, ro = struct.unpack_from("<IIII", данные, о + 8)
        секции.append((va, vsz, ro, rsz))

    def файл(va: int) -> int | None:
        r = va - база
        for va0, vsz, ro, rsz in секции:
            if va0 <= r < va0 + max(vsz, rsz):
                return ro + (r - va0)
        return None

    из = {}
    for класс in range(256):
        о = файл(0x45DAF0 + класс * 0x20)
        if о is None:
            continue
        указатель = struct.unpack_from("<I", данные, о)[0]
        строка = файл(указатель)
        if строка is None:
            continue
        конец = данные.find(b"\0", строка)
        имя = данные[строка:конец].decode("cp866", errors="replace")
        if имя:
            из[класс] = имя
    return из


def прочитать(путь: Path, классы: dict[int, str]) -> None:
    данные = путь.read_bytes()
    из = смещения()
    ожидалось = sum(размер for _, размер in БЛОКИ)
    print(f"\n=== {путь.name} ===")
    if len(данные) != ожидалось:
        print(f"  размер {len(данные)} вместо {ожидалось} — раскладка не та, дальше не идём")
        return
    такт = struct.unpack_from("<i", данные, из["такт"][0])[0]
    print(f"  мировой такт: {такт}")

    предметы, _ = из["предметы"]
    поселения, _ = из["поселения"]

    def класс_записи(номер: int) -> int | None:
        if not номер:
            return None
        о = предметы + номер * ЗАПИСЬ_ПРЕДМЕТА
        вид, класс = данные[о], данные[о + 3]
        return None if вид == 0xFF else класс

    for место in range(ПОСЕЛЕНИЙ):
        база = поселения + место * ЗАПИСЬ_ПОСЕЛЕНИЯ
        карта = данные[база + 3]
        должности = struct.unpack_from("<5H", данные, база + 0x3D0)
        if not карта and not any(должности):
            continue
        print(f"  поселение {место}: карта {карта}, должности {list(должности)}")
        for имя, смещение, гнёзд in ПРИЛАВКИ:
            слоты = struct.unpack_from(f"<{гнёзд}H", данные, база + смещение)
            вещи = []
            for номер in слоты:
                класс = класс_записи(номер)
                if класс is not None:
                    вещи.append(классы.get(класс, f"класс {класс}"))
            print(f"     {имя:8}: {len(вещи)} шт. {вещи if вещи else ''}")


def main() -> int:
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    классы = имена_классов()
    пути = ([Path(a) for a in sys.argv[1:]]
            or sorted(СЕЙВЫ.glob("KONUNG2.SA[0-9]")))
    if not пути:
        print("сейвов не нашёл")
        return 1
    for путь in пути:
        if not путь.is_file():
            путь = СЕЙВЫ / путь.name
        прочитать(путь, классы)
    return 0


if __name__ == "__main__":
    sys.exit(main())
