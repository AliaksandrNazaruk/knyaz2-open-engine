// Мусор в живом слое редактора: функции без вызовов, поля состояния,
// которые пишут и не читают, и счётчик догадок поиска по вёрстке.
//
// Живой слой — ОДИН файл на шесть тысяч строк, не модуль: dead_exports.js
// его не видит (там нет ни import, ни export). Поэтому свой замер.
//
// Догадки считаем отдельно и намеренно: именно они — источник тихих
// поломок. Органы макета ищутся по тексту, ширине и числу детей, и
// промах не виден никому, потому что на экране остаётся вёрстка
// дизайнера с его выдуманными данными.
//
//     node tools/editor_dead.js
'use strict';
const fs = require('fs');
const path = require('path');

const ФАЙЛ = path.join(__dirname, '..', 'knyaz2', 'web', 'static',
                       'editor_live.js');

function безКомментариев(текст) {
  return текст.replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
}

function экранировать(имя) {
  return имя.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function разбор(текст) {
  const код = безКомментариев(текст);
  const имена = [...код.matchAll(
    /(?:^|\n)\s*(?:async\s+)?function\s+([A-Za-zЀ-ӿ_$][\w$Ѐ-ӿ]*)/g)]
    .map(м => м[1]);
  // ССЫЛКА ТОЖЕ СЧИТАЕТСЯ. Половина функций живого слоя никогда не
  // зовётся по имени: `жизнь1d` лежит в таблице экранов, `сборка` и
  // `играть` вешаются обработчиками. Первая версия искала «имя(» и
  // объявляла мёртвыми все четырнадцать — то есть врала ровно там, где
  // ей верят. Считаем ЛЮБОЕ упоминание, кроме самого объявления.
  const безВызова = имена.filter(имя => {
    const рх = new RegExp('(?<![\\w$\\u0400-\\u04FF])' + экранировать(имя) +
                          '(?![\\w$\\u0400-\\u04FF])', 'g');
    return (код.match(рх) || []).length <= 1;
  });
  const пишут = new Set([...код.matchAll(/state\.([\wЀ-ӿ]+)\s*=/g)]
    .map(м => м[1]));
  const неЧитают = [...пишут].filter(поле => {
    // СРАВНЕНИЕ — НЕ ПРИСВАИВАНИЕ. `state.кудаЮнит === "world"` первая
    // версия считала записью и объявляла поле нечитаемым: хвост «=» у
    // «===» попадал под тот же запрет, что и настоящая запись.
    const рх = new RegExp('state\\.' + экранировать(поле) +
                          '\\s*(?!=[^=]|[+\\-*/|&?]=)', 'g');
    return (код.match(рх) || []).length === 0;
  });
  return {
    строк: текст.split('\n').length,
    функций: имена.length,
    безВызова,
    полей: пишут.size,
    неЧитают,
    сканов: (код.match(/querySelectorAll\("div,span"\)/g) || []).length,
    поШирине: (код.match(/clientWidth\s*[<>]/g) || []).length,
    поФону: (код.match(/поФону\(/g) || []).length,
  };
}

if (require.main === module) {
  const итог = разбор(fs.readFileSync(ФАЙЛ, 'utf8'));
  console.log(`строк: ${итог.строк}`);
  console.log(`функций: ${итог.функций}, без единого вызова: ` +
              `${итог.безВызова.length}`);
  if (итог.безВызова.length) console.log('   ' + итог.безВызова.join(', '));
  console.log(`полей state пишут: ${итог.полей}, не читают: ` +
              `${итог.неЧитают.length}`);
  if (итог.неЧитают.length) console.log('   ' + итог.неЧитают.join(', '));
  // ДОГАДКИ БЫВАЮТ РАЗНЫЕ, И ОПАСНА ТОЛЬКО ОДНА ПОРОДА. Поиск по
  // ТОЧНОМУ ТЕКСТУ («Состав · items», «Глушь») промахивается заметно:
  // не нашлось — значит не нашлось. А вот мерки ПО ГЕОМЕТРИИ («уже 470
  // точек», «больше всех детей», «такой-то фон») берут соседний узел
  // молча и выдают его за нужный — именно так каталог объектов уехал в
  // полоску шириной 56 точек. Считаем их отдельно и стережём именно их.
  console.log(`сканов по тексту: ${итог.сканов}`);
  console.log(`догадок по геометрии: сравнений ширины ${итог.поШирине}, ` +
              `поиска по фону ${итог.поФону}, всего ` +
              `${итог.поШирине + итог.поФону}`);
}

module.exports = { разбор, ФАЙЛ };
