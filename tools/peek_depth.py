# -*- coding: utf-8 -*-
"""
Живой замер порядка глубины: ключи жителей и построек из запущенного оригинала.

ЭТО АРБИТР НАД ДЕКОМПИЛЯТОМ. Формулы взяты из прохода сцены VA 0x004267b8, а
не сочинены:

    ключ юнита     = юнит[+0x3A] + (юнит[+0x54] >> 16)
    ключ постройки = запись[+0x20] + dy_кадра + max(высота main, высота стен)
                     и минус четверть этой высоты, если запись[+0x22] & 8

СЛАГАЕМОЕ dy ОБЯЗАТЕЛЬНО. Оно лежит в заголовке ресурса по 0xC0 + состояние*8
(пара i16 dx, dy — та же, что читает konung2/res.py) и делает ключ равным
ПОДОШВЕ кадра. Без него линия глубины уезжает вниз на 183…450 точек, и всё,
что стоит перед домом, тонет в его спрайте. Ровно так этот инструмент однажды
и «подтвердил» неверную формулу: он считал ключ так же, как сборщик пака, и
сверял её саму с собой.

КООРДИНАТЫ В ЗАПИСЯХ — МИРОВЫЕ. Камеру движок прибавляет только при выводе
кадра, а в ключ она не входит вовсе. Сверка 16.08.2026 на карте 35: ключ без
камеры совпал с паком у 125 объектов из 125, с камерой — у 12 (совпадения).

ЧИТАТЬ БЕЗ ЛИШНЕГО СДВИГА. `+0x32/+0x3A` — это уже целые половины полей 16.16
(`+0x30/+0x38`), и второй сдвиг превращал их в нули: инструмент печатал ровно
нули и выглядел работающим. `+0x54` наоборот — целое поле 16.16, ему сдвиг
нужен. Разбор целиком — docs/RENDER_DEPTH.md.

Сводка по +0x54 внизу отвечает на открытый вопрос про тварей: у них холст
свой (замеры дают 73 и 44), а порт считает их по человеческим 150.

    python tools/peek_depth.py [--pid N]
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tools.livepeek import ЮНИТЫ, ШАГ, ВСЕГО_ЮНИТОВ, Игра, найти_игру  # noqa: E402

ОБЪЕКТЫ = 0x00834768        # список объектов сцены, шаг 0x24 (9 int)
ОБЪЕКТОВ = 0x008496CC       # сколько их
КАМЕРА_X = 0x00849590
КАМЕРА_Y = 0x00849594
КАРТА = 0x008496C8
#: Список отрисовки юнитов: указатели и их количество (VA 0x004267b8).
СПИСОК_ЮНИТОВ = 0x00866C3C
СПИСОК_ЮНИТОВ_ДЛИНА = 0x008A7328
#: Нулевая запись массива юнитов — сам игрок (VA 0x43C252).
ИГРОК = 0x007B3C08


def main() -> int:
    # ЭКЗЕМПЛЯР ВЫБИРАЕТСЯ ЯВНО. Игр может быть запущено несколько — забытая
    # со вчера и та, в которой сейчас играют, — а `найти_игру` берёт первую
    # попавшуюся. Один такой замер уже был снят не с того процесса.
    pid = None
    if "--pid" in sys.argv:
        pid = int(sys.argv[sys.argv.index("--pid") + 1])
    pid = pid or найти_игру()
    if not pid:
        print("оригинал не запущен")
        return 1
    игра = Игра(pid)
    карта = игра.dword(КАРТА)
    # Камера печатается только для справки: координаты записей мировые, и в
    # ключ глубины она не входит (см. заголовок).
    кам_x = struct.unpack("<i", игра.читать(КАМЕРА_X, 4))[0]
    кам_y = struct.unpack("<i", игра.читать(КАМЕРА_Y, 4))[0]
    print(f"процесс {pid} | карта {карта} | камера ({кам_x}, {кам_y})\n")

    # --- жители -------------------------------------------------------------
    # СПИСОК ОТРИСОВКИ, А НЕ ВЕСЬ МАССИВ. Проход сцены берёт юнитов из списка
    # указателей 0x00866C3C длиной 0x008A7328 — там лежат те, кто на карте.
    # Прежняя редакция читала массив 0x7B3C08 подряд и не находила никого:
    # экранные координаты у неактивных записей нулевые.
    люди = []
    сколько_людей = игра.dword(СПИСОК_ЮНИТОВ_ДЛИНА) or 0
    for индекс in range(min(сколько_людей, 2000)):
        адрес = игра.dword(СПИСОК_ЮНИТОВ + индекс * 4)
        if not адрес:
            continue
        запись = игра.читать(адрес, 0x100)
        if not запись or len(запись) < 0x60:
            continue
        холст = struct.unpack_from("<i", запись, 0x54)[0] >> 16
        y = struct.unpack_from("<i", запись, 0x3A)[0]
        x = struct.unpack_from("<i", запись, 0x32)[0]
        люди.append({"номер": (адрес - ЮНИТЫ) // ШАГ if адрес > ЮНИТЫ else индекс,
                     "x": x, "y": y,
                     "холст": холст, "ключ": y + холст,
                     "порода": запись[0x1A],
                     "строка": struct.unpack_from("<H", запись, 0x12)[0],
                     "столбец": struct.unpack_from("<H", запись, 0x14)[0]})

    # --- постройки ----------------------------------------------------------
    сколько = игра.dword(ОБЪЕКТОВ) or 0
    дома = []
    for индекс in range(min(сколько, 600)):
        запись = игра.читать(ОБЪЕКТЫ + индекс * 0x24, 0x24)
        if not запись or len(запись) < 0x24:
            continue
        ресурс = struct.unpack_from("<I", запись, 0)[0]
        if not ресурс:
            continue
        состояние = struct.unpack_from("<I", запись, 32)[0] >> 24
        флаги = запись[0x22]
        # x и y — два обычных i16 подряд, флаги идут следом байтом +0x22.
        # Сверено с паком: 114 объектов Борья из 114.
        x = struct.unpack_from("<h", запись, 0x1E)[0]
        y = struct.unpack_from("<h", запись, 0x20)[0]
        шапка = игра.читать(ресурс, 0x140)
        if not шапка or len(шапка) < 0x140:
            continue
        база = struct.unpack_from("<I", шапка, 0)[0]
        главный = struct.unpack_from("<i", шапка, (состояние * 2 + 0x20) * 4)[0]
        стены = struct.unpack_from("<i", шапка, 2 * 4)[0]
        высота = 0
        for смещение in (главный, стены):
            if смещение == -1:
                continue
            кадр = игра.читать(база + смещение, 4)
            if кадр:
                высота = max(высота, struct.unpack_from("<H", кадр, 2)[0])
        if not высота:
            continue
        # dy якоря кадра этого состояния: заголовок + 0xC0 + состояние*8,
        # пара i16 (dx, dy). Движок берёт её как `заголовок[состояние*2 +
        # 0x30] >> 16` (VA 0x4267B8:206).
        якоря = игра.читать(ресурс + 0xC0 + состояние * 8, 4)
        dx, dy = struct.unpack_from("<2h", якоря, 0) if якоря else (0, 0)
        ключ = y + dy + высота
        if флаги & 8:
            ключ -= высота >> 2
        дома.append({"индекс": индекс, "x": x, "y": y, "высота": высота,
                     "поправка": (высота >> 2) if флаги & 8 else 0,
                     "ключ": ключ, "флаги": флаги})

    print(f"жителей на экране: {len(люди)} | построек: {len(дома)}")
    print("\nжители (первые 10):")
    for ч in люди[:10]:
        # У ОТРЯДА ИГРОКА КЛЕТКА В ЭТИХ ПОЛЯХ НЕ ЛЕЖИТ: у записей 0x7B3C08 и
        # соседних +0x12/+0x14 забиты мусором, хотя координаты настоящие.
        # Поэтому клетка печатается только когда она в пределах сетки.
        годная = 0 <= ч["строка"] < 256 and 0 <= ч["столбец"] < 160
        клетка = (f"клетка ({ч['строка']:>3},{ч['столбец']:>3})" if годная
                  else "клетка      —    ")
        print(f"   #{ч['номер']:>4} {клетка}"
              f" мир y {ч['y']:>5} | холст {ч['холст']:>3} | ключ {ч['ключ']:>5}")
    print("\nпостройки (первые 10):")
    for д in дома[:10]:
        print(f"   #{д['индекс']:>4} мир y {д['y']:>5} | высота {д['высота']:>4}"
              f" | поправка {д['поправка']:>3} | флаги 0x{д['флаги']:02X}"
              f" | ключ {д['ключ']:>5}")
    с_поправкой = sum(1 for д in дома if д["поправка"])
    print(f"\nпостроек с поправкой на четверть: {с_поправкой} из {len(дома)}")

    # ВЫСОТА ХОЛСТА ПО ВИДАМ. Бит 0x40 породы отделяет тварь от человека
    # (тот же бит читает клиент, actor.isBeast). У человека холст 150 — это и
    # есть слагаемое ключа в actor.unitSortKey. У твари он свой (замеры дают
    # 73 и 44), в паке его нет, и порт считает её по человеческой мерке.
    сводка: dict[tuple[str, int], int] = {}
    for ч in люди:
        вид = "тварь" if ч["порода"] & 0x40 else "человек"
        сводка[(вид, ч["холст"])] = сводка.get((вид, ч["холст"]), 0) + 1
    print("\nвысота холста (+0x54) по видам:")
    for (вид, высота), сколько in sorted(сводка.items(), key=lambda kv: -kv[1]):
        print(f"   {вид:<8} холст {высота:>4} — {сколько} юнитов")

    # ЧТО НАКРЫВАЕТ ИГРОКА. Ради этого вопроса замер обычно и делают: встать
    # вплотную к дому и посмотреть, рисует движок его ПОСЛЕ игрока или нет.
    # Дом с бо́льшим ключом ложится сверху.
    з = игра.читать(ИГРОК, 0x100)
    if з and len(з) >= 0x60:
        px = struct.unpack_from("<i", з, 0x32)[0]
        py = struct.unpack_from("<i", з, 0x3A)[0]
        ключ_игрока = py + (struct.unpack_from("<i", з, 0x54)[0] >> 16)
        print(f"\nигрок: мир ({px}, {py}) | КЛЮЧ {ключ_игрока}")
        рядом = sorted(дома, key=lambda д: abs(д["x"] - px) + abs(д["y"] - py))
        print("ближайшие постройки:")
        for д in рядом[:5]:
            вердикт = "НАКРЫВАЕТ (рисуется позже)" if д["ключ"] > ключ_игрока else "под игроком"
            print(f"   #{д['индекс']:>4} якорь ({д['x']:>5},{д['y']:>5})"
                  f" | высота {д['высота']:>4} | ключ {д['ключ']:>5}   {вердикт}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
