// Ускорение времени: тактов должно быть ровно во столько раз больше.
//
//     node tools/clock_scale.js
//
// Стенд гоняет НАСТОЯЩИЕ часы клиента — `clockAdvance` из
// knyaz2/web/static/clock.js, — подавая ему вымышленные показания реальных
// часов. Копии логики здесь нет намеренно: копия проверяла бы себя.
//
// Проверяем три вещи, и все три ломались бы молча:
//   1. счёт: при множителе N за то же реальное время тактов ровно в N раз
//      больше — иначе «ускорение» окажется просто рывками;
//   2. фазы: `clockPhaseHits(0xF)` должна отдать столько же попаданий, сколько
//      их укладывается в пройденные такты. Стройка, работа жителей и
//      мастерская фазируются от счётчика (`& 0xF`, `+7 & 0xF`), и потеряй мы
//      попадание при догоне — деревня встала бы именно на ускорении;
//   3. потолок догона растёт вместе с темпом: он держит долг уснувшей вкладки,
//      но при восьмикратном темпе четырёх тактов на кадр мало и без сна.
import { clock, clockAdvance, clockPhaseHits, clockReset,
         TICK_SECONDS } from "../knyaz2/web/static/clock.js";

//: Кадр браузера при шестидесяти в секунду.
const КАДР = 1 / 60;

// Прогнать `секунд` реального времени кадрами и вернуть, что насчитали часы.
function прогон(scale, секунд, шагКадра = КАДР) {
  clockReset(0);
  clock.scale = scale;
  //: Первый вызов только подводит время (в clockAdvance ветка «разрыв»),
  //: поэтому счёт начинаем со второго кадра.
  clockAdvance(0);
  let время = 0;
  let фазы = 0;
  while (время < секунд) {
    время += шагКадра;
    clockAdvance(время);
    фазы += clockPhaseHits(0xF);
  }
  return { тактов: clock.ticks, фазы };
}

let провалов = 0;
const проверить = (имя, вышло, ждём, допуск = 0) => {
  const ладно = Math.abs(вышло - ждём) <= допуск;
  if (!ладно) провалов += 1;
  console.log(`${ладно ? "ровно " : "СБОЙ  "} ${имя}: ${вышло}, ждали ${ждём}` +
              (допуск ? ` ±${допуск}` : ""));
};

const СЕКУНД = 60;
const одинарный = прогон(1, СЕКУНД);
//: Сколько тактов укладывается в шестьдесят секунд при каноничных 78 мс.
const канон = Math.floor(СЕКУНД / TICK_SECONDS);
проверить("темп 1x за минуту", одинарный.тактов, канон, 2);

for (const scale of [2, 4, 8]) {
  const вышло = прогон(scale, СЕКУНД);
  проверить(`темп ${scale}x за минуту`, вышло.тактов, канон * scale, 2 * scale);
  //: Фаза `& 0xF` сходится раз в шестнадцать тактов — сколько бы их ни было
  //: за кадр. Ловим и потерю попаданий, и лишние.
  проверить(`фазы 0xF при ${scale}x`, вышло.фазы,
            Math.floor(вышло.тактов / 16), 1);
}

// ПОТОЛОК ДОГОНА. Кадр в четверть секунды при восьмикратном темпе требует
// 25 тактов; со старым потолком в четыре мир полз бы вшестеро медленнее
// заказанного. Проверяем именно редким кадром, а не частым.
const редкими = прогон(8, СЕКУНД, 0.25);
проверить("темп 8x редкими кадрами", редкими.тактов, канон * 8, 8 * 8);

// И ОБРАТНОЕ: потолок обязан остаться. Вкладка спала полминуты — долг не
// должен прокрутиться разом.
clockReset(0);
clock.scale = 1;
clockAdvance(0);
clockAdvance(0.1);
const доСна = clock.ticks;
clockAdvance(30);                       // разрыв больше секунды
проверить("после сна долг не сыплется", clock.ticks - доСна, 0);

console.log(провалов ? `\nСБОЕВ: ${провалов}` : "\nВСЁ РОВНО");
process.exit(провалов ? 1 : 0);
