// Правка ЦИТАТ кода в тестах — ТЕМ ЖЕ разбором, что и сам код.
//
// Тесты редактора проверяют наличие подстрок в исходнике клиента:
// `self.assertIn('function зонаОдинРаз(карточка, ключ, найти)', живость)`.
// После перевода имён такие цитаты перестают совпадать.
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ЗАМЕНИТЬ ПО СЛОВАРЮ. Одно и то же имя бывает и
// параметром, и ключом объекта: `ключ` в `function зонаОдинРаз(карточка,
// ключ, найти)` переименовано, а в `{ ключ: key2 }` осталось ключом.
// Заменишь везде — цитата разойдётся с исходником; не заменишь нигде —
// разойдётся тоже. Решает не словарь, а ПОЗИЦИЯ, и она уже разобрана в
// latinize_js.js: гоним каждую цитату через тот же `переименовать`.
//
//     node tools/latinize_test_quotes.js <тест.py> <словарь.json>
'use strict';
const fs = require('fs');
const { переименовать } = require('./latinize_js.js');

//: Однострочные литералы Python: обычные и с префиксом (r, f, b).
const ЛИТЕРАЛ = /(?<!['"\w])([rbfuRBFU]{0,2})('([^'\\\n]|\\.)*'|"([^"\\\n]|\\.)*")/g;
//: Тройные кавычки — докстроки: там пояснения по-русски, не код.
const ДОКСТРОКА = /("""[\s\S]*?"""|'''[\s\S]*?''')/g;

function правкаЦитаты(тело, словарь) {
  try {
    return переименовать(тело, словарь).текст;
  } catch (беда) {
    //: цитата — обрывок кода; если разбор не сходится, оставляем как есть
    return тело;
  }
}

//: ЦИТИРУЮТ НЕ ТОЛЬКО КЛИЕНТА. Те же тесты проверяют подстроки в
//: `server.py`: «sideNum = next((sp for sp in range(185, 200)» — это
//: ПИТОН, и его имена никто не переименовывал. Правка по всему файлу
//: ломала такие проверки ровно так же, как чинила клиентские.
//:
//: Различаем по второму доводу проверки: цитаты клиента сверяются с
//: `живость`, серверные — с `сервер`. Поэтому идём не строками, а
//: ВЫРАЖЕНИЯМИ: копим текст, пока не сойдутся скобки, и правим только
//: те, где помянут клиент.
const КЛИЕНТ = /\bживость\b/;

function скобокРовно(текст) {
  let счёт = 0;
  let строка = null;
  for (let и = 0; и < текст.length; и += 1) {
    const з = текст[и];
    if (строка) {
      if (з === '\\') { и += 1; continue; }
      if (з === строка) строка = null;
      continue;
    }
    if (з === '"' || з === "'") { строка = з; continue; }
    if (з === '#') break;
    if (з === '(' || з === '[' || з === '{') счёт += 1;
    if (з === ')' || з === ']' || з === '}') счёт -= 1;
  }
  return счёт;
}

function применить(путь, словарь) {
  const исходник = fs.readFileSync(путь, 'utf8');
  const куски = исходник.split(ДОКСТРОКА);
  let правок = 0;
  const вышло = куски.map((кусок, место) => {
    if (место % 2 === 1) return кусок;        // сама докстрока
    const строки = кусок.split('\n');
    const готово = [];
    let буфер = [];
    let глубина = 0;
    const слить = () => {
      const текст = буфер.join('\n');
      if (!КЛИЕНТ.test(текст)) { готово.push(текст); буфер = []; return; }
      готово.push(текст.replace(ЛИТЕРАЛ, (всё, префикс, литерал) => {
        const кавычка = литерал[0];
        const тело = литерал.slice(1, -1);
        const новое = правкаЦитаты(тело, словарь);
        if (новое === тело) return всё;
        правок += 1;
        return префикс + кавычка + новое + кавычка;
      }));
      буфер = [];
    };
    for (const строка of строки) {
      буфер.push(строка);
      глубина += скобокРовно(строка);
      if (глубина <= 0) { глубина = 0; слить(); }
    }
    if (буфер.length) слить();
    return готово.join('\n');
  }).join('');
  fs.writeFileSync(путь, вышло);
  return правок;
}

if (require.main === module) {
  const [, , файл, словарь] = process.argv;
  const карта = JSON.parse(fs.readFileSync(словарь, 'utf8'));
  console.log(`${файл}: цитат поправлено ${применить(файл, карта)}`);
}

module.exports = { применить };
