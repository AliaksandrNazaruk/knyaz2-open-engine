# -*- coding: utf-8 -*-
"""Перевести цитатные проверки редактора с БУКВ на ПРАВИЛО.

Тесты редактора держатся за дословные подстроки исходника:
``self.assertIn('function зонаОдинРаз(карточка, ключ)', живость)``. Такая
проверка стережёт не правило, а буквы: любое переименование её валит,
хотя код при этом верен. Именно поэтому перевод имён на латиницу дважды
упирался в три десятка красных тестов.

Здесь такие проверки переписываются в ``assertRegex``: латинские опоры
(``function``, ``querySelectorAll``, ``state``, строковые аргументы)
остаются дословно, а КИРИЛЛИЧЕСКИЕ ИМЕНА становятся ``\\w+`` — «любое
имя». Тест продолжает стеречь форму кода и его опорные точки, но
перестаёт зависеть от того, как названа переменная.

Правятся ТОЛЬКО те проверки, которые сейчас не проходят: остальные
остаются дословными, и это хорошо — чем строже, тем лучше, пока не
мешает.

    python tools/loosen_editor_tests.py <тест.py> <исходник.js>
"""
from __future__ import annotations

import io
import re
import sys
import tokenize
from pathlib import Path

КИРИЛЛИЦА = re.compile(r"[Ѐ-ӿ]")
#: имя целиком: кириллическое слово, возможно с латинскими хвостами
ИМЯ = re.compile(r"[\wЀ-ӿ$]*[Ѐ-ӿ][\wЀ-ӿ$]*")


def в_правило(цитата: str) -> str:
    """Цитата кода → регулярка, где кириллические имена — «любое имя»."""
    куски = []
    место = 0
    for совпало in ИМЯ.finditer(цитата):
        куски.append(re.escape(цитата[место:совпало.start()]))
        куски.append(r"\w+")
        место = совпало.end()
    куски.append(re.escape(цитата[место:]))
    return "".join(куски)


def применить(тест: Path, исходник: Path) -> int:
    код = исходник.read_text(encoding="utf-8")
    текст = тест.read_text(encoding="utf-8")
    строки = текст.splitlines(keepends=True)
    правок = 0
    замены = []
    for лексема in tokenize.generate_tokens(io.StringIO(текст).readline):
        if лексема.type != tokenize.STRING:
            continue
        if лексема.string.lstrip("rbfuRBFU").startswith(('"""', "'''")):
            continue
        if лексема.start[0] != лексема.end[0]:
            continue
        тело = лексема.string[1:-1]
        if not КИРИЛЛИЦА.search(тело) or тело in код:
            continue
        #: цитата с кириллицей, которой в исходнике больше нет
        замены.append((лексема.start, лексема.end,
                       "r'" + в_правило(тело).replace("'", "\\'") + "'"))
        правок += 1
    for (сн, ск), (_, кк), новый in sorted(замены, reverse=True):
        строки[сн - 1] = строки[сн - 1][:ск] + новый + строки[сн - 1][кк:]
    готово = "".join(строки)
    #: `assertIn(regex, живость)` смысла не имеет — подстрока с «\\w+»
    #: в исходнике не встречается. Переводим такие проверки в
    #: `assertRegex`, у которого довод и образец идут наоборот.
    готово = re.sub(
        r"self\.assertIn\((r'(?:[^'\\]|\\.)*'),\s*живость\)",
        r"self.assertRegex(живость, \1)", готово)
    готово = re.sub(
        r"self\.assertIn\((r'(?:[^'\\]|\\.)*'),\s*\n\s*живость\)",
        r"self.assertRegex(живость, \1)", готово)
    тест.write_text(готово, encoding="utf-8")
    return правок


if __name__ == "__main__":
    сколько = применить(Path(sys.argv[1]), Path(sys.argv[2]))
    print(f"{sys.argv[1]}: цитат переведено на правило {сколько}")
