# -*- coding: utf-8 -*-
"""Перевод кириллических ИМЁН в питоне на латиницу — без правки текста.

Правило проекта то же, что и для клиента: комментарии и подписи
по-русски, имена только латиницей. В клиенте это уже сделано; здесь
очередь серверной части.

ЧЕМ ПИТОН ПРОЩЕ JS. Для клиента пришлось писать свой лексер и семь раз
его чинить — шаблонные строки, распылитель, ключи объектов. У питона
точный разбор лежит в стандартной библиотеке (`tokenize`), и границы
имён, строк и комментариев он даёт сам.

ЧЕМ ПИТОН СЛОЖНЕЕ. У него есть ИМЕНОВАННЫЕ ДОВОДЫ: `собрать(карта=63)`.
Имя довода — часть интерфейса ровно так же, как ключ объекта в JS:
переименуешь объявление, не переименовав вызов, — и вызов молча уедет в
`**kwargs` или упадёт. Поэтому имя перед «=» внутри скобок не трогаем и
показываем отдельно: решение за человеком.

Проверка та же, что и в клиенте: до и после из файла вынимаются все
строки и комментарии и сверяются байт в байт. Не совпали — не пишем.

    python tools/latinize_py.py <файл.py> --список
    python tools/latinize_py.py <файл.py> --словарь <карта.json>
"""
from __future__ import annotations

import io
import json
import re
import sys
import token as ЛЕКС
import tokenize
from pathlib import Path

КИРИЛЛИЦА = re.compile(r"[Ѐ-ӿ]")


def лексемы(текст: str) -> list[tokenize.TokenInfo]:
    return list(tokenize.generate_tokens(io.StringIO(текст).readline))


def слепок(текст: str) -> str:
    """Весь неисполняемый текст файла — строки и комментарии подряд."""
    куски = [л.string for л in лексемы(текст)
             if л.type in (ЛЕКС.STRING, ЛЕКС.COMMENT)]
    return "".join(куски)


def _значимые(куски: list[tokenize.TokenInfo]) -> list[int]:
    return [и for и, л in enumerate(куски)
            if л.type not in (ЛЕКС.NL, ЛЕКС.NEWLINE, ЛЕКС.INDENT,
                              ЛЕКС.DEDENT, ЛЕКС.COMMENT)]


def разбор(текст: str) -> dict[str, dict]:
    """Кириллические имена: сколько раз, где именуют довод, где свойство."""
    куски = лексемы(текст)
    места = _значимые(куски)
    порядок = {место: и for и, место in enumerate(места)}
    глубина_скобок = []
    свод: dict[str, dict] = {}
    for место, л in enumerate(куски):
        if л.type != ЛЕКС.NAME or not КИРИЛЛИЦА.search(л.string):
            continue
        и = порядок.get(место)
        до = куски[места[и - 1]].string if и else ""
        после = куски[места[и + 1]].string if и is not None and \
            и + 1 < len(места) else ""
        запись = свод.setdefault(л.string, {"всего": 0, "свойство": 0,
                                            "довод": 0})
        запись["всего"] += 1
        if до in (".",):
            запись["свойство"] += 1
        elif после == "=" and до in ("(", ","):
            запись["довод"] += 1
    return свод


def переименовать(текст: str, словарь: dict[str, str]) -> tuple[str, int]:
    было = слепок(текст)
    куски = лексемы(текст)
    #: ИМЯ НЕ ДОЛЖНО БЫТЬ УЖЕ ЗАНЯТО. В `donor.py` рядом жили латинский
    #: `his` (переменная цикла) и кириллический `его`; словарь свёл их в
    #: одно — и вышло `his.get(his)`: обращение к самому себе вместо
    #: словаря. Ошибки нет, падает позже и в другом месте. У разбора JS
    #: такая защита была с самого начала, здесь её не хватало.
    занятые = {л.string for л in куски
               if л.type == ЛЕКС.NAME and not КИРИЛЛИЦА.search(л.string)}
    свои = {л.string for л in куски if л.type == ЛЕКС.NAME}
    беда = [f"{с} → {н}" for с, н in словарь.items()
            if с in свои and н in занятые]
    if беда:
        raise SystemExit("имя уже занято в файле, будет тихое затенение: "
                         + ", ".join(беда))
    места = _значимые(куски)
    порядок = {место: и for и, место in enumerate(места)}
    строки = текст.splitlines(keepends=True)
    глубина, уровень = {}, 0
    for место, л in enumerate(куски):
        if л.type == ЛЕКС.OP and л.string in "([{":
            уровень += 1
        глубина[место] = уровень
        if л.type == ЛЕКС.OP and л.string in ")]}":
            уровень = max(0, уровень - 1)
            глубина[место] = уровень
    правки = []
    for место, л in enumerate(куски):
        if л.type != ЛЕКС.NAME or л.string not in словарь:
            continue
        и = порядок.get(место)
        if и is None:
            continue
        до = куски[места[и - 1]].string if и else ""
        после = куски[места[и + 1]].string if и + 1 < len(места) else ""
        #: ИМЕНОВАННЫЕ ДОВОДЫ ПЕРЕИМЕНОВЫВАЕМ ТОЖЕ, и это осознанно.
        #:
        #: Сперва я их берегла — имя довода часть интерфейса. Но в
        #: питоне ровно так же выглядит ПАРАМЕТР СО ЗНАЧЕНИЕМ ПО
        #: УМОЛЧАНИЮ: `def sprite(self, слот, палитра=None)`. Пропустив
        #: его, инструмент оставлял параметр русским, а всё тело
        #: переименовывал — «NameError: name 'palette' is not defined».
        #: Отличить объявление от вызова по соседним лексемам нельзя.
        #:
        #: Опасности нет: кириллическим доводом можно позвать только наш
        #: же кириллический параметр, а словарь применяется ко всему
        #: дереву разом. Внешние вызовы (struct, json) русских доводов не
        #: знают вовсе.
        #:
        #: СВОЙСТВА ПОСЛЕ ТОЧКИ — ТОЖЕ НАШИ. В клиенте их беречь было
        #: обязательно: там за точкой стоят поля данных из пака и
        #: подписи для человека. В питоне за точкой стоят АТРИБУТЫ НАШИХ
        #: ЖЕ классов: `self.таблица`, `гр.палитры`. Оставив их русскими,
        #: инструмент переименовывал `def палитры` и ломал доступ —
        #: «'Graph' object has no attribute 'палитры'». Чужие библиотеки
        #: кириллических атрибутов не имеют, а данные лежат в СТРОКОВЫХ
        #: ключах, которых разбор не трогает.
        правки.append((л.start, л.end, словарь[л.string]))
    for (сн, ск), (_, кк), новое in sorted(правки, reverse=True):
        строки[сн - 1] = строки[сн - 1][:ск] + новое + строки[сн - 1][кк:]
    вышло = "".join(строки)
    if слепок(вышло) != было:
        raise SystemExit("текст (строки и комментарии) изменился — не пишем")
    return вышло, len(правки)


if __name__ == "__main__":
    путь = Path(sys.argv[1])
    исходник = путь.read_text(encoding="utf-8")
    if "--список" in sys.argv:
        свод = разбор(исходник)
        всего = sum(з["всего"] for з in свод.values())
        print(f"кириллических имён: {len(свод)}, вхождений: {всего}")
        for имя, з in sorted(свод.items(), key=lambda п: -п[1]["всего"]):
            хвост = []
            if з["свойство"]:
                хвост.append(f"свойство×{з['свойство']}")
            if з["довод"]:
                хвост.append(f"довод×{з['довод']}")
            print(f"{з['всего']:5}  {имя}" +
                  (f"   ({', '.join(хвост)})" if хвост else ""))
        raise SystemExit(0)
    место = sys.argv.index("--словарь")
    словарь = json.loads(Path(sys.argv[место + 1]).read_text(encoding="utf-8"))
    вышло, сколько = переименовать(исходник, словарь)
    путь.write_text(вышло, encoding="utf-8")
    print(f"{путь}: переименовано {сколько}")
