# -*- coding: utf-8 -*-
"""Переименовать имена в ЦИТАТАХ кода внутри тестов редактора.

Тесты `test_editor_layer.py` проверяют наличие подстрок в исходнике
клиента: `self.assertIn('function зонаОдинРаз(карточка, ключ)', живость)`.
После перевода имён на латиницу такие цитаты перестают совпадать — не
потому что правило нарушено, а потому что тест держится за буквы.

Здесь цитаты правятся тем же словарём, что и сам код, с двумя
оговорками:

* ДОКСТРОКИ НЕ ТРОГАЕМ — там пояснения по-русски, а не код;
* ВЛОЖЕННЫЕ СТРОКИ НЕ ТРОГАЕМ. В цитате живут и строковые литералы JS:
  ``промах("зона", ключ)``. Имя ``ключ`` переименовать надо, а ``"зона"``
  нельзя — сам разбор JS строк не трогал, и цитата обязана это повторить.

    python tools/latinize_test_quotes.py <файл> <словарь.json>
"""
from __future__ import annotations

import io
import json
import re
import sys
import tokenize
from pathlib import Path

ВЛОЖЕННАЯ = re.compile(r'("(?:[^"\\]|\\.)*"'
                       r"|'(?:[^'\\]|\\.)*'"
                       r"|`(?:[^`\\]|\\.)*`)")
ЛИТЕРАЛ = re.compile(r'^([rbfuRBFU]*)(["\'])(.*)\2$', re.S)


def правка(литерал: str, словарь: dict[str, str], рх: re.Pattern) -> str:
    совпало = ЛИТЕРАЛ.match(литерал)
    if not совпало:
        return литерал
    префикс, кавычка, тело = совпало.groups()
    части = ВЛОЖЕННАЯ.split(тело)
    for место in range(0, len(части), 2):
        часть = части[место]
        части[место] = рх.sub(lambda з: словарь[з.group(1)], часть)
    return префикс + кавычка + "".join(части) + кавычка


def применить(путь: Path, словарь: dict[str, str],
              только_клиент: bool = True, якорь: str = "живость") -> int:
    порядок = sorted(словарь, key=len, reverse=True)
    рх = re.compile(r"(?<![\wЀ-ӿ])("
                    + "|".join(map(re.escape, порядок))
                    + r")(?![\wЀ-ӿ])")
    исходник = путь.read_text(encoding="utf-8")
    строки = исходник.splitlines(keepends=True)
    замены = []
    #: ЦИТИРУЮТ НЕ ТОЛЬКО КЛИЕНТА. Те же тесты проверяют подстроки в
    #: `server.py` — «sideNum = next((sp for sp in range(185, 200)» это
    #: ПИТОН, его имена никто не переименовывал. Правка по всему файлу
    #: ломала такие проверки ровно так же, как чинила клиентские.
    #: Различаем по доводу проверки: клиентские сверяются с `живость`.
    выражение: list = []
    клиентские: set = set()
    for лексема in tokenize.generate_tokens(io.StringIO(исходник).readline):
        if лексема.type in (tokenize.NEWLINE, tokenize.NL):
            если_клиент = any(т.type == tokenize.NAME and т.string == якорь
                              for т in выражение)
            if если_клиент:
                клиентские.update(id(т) for т in выражение)
            выражение = []
            continue
        выражение.append(лексема)
        if лексема.type == tokenize.STRING:
            замены.append(лексема)
    подходят = ([л for л in замены if id(л) in клиентские]
                if только_клиент else замены)
    замены = []
    for лексема in подходят:
        if лексема.string.lstrip("rbfuRBFU").startswith(('"""', "'''")):
            continue
        if лексема.start[0] != лексема.end[0]:
            continue
        новый = правка(лексема.string, словарь, рх)
        if новый != лексема.string:
            замены.append((лексема.start, лексема.end, новый))
    for (сн, ск), (_, кк), новый in sorted(замены, reverse=True):
        строки[сн - 1] = строки[сн - 1][:ск] + новый + строки[сн - 1][кк:]
    путь.write_text("".join(строки), encoding="utf-8")
    return len(замены)


if __name__ == "__main__":
    файл = Path(sys.argv[1])
    словарь = json.loads(Path(sys.argv[2]).read_text(encoding="utf-8"))
    только = "--все" not in sys.argv
    #: --якорь сервер: чинить цитаты, сверяемые с `сервер`, а не с клиентом
    якорь = (sys.argv[sys.argv.index("--якорь") + 1]
             if "--якорь" in sys.argv else "живость")
    print(f"{файл}: цитат поправлено "
          f"{применить(файл, словарь, только, якорь)}")
