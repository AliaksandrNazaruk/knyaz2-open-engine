# -*- coding: utf-8 -*-
"""Живая трасса боя из ЗАПУЩЕННОЙ оригинальной игры. Только чтение.

    python tools/livepeek.py                 # смотреть, что происходит
    python tools/livepeek.py --csv бой.csv   # писать трассу в файл
    python tools/livepeek.py --unit 42       # следить за конкретной записью

Зачем: сейв даёт снимок состояния, а бой — это ВРЕМЯ. Сколько тактов держится
кадр замаха, на каком кадре уходит стрела, когда падает здоровье, как меняется
походка. Всё это видно только на живой игре, и сверять наш порт с оригиналом
надо именно по такой трассе, а не на глаз.

Читаем ровно те поля, что уже разобраны по декомпиляту:

    0x0084962C  мировой такт           0x008496C8  текущая карта
    0x0084951C  указатель на игрока    0x0084950C  запись его отряда
    0x007B3C08  массив юнитов, шаг 0x100, 2000 записей

    юнит +0x10 цель      +0x12/+0x14 клетка   +0x16 занятие
         +0x17 поза      +0x18 направление    +0x1C кадр
         +0x4E здоровье  +0x52 отрава         +0x58 оружие в руке
         +0xFB подшаг    +0xFD походка        +0x1A порода

Игра тридцатидвухбитная, поэтому и адреса тридцатидвухбитные: читаем как есть.
"""
from __future__ import annotations

import argparse
import ctypes
import ctypes.wintypes as wt
import struct
import sys
import time

ЮНИТЫ = 0x007B3C08
ШАГ = 0x100
ВСЕГО_ЮНИТОВ = 2000
ТАКТ = 0x0084962C
КАРТА = 0x008496C8
ИГРОК = 0x0084951C
ОТРЯД_ИГРОКА = 0x0084950C
#: Массив предметов: шаг 0x10, +0x00 вид, +0x03 класс, +0x04 сколько в пачке.
#: Адрес снят с 0x41A414 ((&DAT_006f956f)[запись * 0x10] — класс) и с расхода
#: стрелы в 0x413894:324 (&DAT_006f9570 + запись * 0x10 — счётчик пачки).
ПРЕДМЕТЫ = 0x006F956C

PROCESS_VM_READ = 0x0010
PROCESS_QUERY_INFORMATION = 0x0400

kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)


def найти_игру() -> int | None:
    """PID процесса konung2.exe."""
    import subprocess
    готово = subprocess.run(
        ["tasklist", "/FI", "IMAGENAME eq konung2.exe", "/FO", "CSV", "/NH"],
        capture_output=True, text=True, encoding="cp866", errors="replace")
    for строка in готово.stdout.splitlines():
        части = [ч.strip('"') for ч in строка.split('","')]
        if len(части) > 1 and части[0].lower().startswith("konung2"):
            try:
                return int(части[1])
            except ValueError:
                continue
    return None


class Игра:
    """Читатель памяти запущенной игры. Пишет НИЧЕГО."""

    def __init__(self, pid: int) -> None:
        self.дескриптор = kernel32.OpenProcess(
            PROCESS_VM_READ | PROCESS_QUERY_INFORMATION, False, pid)
        if not self.дескриптор:
            raise OSError(f"не открыть процесс {pid}: "
                          f"ошибка {ctypes.get_last_error()}")

    def читать(self, адрес: int, сколько: int) -> bytes | None:
        буфер = ctypes.create_string_buffer(сколько)
        прочитано = ctypes.c_size_t()
        ок = kernel32.ReadProcessMemory(
            self.дескриптор, ctypes.c_void_p(адрес), буфер, сколько,
            ctypes.byref(прочитано))
        return буфер.raw[:прочитано.value] if ок else None

    def dword(self, адрес: int) -> int | None:
        сырое = self.читать(адрес, 4)
        return struct.unpack("<I", сырое)[0] if сырое else None

    def закрыть(self) -> None:
        if self.дескриптор:
            kernel32.CloseHandle(self.дескриптор)
            self.дескриптор = None


ПОЛЯ = [
    ("цель", 0x10, "<H"), ("строка", 0x12, "<B"), ("столбец", 0x14, "<B"),
    # Гнездо боеприпаса: 0x413894:323 берёт из него запись предмета и убавляет
    # её пачку на кадре «кадров − 6». Прямой признак самого выстрела.
    ("боеприпас", 0x50, "<H"),
    # Флаг стрельбы: 0x412FF4 ставит его в 1, когда есть и боеприпас (+0x50),
    # и метательное (+0x5A); выбор ближнего замаха 0x416B50 обнуляет. Это и
    # есть «оружие само перешло на ближний бой».
    ("стрельба", 0xEE, "<B"),
    # КУДА ИДЁТ и КАКИМ МАРШРУТОМ — без этого разбирать ИИ нечем: поза и
    # клетка говорят, где юнит СЕЙЧАС, а намерение лежит в назначении
    # (+0x13/+0x15, их же сверяет 0x413894 через 0x43B7D0) и в буфере шагов
    # +0x00..+0x0F — это готовый маршрут списком направлений, 0xFF «пусто».
    ("назначение_строка", 0x13, "<B"), ("назначение_столбец", 0x15, "<B"),
    ("шаги", 0x00, "16s"),
    ("занятие", 0x16, "<B"), ("поза", 0x17, "<B"), ("направление", 0x18, "<B"),
    ("стойка", 0x19, "<B"), ("порода", 0x1A, "<B"), ("сторона", 0x1B, "<B"),
    ("кадр", 0x1C, "<B"), ("здоровье", 0x4E, "<h"), ("отрава", 0x52, "<h"),
    ("подшаг", 0xFB, "<B"), ("походка", 0xFD, "<B"),
    ("кадров", 0xFE, "<B"), ("уровень", 0xF3, "<B"),
    # ГНЁЗДА СНАРЯЖЕНИЯ — по слову на гнездо, номера записей предметов. Нужны,
    # чтобы «один меч» и «два меча» доказывались памятью, а не описанием: удар
    # позы 9 бьёт гнездо 0 на кадре 7 и гнездо 4 на кадре 9 (0x412480), и
    # второй удар обязан пропадать, когда вторая рука пуста.
    ("гнездо0", 0x56, "<H"), ("рука", 0x58, "<H"), ("гнездо2", 0x5A, "<H"),
    ("гнездо3", 0x5C, "<H"), ("гнездо4", 0x5E, "<H"), ("гнездо5", 0x60, "<H"),
]


def разобрать(буфер: bytes, номер: int, начало: int = 0) -> dict | None:
    о = начало + номер * ШАГ
    if о + ШАГ > len(буфер):
        return None
    из = {"юнит": номер}
    for имя, смещение, вид in ПОЛЯ:
        значение = struct.unpack_from(вид, буфер, о + смещение)[0]
        из[имя] = значение.hex() if isinstance(значение, bytes) else значение
    return None if буфер[о + 0x1A] == 0xFF else из


def снять(игра: Игра, номер: int) -> dict | None:
    запись = игра.читать(ЮНИТЫ + номер * ШАГ, ШАГ)
    if not запись or len(запись) < ШАГ:
        return None
    из = разобрать(запись, 0)
    #: НОМЕР НАДО ВЕРНУТЬ НА МЕСТО. Читая одну запись, мы разбираем её с
    #: нулевого смещения, и `разобрать` проставляет «юнит: 0» — в трассе все
    #: закреплённые слоты оказывались нулевыми, и дорожки было не различить.
    if из is not None:
        из["юнит"] = номер
    return из


def рядом_с(буфер: bytes, кто: dict, сколько: int, радиус: int = 2) -> list[dict]:
    """Кто стоит вплотную к юниту — по возрастанию расстояния.

    Поле +0x10 это цель ПРИКАЗА, а не тот, с кем идёт рубка: три замера подряд
    сорвались именно на этом — игрок был отправлен на дальнего врага, а бил его
    вплотную совсем другой, которого в трассе не было. Ближний бой достаёт на
    одну клетку, поэтому урон надо искать среди соседей.
    """
    # ОТБИРАЕМ ПО ТРЁМ БАЙТАМ, а не разбирая запись целиком. Полный разбор
    # двух тысяч записей на каждом такте не поспевал за игрой: в трассе на
    # 2428 тактов оказалось 1246 пропусков, то есть половина. Порода, строка и
    # столбец лежат рядом, и этого хватает, чтобы решить, нужен ли юнит.
    свои = []
    строка_кто, столбец_кто = кто["строка"], кто["столбец"]
    for номер in range(ВСЕГО_ЮНИТОВ):
        о = номер * ШАГ
        порода = буфер[о + 0x1A]
        if порода == 0xFF or порода & 0x80 or номер == кто["юнит"]:
            continue
        даль = max(abs(буфер[о + 0x12] - строка_кто),
                   abs(буфер[о + 0x14] - столбец_кто))
        if даль <= радиус:
            свои.append((даль, номер))
    свои.sort()
    return [разобрать(буфер, номер) for _, номер in свои[:сколько]]


def не_живой(если: dict | None) -> bool:
    return если is None or bool(если["порода"] & 0x80)


def номер_игрока(игра: Игра) -> int | None:
    указатель = игра.dword(ИГРОК)
    if not указатель or указатель < ЮНИТЫ:
        return None
    return (указатель - ЮНИТЫ) // ШАГ


def номер_цели(снимок: dict | None) -> int | None:
    """Кого юнит бьёт прямо сейчас: поле +0x10 — это НОМЕР ЗАПИСИ, не адрес."""
    if not снимок:
        return None
    цель = снимок.get("цель") or 0
    return цель if 0 < цель < ВСЕГО_ЮНИТОВ else None


def main() -> int:
    разбор = argparse.ArgumentParser()
    разбор.add_argument("--csv", help="куда писать трассу")
    разбор.add_argument("--unit", type=int, action="append",
                        help="номер записи юнита; можно несколько раз")
    разбор.add_argument("--hz", type=float, default=60.0, help="частота опроса")
    разбор.add_argument("--seconds", type=float, default=0.0,
                        help="сколько снимать; 0 — до Ctrl+C")
    разбор.add_argument("--near", type=int, default=3,
                        help="сколько СОСЕДЕЙ игрока писать (0 — не писать)")
    разбор.add_argument("--raw", action="store_true",
                        help="писать ВСЮ запись игрока шестнадцатеричным")
    разбор.add_argument("--sticky", type=int, default=2,
                        help="сколько ЦЕЛЕЙ держать в трассе постоянно")
    разбор.add_argument("--foes", type=int, default=0,
                        help="закрепить N ближайших ЧУЖИХ и писать их всегда")
    разбор.add_argument("--radius", type=int, default=20,
                        help="в каком радиусе искать их при закреплении")
    аргументы = разбор.parse_args()
    #: Закреплённых слотов должно хватить на всех, кого закрепляем.
    аргументы.sticky = max(аргументы.sticky, аргументы.foes)

    pid = найти_игру()
    if pid is None:
        print("konung2.exe не запущен — запустите игру и повторите")
        return 1
    игра = Игра(pid)
    print(f"процесс {pid}, читаю только на чтение")

    я = номер_игрока(игра)
    следить = list(аргументы.unit or [])
    if я is not None and я not in следить:
        следить.insert(0, я)
    print(f"игрок — запись {я}; слежу за {следить}")

    # ЦЕЛЬ ИГРОКА ПИШЕТСЯ ВСЕГДА, отдельным набором столбцов. Первый замер боя
    # пропал впустую именно из-за этого: игрок бил запись 423, а в списке
    # слежения её не было, и кадр, на котором ложится урон, сверить было не с
    # чем. Кого бьют — заранее не угадаешь, поэтому слот заполняется на лету, а
    # столбец «цель_юнит» говорит, чей это снимок на данном такте.
    выход = open(аргументы.csv, "w", encoding="utf-8", newline="") if аргументы.csv else None
    if выход:
        столбцы = ["время", "такт", "карта"]
        столбцы += [f"{имя}{н}" for н in следить for имя, _, _ in ПОЛЯ]
        столбцы += ["цель_юнит"] + [f"цель_{имя}" for имя, _, _ in ПОЛЯ]
        for гнездо in range(аргументы.near):
            столбцы += [f"с{гнездо}_юнит", f"с{гнездо}_даль"]
            столбцы += [f"с{гнездо}_{имя}" for имя, _, _ in ПОЛЯ]
        for гнездо in range(аргументы.sticky):
            столбцы += [f"ц{гнездо}_юнит", f"ц{гнездо}_даль"]
            столбцы += [f"ц{гнездо}_{имя}" for имя, _, _ in ПОЛЯ]
        # Кто потерял здоровье этим тактом: «юнит:сколько», через точку с запятой.
        столбцы.append("урон")
        # Сколько стрел в текущей пачке — поле +0x04 записи предмета.
        столбцы.append("стрел")
        # СЫРАЯ ЗАПИСЬ ЦЕЛИКОМ — ПОСЛЕДНИМ СТОЛБЦОМ, как её и пишет строка.
        # Разобранных полей всегда не хватает: расход стрелы, счётчики, флаги —
        # их смещения заранее неизвестны. Проще писать все 256 байт и смотреть
        # потом, что менялось в нужный такт.
        if аргументы.raw:
            столбцы.append("сырое")
        выход.write(",".join(столбцы) + "\n")

    # ЛИПКИЕ ЦЕЛИ. Поле +0x10 гаснет и меняется, а стрела летит долго: замер
    # стрельбы это и погубил — цели были видны урывками, и прилёт каждой
    # стрелы разложить не удалось. Раз попав сюда, юнит пишется КАЖДЫЙ такт
    # до конца записи, и слот за ним закреплён — порядок не меняется.
    липкие: list[int] = []
    # ЗДОРОВЬЕ ВСЕГО МИРА С ПРОШЛОГО ТАКТА. Четыре замера подряд сорвались на
    # том, что урон искали не у того юнита: +0x10 это цель ПРИКАЗА, при
    # стрельбе она вообще может указывать на труп. Массив читается целиком в
    # любом случае, поэтому дешевле сравнивать здоровье ВСЕХ и писать список
    # «кто сколько потерял» одним столбцом — тогда прилёт стрелы найдётся сам.
    прошлое_здоровье: dict[int, int] = {}

    начало = time.perf_counter()
    пауза = 1.0 / max(1.0, аргументы.hz)
    прошлый_такт = None
    try:
        while True:
            теперь = time.perf_counter() - начало
            if аргументы.seconds and теперь > аргументы.seconds:
                break
            такт = игра.dword(ТАКТ)
            if такт is None:
                print("игра закрылась")
                break
            # СНИМАЕМ РОВНО РАЗ НА ТАКТ. Опрос идёт вчетверо чаще самого такта,
            # и если на каждый опрос тянуть все две тысячи записей (512 КиБ),
            # чтение начинает не поспевать — в трассе появляются пропуски. Такт
            # мира это единица времени движка, чаще снимать нечего.
            if такт == прошлый_такт:
                time.sleep(пауза)
                continue
            карта = игра.dword(КАРТА)
            # ВЕСЬ МАССИВ ОДНИМ ЧТЕНИЕМ: одно обращение к памяти на такт вместо
            # двух тысяч.
            #: Массив нужен и соседям, и закреплению чужих, и столбцу урона —
            #: раньше он читался только при `--near`, и с `--near 0` разом
            #: отваливались и поиск врагов, и учёт урона по всему миру.
            все = игра.читать(ЮНИТЫ, ШАГ * ВСЕГО_ЮНИТОВ)
            снимки = ([разобрать(все, н) for н in следить] if все
                      else [снять(игра, н) for н in следить])
            кого = номер_цели(снимки[0] if снимки else None)
            жертва = None
            if кого is not None:
                жертва = разобрать(все, кого) if все else снять(игра, кого)
            соседи = (рядом_с(все, снимки[0], аргументы.near)
                      if все and снимки and снимки[0] else [])
            # ЧУЖИЕ ЗАКРЕПЛЯЮТСЯ ОДИН РАЗ, при первом же снимке. Для разбора ИИ
            # нужны НЕПРЕРЫВНЫЕ дорожки: кто когда пошёл, куда нацелился, каким
            # маршрутом. Слоты соседей для этого не годятся — они меняют хозяина
            # всякий раз, когда меняется расстановка вокруг игрока.
            if аргументы.foes and все and снимки and снимки[0] and not липкие:
                свои_сторона = снимки[0]["сторона"]
                чужие = []
                for номер in range(ВСЕГО_ЮНИТОВ):
                    кто = разобрать(все, номер)
                    if не_живой(кто) or кто["сторона"] == свои_сторона:
                        continue
                    # СПЯЩИХ В ЗЕМЛЕ НЕ БЕРЁМ. Расстановка кладёт скелетов,
                    # кикимор и ичетиков в позу 4, и они не шевелятся, пока
                    # отряд не разбудят. Первый заход на слабых врагах ушёл
                    # впустую именно так: три слота из четырёх заняли твари,
                    # простоявшие все 2426 тактов без единого кадра.
                    if (кто["порода"] & 0x40) and кто["поза"] == 4:
                        continue
                    даль = max(abs(кто["строка"] - снимки[0]["строка"]),
                               abs(кто["столбец"] - снимки[0]["столбец"]))
                    if даль <= аргументы.radius:
                        чужие.append((даль, номер))
                чужие.sort()
                липкие.extend(номер for _, номер in чужие[:аргументы.foes])
                for даль, номер in чужие[:аргументы.foes]:
                    кто = разобрать(все, номер)
                    print(f"  закрепил #{номер}: даль {даль}, уровень "
                          f"{кто['уровень']}, поза {кто['поза']}, "
                          f"порода 0x{кто['порода']:02X}")
            # Новую цель дописываем В КОНЕЦ и больше не трогаем: слот закреплён
            # за юнитом до конца записи, иначе столбцы поедут между тактами.
            elif кого is not None and кого not in липкие:
                if len(липкие) < аргументы.sticky:
                    липкие.append(кого)
            if выход:
                поля = []
                for снимок in снимки:
                    поля += ["" if not снимок else снимок[имя] for имя, _, _ in ПОЛЯ]
                поля.append("" if кого is None else кого)
                поля += ["" if not жертва else жертва[имя] for имя, _, _ in ПОЛЯ]
                свой = снимки[0] if снимки else None
                for гнездо in range(аргументы.near):
                    сосед = соседи[гнездо] if гнездо < len(соседи) else None
                    поля.append("" if not сосед else сосед["юнит"])
                    if сосед and свой:
                        поля.append(max(abs(сосед["строка"] - свой["строка"]),
                                        abs(сосед["столбец"] - свой["столбец"])))
                    else:
                        поля.append("")
                    поля += ["" if not сосед else сосед[имя] for имя, _, _ in ПОЛЯ]
                # ЛИПКИЕ ЦЕЛИ пишутся всегда и в закреплённом за ними слоте.
                for гнездо in range(аргументы.sticky):
                    номер = липкие[гнездо] if гнездо < len(липкие) else None
                    кто = None
                    if номер is not None:
                        кто = разобрать(все, номер) if все else снять(игра, номер)
                    поля.append("" if кто is None else кто["юнит"])
                    if кто and свой:
                        поля.append(max(abs(кто["строка"] - свой["строка"]),
                                        abs(кто["столбец"] - свой["столбец"])))
                    else:
                        поля.append("")
                    поля += ["" if not кто else кто[имя] for имя, _, _ in ПОЛЯ]
                убыль = []
                if все:
                    for номер in range(ВСЕГО_ЮНИТОВ):
                        о = номер * ШАГ
                        if все[о + 0x1A] == 0xFF:
                            continue
                        # Здоровье — одно слово; разбирать всю запись ради него
                        # незачем, и именно это съедало такты.
                        стало = struct.unpack_from("<h", все, о + 0x4E)[0]
                        было = прошлое_здоровье.get(номер)
                        if было is not None and стало < было:
                            кто = разобрать(все, номер)
                            # Расстояние до игрока пишем ТУТ ЖЕ: без него
                            # скорость полёта стрелы не посчитать, а искать
                            # позицию жертвы задним числом негде — в трассе
                            # лежат только слоты соседей и липких целей.
                            даль = ""
                            if свой:
                                даль = max(abs(кто["строка"] - свой["строка"]),
                                           abs(кто["столбец"] - свой["столбец"]))
                            убыль.append(f"{номер}:{было - стало}:{даль}")
                        прошлое_здоровье[номер] = стало
                поля.append(";".join(убыль))
                # СКОЛЬКО СТРЕЛ ОСТАЛОСЬ. Убавление этого числа и есть сам
                # выстрел: 0x413894:321-325 на кадре «кадров − 6» пускает
                # снаряд и тут же вычитает единицу из пачки.
                запас = ""
                if свой and свой.get("боеприпас"):
                    пачка = игра.читать(ПРЕДМЕТЫ + свой["боеприпас"] * 0x10, 0x10)
                    if пачка and len(пачка) >= 8:
                        запас = struct.unpack_from("<I", пачка, 4)[0]
                поля.append(запас)
                if аргументы.raw and следить:
                    смещение = следить[0] * ШАГ
                    кусок = (все[смещение:смещение + ШАГ] if все
                             else игра.читать(ЮНИТЫ + смещение, ШАГ)) or b""
                    поля.append(кусок.hex())
                выход.write(f"{теперь:.4f},{такт},{карта}," + ",".join(map(str, поля)) + "\n")
            if такт != прошлый_такт:
                прошлый_такт = такт
                для_показа = [с for с in снимки if с]
                if жертва and жертва["юнит"] not in следить:
                    для_показа.append(жертва)
                for сосед in соседи:
                    if сосед["юнит"] not in следить and сосед is not жертва:
                        для_показа.append(сосед)
                if для_показа:
                    строки = "  ".join(
                        f"#{с['юнит']} поза={с['поза']:>3} кадр={с['кадр']:>2} "
                        f"походка={с['походка']:>2} здор={с['здоровье']:>4} "
                        f"цель={с['цель']:>4}" for с in для_показа)
                    print(f"такт {такт:>8} карта {карта:>3}  {строки}")
            time.sleep(пауза)
    except KeyboardInterrupt:
        print("\nостановлено")
    finally:
        if выход:
            выход.close()
            print(f"трасса записана: {аргументы.csv}")
        игра.закрыть()
    return 0


if __name__ == "__main__":
    sys.exit(main())
