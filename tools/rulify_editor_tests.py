# -*- coding: utf-8 -*-
"""Перевести цитатные проверки редактора с БУКВ на ПРАВИЛО.

В `test_editor_layer.py` 486 цитат кода, и почти все — дословные:
``self.assertIn('function зонаОдинРаз(карточка, ключ)', живость)``. Такая
проверка стережёт не правило, а буквы: переименование валит её, хотя код
верен. Именно об это дважды споткнулся перевод имён на латиницу.

Здесь два прохода, и оба нужны:

1. ПЕРЕИМЕНОВАТЬ цитату тем же словарём — большинство проверок после
   этого снова совпадают дословно, и они остаются самыми строгими;
2. что не совпало — ПЕРЕВЕСТИ В ПРАВИЛО: латинские опоры (``function``,
   ``querySelectorAll``, ``state``, строковые аргументы) остаются
   дословно, кириллические имена становятся ``\\w+`` — «любое имя», а
   сам вызов из ``assertIn(цитата, живость)`` превращается в
   ``assertRegex(живость, образец)``.

ВЫЗОВ ПРАВИМ РАЗБОРОМ, А НЕ РЕГУЛЯРКОЙ. Четыре попытки сделать это
регуляркой не сошлись: у вызова с десяток написаний — одинарные и
двойные кавычки, перенос строки, вызовы в циклах, f-строки. Лексер
Python находит границы вызова точно.

    python tools/rulify_editor_tests.py <тест.py> <исходник.js> <словарь.json>
"""
from __future__ import annotations

import io
import json
import re
import sys
import tokenize
from pathlib import Path

КИРИЛЛИЦА = re.compile(r"[Ѐ-ӿ]")
ИМЯ = re.compile(r"[\wЀ-ӿ$]*[Ѐ-ӿ][\wЀ-ӿ$]*")
ВЛОЖЕННАЯ = re.compile(r'("(?:[^"\\]|\\.)*"'
                       r"|'(?:[^'\\]|\\.)*'"
                       r"|`(?:[^`\\]|\\.)*`)")


def в_правило(цитата: str) -> str:
    """Цитата кода → регулярка: кириллические имена станут «любым именем»."""
    куски, место = [], 0
    for совпало in ИМЯ.finditer(цитата):
        куски.append(re.escape(цитата[место:совпало.start()]))
        куски.append(r"\w+")
        место = совпало.end()
    куски.append(re.escape(цитата[место:]))
    return "".join(куски)


def переименовать_цитату(тело: str, словарь: dict, рх: re.Pattern) -> str:
    """Имена в цитате — по словарю; строки и СВОЙСТВА не трогаем.

    Свойство после точки в коде осталось русским: ключи объектов не
    переименовывались вовсе, поэтому `что.вид` стало `what.вид`, а не
    `what.kindOf`. Пока правка цитат об этом не знала, она писала
    `what.kindOf` — и проверка искала то, чего в коде нет. Это и было
    причиной большей части несошедшихся цитат.
    """
    части = ВЛОЖЕННАЯ.split(тело)
    for место in range(0, len(части), 2):
        часть = части[место]

        def замена(совпало: re.Match, где: str = часть) -> str:
            начало = совпало.start(1)
            до = где[начало - 1] if начало else ""
            return совпало.group(1) if до == "." else словарь[совпало.group(1)]

        части[место] = рх.sub(замена, часть)
    return "".join(части)


def _лексемы(текст: str) -> list:
    return list(tokenize.generate_tokens(io.StringIO(текст).readline))


def _смещения(текст: str) -> list[int]:
    """Смещение начала каждой строки — чтобы резать по (строка, столбец)."""
    места, место = [0], 0
    for строка in текст.splitlines(keepends=True):
        место += len(строка)
        места.append(место)
    return места


def применить(тест: Path, исходник: Path, словарь: dict) -> tuple[int, int]:
    код = исходник.read_text(encoding="utf-8")
    порядок = sorted(словарь, key=len, reverse=True)
    рх = re.compile(r"(?<![\wЀ-ӿ])(" + "|".join(map(re.escape, порядок))
                    + r")(?![\wЀ-ӿ])")
    текст = тест.read_text(encoding="utf-8")

    # --- проход 1: переименовать цитаты по словарю --------------------
    места = _смещения(текст)
    правки = []
    for л in _лексемы(текст):
        if л.type != tokenize.STRING or л.start[0] != л.end[0]:
            continue
        if л.string.lstrip("rbfuRBFU").startswith(('"""', "'''")):
            continue
        тело = л.string[1:-1]
        if not КИРИЛЛИЦА.search(тело) or тело in код:
            continue
        новое = переименовать_цитату(тело, словарь, рх)
        #: БЕРЁМ ПРАВКУ, ТОЛЬКО ЕСЛИ ОНА СХОДИТСЯ С ИСХОДНИКОМ. Попытка
        #: переименовывать без оглядки вышла хуже: цитата меняется и
        #: формой (развёрнутый ключ, сохранённый русский ключ), а вслепую
        #: словарь этого не знает — красных стало больше, не меньше.
        #: Что не сошлось, доводится руками: таких мест два десятка, и
        #: каждое требует взгляда, а не правила.
        if новое != тело and новое in код:
            начало = места[л.start[0] - 1] + л.start[1] + 1
            правки.append((начало, начало + len(тело), новое))
    for начало, конец, новое in sorted(правки, reverse=True):
        текст = текст[:начало] + новое + текст[конец:]
    переименовано = len(правки)

    # --- проход 2: что не совпало — в правило -------------------------
    места = _смещения(текст)
    правки = []
    лексемы = _лексемы(текст)
    for место, л in enumerate(лексемы):
        if л.type != tokenize.NAME or л.string != "assertIn":
            continue
        #: границы вызова: от «(» до парной «)»
        откр = место + 1
        while откр < len(лексемы) and лексемы[откр].string != "(":
            откр += 1
        глубина, закр = 0, откр
        while закр < len(лексемы):
            з = лексемы[закр].string
            if з in "([{":
                глубина += 1
            elif з in ")]}":
                глубина -= 1
                if глубина == 0:
                    break
            закр += 1
        доводы = [т for т in лексемы[откр + 1:закр]
                  if т.type not in (tokenize.NL, tokenize.COMMENT)]
        if not доводы or доводы[0].type != tokenize.STRING:
            continue
        цитата = доводы[0]
        if цитата.start[0] != цитата.end[0]:
            continue
        тело = цитата.string[1:-1]
        if not КИРИЛЛИЦА.search(тело) or тело in код:
            continue
        #: второй довод — что ищем в чём; берём его текст как есть
        запятая = next((и for и, т in enumerate(доводы)
                        if т.string == "," and т.start[1] > цитата.end[1]), None)
        if запятая is None:
            continue
        хвост = доводы[запятая + 1:]
        если = "".join(т.string for т in хвост).strip()
        if not если:
            continue
        образец = в_правило(тело).replace("\\", "\\\\").replace("'", "\\'")
        начало = места[лексемы[место].start[0] - 1] + лексемы[место].start[1]
        конец = места[лексемы[закр].start[0] - 1] + лексемы[закр].start[1] + 1
        правки.append((начало, конец,
                       f"assertRegex({если}, r'{в_правило(тело)}')"))
    for начало, конец, новое in sorted(правки, reverse=True):
        текст = текст[:начало] + новое + текст[конец:]
    тест.write_text(текст, encoding="utf-8")
    return переименовано, len(правки)


if __name__ == "__main__":
    тест, исходник, словарь = (Path(sys.argv[1]), Path(sys.argv[2]),
                               json.loads(Path(sys.argv[3])
                                          .read_text(encoding="utf-8")))
    а, б = применить(тест, исходник, словарь)
    print(f"{тест}: цитат переименовано {а}, переведено в правило {б}")
