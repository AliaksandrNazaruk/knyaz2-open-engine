# -*- coding: utf-8 -*-
"""Найти в памяти запущенной игры области, которые ЖИВУТ (меняются).

    python tools/scan_live.py <pid>

Ждёт, пока игра затикает (запись игрока начнёт меняться), потом снимает два
снимка сегмента данных и показывает, какие блоки изменились. Нужно, чтобы
поймать подсистему, о которой ничего не известно, — например, анимацию,
которой нет ни в объектах карты, ни в наложениях, ни в юнитах.
"""
from __future__ import annotations

import struct
import sys
import time

sys.path.insert(0, "tools")
sys.path.insert(0, ".")
from livepeek import Игра                                        # noqa: E402

НАЧАЛО, КОНЕЦ = 0x610000, 0x8E0000
БЛОК = 0x10000


def снимок(g: Игра) -> dict[int, bytes]:
    out = {}
    for адрес in range(НАЧАЛО, КОНЕЦ, БЛОК):
        кусок = g.читать(адрес, БЛОК)
        if кусок:
            out[адрес] = кусок
    return out


def main() -> None:
    pid = int(sys.argv[1])
    g = Игра(pid)
    # ЧАСЫ, А НЕ ЗАПИСЬ ИГРОКА. Первый вариант ждал изменений в записи
    # героя — но если он просто стоит, она не меняется, и сканер зря
    # объявлял игру спящей. Мировой такт растёт всегда: 0x87F594 идёт
    # примерно на 13 в секунду, это и есть канонные 12.8 такта.
    ЧАСЫ = 0x0087F594
    print("жду, пока игра затикает (часы 0x87F594)…")
    было = g.dword(ЧАСЫ)
    for _ in range(120):
        time.sleep(0.5)
        стало = g.dword(ЧАСЫ)
        if стало is not None and было is not None and стало != было:
            print(f"игра идёт: такт {было} -> {стало}")
            break
        было = стало
    else:
        print("игра стоит — переключитесь в её окно")
        return
    a = снимок(g)
    time.sleep(1.0)
    b = снимок(g)
    живые = []
    for адрес, кусок in a.items():
        другой = b.get(адрес)
        if not другой or len(другой) != len(кусок):
            continue
        разных = sum(1 for x, y in zip(кусок, другой) if x != y)
        if разных:
            живые.append((разных, адрес))
    живые.sort(reverse=True)
    print(f"живых блоков: {len(живые)}")
    for разных, адрес in живые[:14]:
        print(f"   {адрес:#x}: изменилось {разных} байт")
    g.закрыть()


if __name__ == "__main__":
    main()
