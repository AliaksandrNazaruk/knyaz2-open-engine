// Выходы с локации.
//
// Это не наша выдумка: в стартовом мире есть таблица переходов (250 записей
// по 17 байт, konung2/gamefile.py). Запись называет карту-источник, куда
// ведёт (-1 — уйти на глобальную карту, -2 — особый переход), клетку, куда
// встанет отряд на той стороне, и ПРЯМОУГОЛЬНИК-ТРИГГЕР в клетках исходной
// карты. У Черного Бора их четыре: две полосы по краям ведут на глобальную
// карту, узкая полоса на западе — к Волхву (карта 34), и есть особый выход
// в три клетки.
//
// Сборщик переводит прямоугольник в мировые координаты, здесь остаётся
// поймать героя внутри и сказать об этом один раз.
import { world } from "./world.js";
import { hero } from "./hero.js";

export const exits = [];

// Что было на прошлом тике: шёл ли и на какой клетке стоял. По этой паре и
// ловится «дошёл» — см. exitsTick.
//
// ОДНОГО ПРИЗНАКА «ШЁЛ» МАЛО, и на этом уже обожглись: путь в ОДИН шаг может
// начаться и кончиться между двумя тиками, тогда `шёл` не поднимается ни разу
// и кромки не выходит вовсе — дверь, к которой игрок подходит вплотную, так и
// не срабатывает. Поэтому вторая половина признака — смена клетки.
let heroWas = { walked: false, cell: null };
const mateWas = new Map();

export function exitsSetup(map) {
  exits.length = 0;
  // ПРИХОД НА КАРТУ — НЕ ПРИБЫТИЕ. Движок зовёт разбор прибытия из хода
  // (0x413894), а не из расстановки, поэтому вставший на карту отряд никакого
  // перехода не запускает, даже если встал прямо на дверь. У нас это значит
  // «никто не шёл и все стоят там же»: первый тик запомнит клетки прихода.
  heroWas = { walked: false, cell: null };
  mateWas.clear();
  for (const entry of map.exits ?? []) exits.push({ ...entry });
  return exits;
}

// Выход, внутри которого лежит точка.
export function exitAt(x, y) {
  for (const door of exits) {
    if (x >= door.left && x <= door.right && y >= door.top && y <= door.bottom) {
      return door;
    }
  }
  return null;
}

// ПЕРЕХОД СРАБАТЫВАЕТ НЕ ТОЛЬКО ПОД ВОЖАКОМ.
//
// Разбор дошедшего юнита зовёт переход для КАЖДОГО, кто встал на клетку с
// битом 0x1000 (VA 0x4115AC, ветка по умолчанию), а сам переход пускает
// дальше двоих (VA 0x420900:11):
//
//     if (юнит == вожак ||
//         (вожак[+0x13] == юнит[+0x12] && вожак[+0x15] == юнит[+0x14]))
//
// то есть либо сам игрок, либо тот, кто занял КЛЕТКУ, КУДА ШЁЛ ВОЖАК. И это
// не мелочь: клетку выхода держит один юнит, спутник добегает до неё раньше
// игрока, и шагнуть туда игроку уже некуда — без второй ветки отряд встаёт
// перед дверью насовсем.
//: Идёт ли юнит: буфер шагов не пуст (+0x00 != 0xFF) — в порте это `path`.
function walking(unit) {
  return Boolean(unit?.moving || unit?.path?.length);
}

//: Дошёл ли юнит ровно туда, куда шёл (+0x12 == +0x13 && +0x14 == +0x15).
//: Приказа нет — считаем, что дошёл: расстановка сама приравнивает клетку
//: назначения к своей (0x415238), и у движка эти поля всегда заполнены.
function atGoal(unit, row, col) {
  if (row == null || col == null) return true;
  return unit?.cell?.row === row && unit?.cell?.col === col;
}

//: Ключ клетки — только для сравнения «та же или другая».
function cellKey(cell) { return cell ? `${cell.row},${cell.col}` : null; }

// Кромка «дошёл»: сейчас стоим, а на прошлом тике либо шли, либо стояли на
// ДРУГОЙ клетке. Второе — про путь в один шаг, который целиком укладывается
// между двумя тиками. Возвращает и признак, и что запомнить на следующий раз.
function arrivalOf(unit, was) {
  const key = cellKey(unit?.cell);
  const walks = walking(unit);
  const now = { walked: walks, cell: key };
  if (walks) return { arrived: false, now };
  const first = was.cell === null && !was.walked;   // первый тик после входа
  return { arrived: !first && (was.walked || key !== was.cell), now };
}

// ПЕРЕХОД — ЭТО ПРИБЫТИЕ, А НЕ ПРОХОД НАСКВОЗЬ.
//
// Здесь стояла проверка «пиксели героя внутри прямоугольника», и она
// срабатывала на любом шаге через клетку выхода: игрок шёл мимо и его
// уносило обратно, а на узком берегу пройти было нельзя вовсе.
//
// В движке переход зовут ИЗ ОДНОГО МЕСТА — из разбора прибытия
// `FUN_004115AC`, и до него надо пройти три двери:
//
//     if (юнит[+0x00] == -1)                          // буфер шагов ПУСТ
//       if (юнит[+0x12] == юнит[+0x13] &&             // клетка == куда шёл
//           юнит[+0x14] == юнит[+0x15])
//         switch (занятие & 0x0F) { ... default:
//           if (клетка_поля & 0x1000) FUN_00420900(юнит);
//
// А сам разбор зовётся не каждый кадр, а ПОСЛЕ ШАГА: `0x413894:217` сдвигает
// буфер шагов на один и тут же спрашивает разбор, плюс ветка `:176` для того,
// кто стоит в позе ходьбы с пустым буфером. Значит переход бывает ровно на
// ПОСЛЕДНЕМ шаге пути — когда игрок пришёл туда, куда шёл.
//
// Поэтому здесь ловится КРОМКА «шёл → встал»: ровно один тик на приход, как
// один вызов разбора на последний шаг. Проход насквозь такой кромки не даёт —
// шаги не кончились, — а расстановка не даёт её тем более: после неё никто не
// шёл, и `exitsSetup` так и помечает.
//
// ПЕРЕХОД СРАБАТЫВАЕТ НЕ ТОЛЬКО ПОД ВОЖАКОМ. Разбор зовут для КАЖДОГО, кто
// встал на клетку с битом 0x1000, а сам переход пускает дальше двоих
// (VA 0x420900:11):
//
//     if (юнит == вожак ||
//         (вожак[+0x13] == юнит[+0x12] && вожак[+0x15] == юнит[+0x14]))
//
// то есть либо сам игрок, либо тот, кто занял КЛЕТКУ, КУДА ШЁЛ ВОЖАК. И это
// не мелочь: клетку выхода держит один юнит, спутник добегает до неё раньше
// игрока, и шагнуть туда игроку уже некуда — без второй ветки отряд встаёт
// перед дверью насовсем.
export function exitsTick() {
  if (!hero.alive) return false;
  const свой = arrivalOf(hero, heroWas);
  heroWas = свой.now;

  let door = null;
  if (свой.arrived && atGoal(hero, hero.orderRow, hero.orderCol)) {
    door = exitAt(hero.x, hero.y);
  }

  // Спутники: кромка своя у каждого, а условие — клетка, куда шёл вожак.
  const живые = new Set();
  for (const mate of world.units ?? []) {
    if (!mate?.ally || mate.alive === false || !mate.cell) continue;
    const id = mate.id ?? mate.slot;
    живые.add(id);
    const был = mateWas.get(id) ?? { walked: false, cell: null };
    const его = arrivalOf(mate, был);
    mateWas.set(id, его.now);
    if (door || !его.arrived) continue;
    if (!atGoal(mate, hero.orderRow, hero.orderCol)) continue;
    door = exitAt(mate.x, mate.y);
  }
  //: Выбывших забываем, иначе список растёт весь сеанс.
  for (const id of [...mateWas.keys()]) if (!живые.has(id)) mateWas.delete(id);

  if (!door) return false;
  world.onExit?.(door);
  return true;
}
