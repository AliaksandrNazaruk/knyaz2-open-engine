// СТРУИ ДОЖДЯ. Прежний разбор был НЕВЕРЕН, и это стоит записать прямо.
//
// Весь погодный код Diablo раздвоен флагом [0x7A8A14], а флаг значит одно:
// «это акт 5». Ставится он так (VA 0x472723):
//
//     call 0x6427F0        ; номер акта
//     cmp  al, 4           ; акт 5 — Харрогат
//     je   снег
//     mov  [0x7A8A14], 0   ; акты 1–4 — дождь
//
// Порождение, движение и отрисовка раздвоены по нему все три, а я разобрал
// ветку с НЕнулевым флагом. То есть скорость `8 + 28·глубина`, форма из
// таблицы 0x6D6E78 и качание вбок — ЭТО СНЕГ. Игрок дважды сказал, что на
// экране снег; он был прав оба раза, а моя «проверка» подтвердила ошибку.
//
// НАСТОЯЩИЙ ДОЖДЬ (порождение VA 0x4731FC, отрисовка VA 0x473604):
//
//     x       = жребий(ширина)
//     цельY   = 40 + жребий(высота − 87)      своя линия земли у каждой
//     y       = −20 + жребий(цельY + 20)
//     глубина = (цельY − 40) / (высота − 87)
//     длина   = 4 + 8·глубина    →  4…12 точек     [+0x10], VA 0x47328A
//     скорость= 15 + 15·глубина  →  15…30 за такт  [+0x14], VA 0x473292
//     оттенок = лесенка[жребий(12)]                [+0x24], VA 0x473213
//     [+0x20] = 3                                  сколько лежать упавшей
//
// Никакой таблицы форм у дождя нет вовсе: [+0x10] — это ДЛИНА ЧЁРТОЧКИ, а
// наклон у всех общий, по ветру:
//
//     dx = cos(угол)·длина,  dy = sin(угол)·длина        VA 0x473609
//     если dy > (цельY − y): чёрточку укорачивают        VA 0x47363C
//
// Последнее — приятная мелочь: у самой земли капля становится короче, а
// упав, рисуется одной точкой ещё три такта (VA 0x4735C1).

// ЛЕСЕНКА ОТТЕНКОВ — ЭТО И ЕСТЬ РАЗНИЦА В ЯРКОСТИ МЕЖДУ КАПЛЯМИ.
//
// Оттенок каждой капли выбирается ЖРЕБИЕМ из двенадцати (VA 0x473213:
// `esi = жребий mod 12`), а не по глубине. Лесенку строят на входе в уровень
// (VA 0x472940), и у каждого акта своя: акт 1 берёт 0x7A8980 и рисует
// полупрозрачно (0x7F), акты 2 и 4 — 0x7A894C, акт 3 — 0x7A89A4, оба
// непрозрачно.
//
//     значение = 98 − i·80/12,  цвет = (v, v+25, v)     i = 0…11
//
// Средний канал выше на 25 — то есть капли не серые, а зеленовато-серые.
// Берём лесенку акта 1: его поля ближе всего к нашим.
const ЛЕСЕНКА = Array.from({ length: 12 }, (_, i) => {
  const v = 98 - Math.floor(i * 80 / 12);
  return "rgb(" + v + ", " + (v + 25) + ", " + v + ")";
});
//: прозрачность акта 1 — 0x7F (VA 0x473269), у прочих 0xFF
const ПРОЗРАЧНОСТЬ = 0x7F / 255;

function родить(width, height) {
  //: их отступы и размеры — под кадр 640x480, тянем по стороне
  const k = масштаб(width, height);
  const поле = Math.max(1, height - 87 * k);
  const цельY = 40 * k + Math.random() * поле;
  const глубина = Math.min(1, Math.max(0, (цельY - 40 * k) / поле));
  return {
    x: Math.random() * width,
    y: -20 * k + Math.random() * (цельY + 20 * k),
    цельY,
    длина: (4 + Math.floor(8 * глубина)) * k,
    speed: (15 + Math.floor(15 * глубина)) * k,
    тон: ЛЕСЕНКА[Math.floor(Math.random() * ЛЕСЕНКА.length)],
    лежит: 0,
  };
}

//: КАМЕРА КАПЛЮ НЕ ТАЩИТ. Движок вычитает из шага прокрутку экрана
//: ([0x7A0678] и [0x7A067C], VA 0x473419), то есть падающая капля стоит на
//: месте МИРА, а не кадра. Держим прошлое положение камеры, чтобы знать сдвиг.
let былаКамера = null;

export function streaksTick(width, height, ticks) {
  if (!weather.rain) {
    if (weather.streaks.length) weather.streaks.length = 0;
    былаКамера = null;
    return;
  }
  const шагов = ticks * ШАГ_ДВИЖКА;
  const list = weather.streaks;
  //: сколько их — решает буря, и это далеко не всегда 256; их 32…255
  //: заданы на кадр 640x480, значит тянем по ПЛОЩАДИ
  const растяжка = масштаб(width, height);
  const надо = Math.round(буря.частиц * растяжка * растяжка);
  while (list.length > надо) list.pop();
  while (list.length < надо) list.push(родить(width, height));
  if (!шагов) return;

  const сдвигX = былаКамера ? (view.cameraX - былаКамера.x) * view.zoom : 0;
  const сдвигY = былаКамера ? (view.cameraY - былаКамера.y) * view.zoom : 0;
  былаКамера = { x: view.cameraX, y: view.cameraY };

  //: множитель скорости от силы бури — 0.85…1.0 (VA 0x4732FA)
  const k = буря.сила * 0.15 + 0.85;
  const { dx, dy } = падение();
  for (let i = 0; i < list.length; i += 1) {
    const drop = list[i];
    if (drop.лежит > 0) {
      //: упавшая лежит точкой три такта и уходит (VA 0x4733CA)
      drop.лежит -= шагов;
      if (drop.лежит <= 0) list[i] = родить(width, height);
      continue;
    }
    const шаг = drop.speed * k * шагов;
    drop.x += dx * шаг - сдвигX;
    drop.y += dy * шаг - сдвигY;
    //: по горизонтали кадр замкнут (VA 0x473422), по вертикали — своя земля
    if (drop.x < 0) drop.x += width;
    else if (drop.x >= width) drop.x -= width;
    if (drop.y >= drop.цельY) { drop.y = drop.цельY; drop.лежит = 3; }
  }
}

export function renderStreaks(target) {
  if (!weather.rain || !weather.streaks.length) return;
  target.save();
  target.setTransform(1, 0, 0, 1, 0, 0);
  //: ОБЫЧНОЕ НАЛОЖЕНИЕ, А НЕ СЛОЖЕНИЕ. Цвет капли тёмный (98…25 по каналу),
  //: и прозрачность 0x7F у них означает полусмешение с тем, что под ней.
  //: Сложением тёмно-зелёная капля просто позеленила бы сцену.
  target.globalAlpha = ПРОЗРАЧНОСТЬ;
  target.lineWidth = 1;
  const { dx, dy } = падение();
  for (const drop of weather.streaks) {
    const x = Math.round(drop.x), y = Math.round(drop.y);
    if (drop.лежит > 0) {
      //: упавшая — одна точка (VA 0x4735F3: отрезок из точки в себя)
      target.fillStyle = drop.тон;
      target.fillRect(x, y, 1, 1);
      continue;
    }
    //: у земли чёрточку укорачивают, чтобы не пробить свою линию земли
    let длина = drop.длина;
    const до = drop.цельY - drop.y;
    if (dy > 0 && dy * длина > до) длина = до / dy;
    target.strokeStyle = drop.тон;
    target.beginPath();
    target.moveTo(x, y);
    target.lineTo(x + dx * длина, y + dy * длина);
    target.stroke();
  }
  target.restore();
}

//: Листы погоды в предзагрузку — иначе первый дождь идёт пустыми кольцами.
export function weatherAssets() {
  return sheets().map((sheet) => sheet.path).filter(Boolean);
}
