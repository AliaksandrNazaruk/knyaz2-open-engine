// Погода: круги по земле от дождя. Закон снят с Diablo II, разбор в
// docs/RAIN.md — у самого Князя погоды нет вовсе (в KONUNG2.EXE ни дождя,
// ни снега, проверено поиском).
//
// ГЛАВНОЕ ПРО КОЛЬЦА: они НЕ следы от капель.
//
// Движок держит три независимые системы (VA 0x472320): частицы-струи (256
// записей по 40 байт), всплески (512 по 24) и пузыри (128 по 24). Всплеск
// рождается не там, где упала капля, а В СЛУЧАЙНОМ МЕСТЕ: порождатель зовёт
// жребий (VA 0x472280, множитель 0x6AC690C5) и кладёт результат прямо в
// координаты записи. Связи между струями и кольцами в коде нет никакой.
//
// Четыре набора кадров — это ГЛУБИНА, а не разнообразие: Rain1 разрастается
// до 91 точки, Rain4 до 18. Дальние кольца мельче ближних, и этим движок
// изображает перспективу там, где её нет.
//
// ЧТО НАШЕ, А ЧТО ИХ. Их — кадры, четыре размера, десять шагов, сложение
// (серая лесенка 12…132 в исходнике значит подсветку, а не краску) и сама
// мысль сеять жребием. Наше — привязка к нашей земле: кольцо ЛЕЖИТ НА
// ЗЕМЛЕ, поэтому едет законом плоскости (`drawPlane`), как вода и тени.
