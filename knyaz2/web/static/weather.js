// ТЕМП ДВИЖКА DIABLO — 25 ТАКТОВ В СЕКУНДУ, и это не оценка.
// Качание снега берёт фазу `(время · 512)/25` по кругу в 512 единиц
// (VA 0x4733EE), то есть полный оборот выходит ровно за 25 тактов — за
// секунду. Все их числа ниже заданы в этих тактах.
const ТАКТОВ_ДВИЖКА = 25;
//: их тактов на один наш: такт канона 78 мс, у них 1/25 с
const ШАГ_ДВИЖКА = ТАКТОВ_ДВИЖКА * 0.078;

export const weather = {
  //: идёт ли дождь. Пока ставится флагом в адресе, потом — свойством карты
  rain: false,
  //: ПОРОГ ЖРЕБИЯ ИЗ ТЫСЯЧИ НА ВОДЯНУЮ ПЛИТКУ ЗА ИХ КАДР. Не подбирается:
  //: движок кладёт в него силу бури целиком (VA 0x4DE759 — `сила · 1000`,
  //: и ровно это число сравнивается с `rand(1000)` у каждой плитки воды).
  //: То есть на пике плещет почти каждая водяная плитка каждый кадр.
  //:
  //: null значит «по силе бури», как у них. Число из адреса перебивает —
  //: это отладочная ручка, не канон.
  chance: null,
  //: СКОЛЬКО ДЕРЖИТСЯ ОДИН ШАГ КОЛЬЦА — два ИХ такта на кадр
  //: (VA 0x472CC1: счётчик [всплеск+0x14] убывает, на нуле кадр растёт и
  //: счётчик снова ставится в 2). Десять кадров значит 20 тактов, 0.8 с.
  //: Прежние 1.6 нашего такта на кадр были моим числом и растягивали
  //: кольцо до 1.25 с — оттого их и висело на экране лишку.
  step: 2 / ШАГ_ДВИЖКА,
  //: живые кольца
  drops: [],
  //: живые струи (экранные)
  streaks: [],
};

//: см. readFlag — держать бурю на пике, не пуская в сухую фазу
let весьВремяЛивень = false;

function readFlag() {
  try {
    const raw = new URLSearchParams(window.location.search).get("rain");
    if (raw === null) return false;
    const text = raw.trim().toLowerCase();
    if (["0", "off", "false", "no"].includes(text)) return false;
    //: ОТЛАДОЧНАЯ РУЧКА, НЕ КАНОН. Буря честно уходит в сухую фазу на
    //: 5–10 минут, и ждать её, проверяя вид дождя, невыносимо. `?rain=шторм`
    //: сажает бурю сразу в фазу «держит пик» с полным пиком и не выпускает.
    if (["шторм", "storm", "ливень"].includes(text)) {
      весьВремяЛивень = true;
      return true;
    }
    const value = Number(text);
    //: числом задаётся тот самый порог жребия из тысячи
    if (Number.isFinite(value) && value > 0) weather.chance = value;
    return true;
  } catch { return false; }
}

weather.rain = readFlag();

// ============================================================ ЦИКЛ БУРИ
// Дождь у них не идёт ровно: он ЗАВОДИТСЯ, набирает, стоит и стихает.
// Автомат на четыре фазы по кругу (VA 0x473EB1): когда счётчик исчерпан,
// фаза растёт на единицу по модулю четыре, длительность берётся жребием
// `основа + rand(размах)` из пары таблиц (0x7A8970 — основы, 0x7A8958 —
// размахи, заданы в 0x4728C8), и зовётся `SetWeather(фаза)` (0x473D00).
//
//     фаза 0  сухо          [0x7A89E0] = 0            7500 + rand(7500)
//     фаза 1  нарастание    пик = 32 + rand(224)       250 + rand(250)
//     фаза 2  держит пик    —                         3000 + rand(3000)
//     фаза 3  спад          —                          125 + rand(50)
//
// А само число капель считается КАЖДЫЙ ТАКТ (VA 0x473F01 и 0x473F1D):
//
//     нарастание:  частиц = (Т − t) · пик / Т
//     спад:        частиц = пик · t / Т
//     сила       = частиц / 256                      (0x473F38, 1/256)
//
// Пик у каждой бури свой, 32…255, — оттого одна морось, другая ливень.
//
// СИЛА ПРАВИТ ТРЕМЯ ВЕЩАМИ, и список закрыт: я перебрал всех, кто её читает
// через 0x473C80 — скорость падения (0.85 + 0.15·сила, VA 0x4732FA), порог
// колец на воде (сила·1000, VA 0x4DE759) и громкость шума дождя (сила·255,
// VA 0x4E439D). СВЕТА СРЕДИ НИХ НЕТ: Diablo дождём сцену не темнит,
// пасмурность акта зашита в постоянный свет уровня и палитру.
// ИХ ЧИСЛА ЗАДАНЫ ПОД КАДР 640x480, И ЭТО НАДО ПЕРЕСЧИТЫВАТЬ.
//
// Движок читает ширину и высоту из [0x71146C]/[0x711470], но все отступы и
// размеры в нём — АБСОЛЮТНЫЕ точки, выверенные под родное разрешение: капля
// длиной 4…12 точек, отступ 40 сверху, 87 снизу, и ровно 32…255 капель на
// экран. На 800x600 у самой Diablo дождь оттого и выходит реже — это
// побочность фиксированных констант, а не замысел.
//
// Наш кадр 1349x1035 — вчетверо больше по площади. Перенеся числа буквально,
// я получил вчетверо более редкий и вдвое более короткий дождь: капель почти
// не видно. Поэтому берём их кадр за образец и тянем по нему:
//
//     k = √(наша площадь / (640·480))
//     число капель ∝ k²      (площадь)
//     длина, скорость, отступы ∝ k   (сторона)
//
// Так на экране выходит та же густота и то же время пересечения кадра, что у
// них, — то есть их вид, а не их числа. Это осознанное отступление от буквы,
// и другого способа совместить фиксированные константы с плавающим кадром нет.
const КАДР_ДВИЖКА = { ширина: 640, высота: 480 };

function масштаб(width, height) {
  return Math.sqrt(width * height / (КАДР_ДВИЖКА.ширина * КАДР_ДВИЖКА.высота));
}

const ФАЗЫ = [
  { имя: "сухо", основа: 7500, размах: 7500 },
  { имя: "нарастание", основа: 250, размах: 250 },
  { имя: "пик", основа: 3000, размах: 3000 },
  { имя: "спад", основа: 125, размах: 50 },
];

export const буря = {
  фаза: 0, осталось: 0, длина: 1, пик: 256, частиц: 0, сила: 0,
};

function бурюТик(шагов) {
  if (весьВремяЛивень) {
    //: фаза 2 сама по себе ничего не считает — просто держит, что есть
    буря.фаза = 2;
    буря.пик = 255;
    буря.частиц = 255;
    буря.сила = 255 / 256;
    буря.осталось = буря.длина = 1e9;
    return;
  }
  буря.осталось -= шагов;
  if (буря.осталось <= 0) {
    буря.фаза = (буря.фаза + 1) % ФАЗЫ.length;
    const { основа, размах } = ФАЗЫ[буря.фаза];
    буря.длина = основа + Math.random() * размах;
    буря.осталось = буря.длина;
    //: SetWeather(0) гасит счёт начисто, SetWeather(1) берёт новый пик
    if (буря.фаза === 0) буря.частиц = 0;
    if (буря.фаза === 1) буря.пик = 32 + Math.floor(Math.random() * 224);
  }
  const t = Math.max(0, буря.осталось);
  if (буря.фаза === 1) {
    буря.частиц = Math.round((буря.длина - t) * буря.пик / буря.длина);
  } else if (буря.фаза === 3) {
    буря.частиц = Math.round(буря.пик * t / буря.длина);
  }
  буря.сила = буря.частиц / 256;
}

// ВЕТЕР. Угол падения — гуляющий глобал [0x7A89C4], и круг у него в 512
// единиц (качание снега берёт фазу `& 0x1FF`, VA 0x473404, и период выходит
// ровно секунда при 25 тактах — этим же подтверждается и частота движка).
//
// Дрейф: каждый такт угол тянется к цели на две единицы (VA 0x4737F7; шаг
// равен 1 у снега и 2 у дождя). Цель меняется по своему счётчику:
//
//     [0x7A89E4] = 125 + rand(375)      когда сменить      VA 0x473859
//     [0x7A89F8] =  92 + rand(71)       новая цель         VA 0x4738D8
//
// Отвес — это 128, значит 92…162 есть РОВНО ±25° от вертикали, симметрично.
// Оттого капли и не идут всегда в одну сторону.
const ВЕТЕР = { угол: 128, цель: 128, осталось: 0 };

function ветерТик(шагов) {
  const шаг = 2 * шагов;
  if (ВЕТЕР.цель < ВЕТЕР.угол) ВЕТЕР.угол = Math.max(ВЕТЕР.цель, ВЕТЕР.угол - шаг);
  else if (ВЕТЕР.цель > ВЕТЕР.угол) ВЕТЕР.угол = Math.min(ВЕТЕР.цель, ВЕТЕР.угол + шаг);
  ВЕТЕР.осталось -= шагов;
  if (ВЕТЕР.осталось <= 0) {
    ВЕТЕР.осталось = 125 + Math.random() * 375;
    ВЕТЕР.цель = 92 + Math.random() * 71;
  }
}

//: единичный вектор падения из угла: 128 — точно вниз
function падение() {
  const rad = ВЕТЕР.угол * Math.PI / 256;
  return { dx: Math.cos(rad), dy: Math.sin(rad) };
}

// ПАСМУРНОСТЬ — НАША ДОБАВКА, И ЭТО НАДО СКАЗАТЬ ПРЯМО.
//
// У Diablo такого нет (список потребителей силы выше — закрытый), у Князя
// погоды нет вовсе. Но дождь в ясный полдень выглядит нелепо, поэтому небо
// затягиваем — ТОЙ ЖЕ механикой, какой движок Князя правит сутки: уровнем
// канала −100…+100, где отрицательный гасит канал как `c·(1−L/100)`
// (генератор канальных таблиц VA 0x43CA8B). Никакого своего фильтра поверх
// кадра и никакого выдуманного оттенка: три канала гасятся ровно поровну,
// а глубина идёт по силе бури.
const ТУЧИ = 25;

function sets() {
  return world.map?.weather?.sets?.rain ?? null;
}

function sheets() {
  return world.map?.weather?.sheets ?? [];
}

// КОЛЬЦА РОЖДАЮТСЯ ТОЛЬКО НА ВОДЕ.
//
// Первый заход сеял их по всей видимой коробке — и это была ошибка: круги
// шли по траве, по крышам, по чему угодно. В движке всплеск рождается
// ВНУТРИ ЦИКЛА ОТРИСОВКИ ПЛИТОК и только у плитки с поднятым битом (VA
// 0x4DE5BA: `test byte [запись+6], 2`), а дальше та бросает жребий из
// тысячи (`rand(1000) < порог`, VA 0x4DE5C3).
//
// У нас водяные клетки — это `world.underlay`: список кладётся только там,
// где маска подложки ненулевая, то есть ровно там, где вода. Значит перебор
// по нему и есть их «плитки с битом».
//
// РАЗМЕР — ПО ГЛУБИНЕ, а не жребием: у нас, в отличие от них, есть
// настоящая перспектива, и мельчить дальние кольца ещё и набором кадров
// значило бы согнуть закон дважды. Поэтому набор берётся по строке кадра —
// это ровно то, ради чего у них четыре набора и заведены.
function born(box, ticks) {
  const all = sets();
  const sizes = all?.sizes ?? [];
  if (!sizes.length) return;
  const cells = world.underlay ?? [];
  if (!cells.length) return;
  const height = Math.max(1, box.bottom - box.top);
  //: ЖРЕБИЙ У НИХ — НА ПЛИТКУ, А НАША КЛЕТКА ВПЯТЕРО КРУПНЕЕ.
  //:
  //: Движок бросает его на каждую нарисованную плитку воды, а плитка у него
  //: 160x80 = 12800 точек. Наша клетка подложки 256x256 = 65536, то есть
  //: пять с лишним ихних. Кидая по одному разу на клетку, мы кидали впятеро
  //: реже них — отсюда и «интерференции слишком мало».
  const ПЛИТКА = 160 * 80;
  //: вероятность на плитку — сила бури, как в 0x4DE759
  const вероятность = weather.chance === null
    ? буря.сила : weather.chance / 1000;
  if (вероятность <= 0) return;
  //: ПОТОЛОК КАК У НИХ: система всплесков заведена на 512 записей
  //: (VA 0x472340, `push 0x18; mov edx,0x200`). Заодно страховка от карты,
  //: где воды пол-экрана.
  const потолок = 512;
  for (const cell of cells) {
    if (weather.drops.length >= потолок) break;
    const size = cell.size ?? 256;
    if (cell.x + size < box.left || cell.x > box.right ||
        cell.y + size < box.top || cell.y > box.bottom) continue;
    //: сколько ихних плиток покрывает эта клетка — столько раз и кидаем,
    //: и КАЖДЫЙ удачный бросок родит своё кольцо, как у них своё на плитку
    //: ...и столько же раз ЗА КАЖДЫЙ ИХ КАДР, а их кадров на наш такт
    //: приходится 1.95 — жребий у них крутится в цикле отрисовки плиток.
    //:
    //: ПЛИТКА У НИХ ЭКРАННАЯ, А КЛЕТКА У НАС МИРОВАЯ. Сперва я делил мировую
    //: площадь клетки на 160x80 и получал 5.12 при любом зуме. Неверно: при
    //: зуме 1.65 клетка кроет на экране 13.9 их плиток, а при 0.45 — всего
    //: одну. Без зума густота колец ездила от приближения, и как раз против
    //: здравого смысла — вблизи их становилось меньше.
    const наЭкране = size * view.zoom;
    const бросков = Math.max(1, Math.round(
      наЭкране * наЭкране / ПЛИТКА * ШАГ_ДВИЖКА * ticks));
    for (let k = 0; k < бросков && weather.drops.length < потолок; k += 1) {
      if (Math.random() >= вероятность) continue;
      const x = cell.x + Math.random() * size;
      const y = cell.y + Math.random() * size;
      //: доля высоты кадра: 0 наверху (далеко), 1 внизу (близко)
      const share = Math.min(1, Math.max(0, (y - box.top) / height));
      //: наборы идут от крупного к мелкому, значит близкому нужен первый
      const pick = Math.min(sizes.length - 1,
                            Math.floor((1 - share) * sizes.length));
      weather.drops.push({ x, y, size: pick, frame: 0 });
    }
  }
}

export function weatherTick(visible) {
  if (!weather.rain) {
    if (weather.drops.length) weather.drops.length = 0;
    буря.частиц = 0;
    буря.сила = 0;
    overcast.level = 0;
    return;
  }
  //: ЖИВЁМ ПО МИРОВЫМ ТАКТАМ, как всё остальное: `clock.elapsed` — сколько
  //: их прошло за этот кадр браузера. По кадрам браузера считать нельзя,
  //: иначе на быстром мониторе дождь пойдёт втрое гуще.
  const ticks = clock.elapsed ?? 0;
  //: БУРЯ ИДЁТ ПЕРВОЙ: от её силы зависят и кольца ниже, и струи, и тучи.
  //: Считается здесь, а не в струях, потому что кольцам сила нужна уже
  //: в этом кадре, а струи рисуются позже (scene.js).
  if (ticks) {
    const шагов = ticks * ШАГ_ДВИЖКА;
    бурюТик(шагов);
    ветерТик(шагов);
    overcast.level = ТУЧИ * буря.сила;
  }
  //: колец может не быть в паке — струи и тучи всё равно идут
  if (!ticks || !sets()) return;
  for (let i = weather.drops.length - 1; i >= 0; i -= 1) {
    const drop = weather.drops[i];
    drop.frame += ticks / weather.step;
    const strip = sets().sizes[drop.size];
    if (drop.frame >= strip.length) weather.drops.splice(i, 1);
  }
  born(visible, ticks);
}

export function renderRain() {
  if (!weather.rain || !weather.drops.length) return;
  const all = sets();
  if (!all) return;
  const list = sheets();
  const mode = context.globalCompositeOperation;
  //: СЛОЖЕНИЕ. В исходнике кольцо нарисовано серой лесенкой (12…132), то
  //: есть оно ПОДСВЕЧИВАЕТ то, что под ним, а не мажет краской. Обычной
  //: альфой серое кольцо на тёмной земле выглядит грязным пятном.
  if (all.blend === "additive") context.globalCompositeOperation = "lighter";
  for (const drop of weather.drops) {
    const strip = all.sizes[drop.size];
    const frame = strip[Math.floor(drop.frame)];
    if (!frame) continue;
    const image = world.images.get(list[frame.sheet]?.path);
    if (!image) continue;
    //: кольцо лежит НА ЗЕМЛЕ — значит плоскость, и едет законом земли.
    //: Кадр лежит куском общего листа, поэтому `drawPlanePart`.
    drawPlanePart(context, image,
                  frame.x, frame.y, frame.width, frame.height,
                  drop.x + frame.offset_x, drop.y + frame.offset_y,
                  frame.width, frame.height);
  }
  context.globalCompositeOperation = mode;
}

