// Сложность: во что она обходится игроку.
//
// ЧТО ДЕЛАЕТ СЛОЖНОСТЬ В ДВИЖКЕ. Ровно одно — множит начисляемый опыт.
// Ступеней у неё ТРИ: кнопки экрана настроек пишут в 0x84958C двойку,
// единицу и ноль (VA 0x438A00, случаи 10/11/12), те же три значения читает
// отрисовка галочек (VA 0x4326A8), а начисление берёт множитель как
// «значение + 2» — от ×2 до ×4 (VA 0x413110). Штрафа в движке не бывает
// вовсе, и стартовых денег сложность не трогает.
//
// Направление там ровно такое же, как здесь: первая кнопка (лёгкая игра)
// пишет двойку, то есть даёт САМЫЙ БОЛЬШОЙ множитель опыта. Прежний список
// в нашем меню считал наоборот — «опыт ×(номер + 2)», где Князь получал
// ×6, — и это была наша ошибка, а не канон.
//
// ЧТО ЗДЕСЬ НАШЕ. Пять ступеней вместо трёх и штраф у верхних: до ×0.5
// опыта и без денег на старте. Середина («Витязь») оставлена канонической:
// ×2 опыта — столько движок ставит без KONUNG2.CFG — и деньги ровно те, что
// лежат в записи героя.
export const DIFFICULTY = [
  { name: "Ученик",   xp: 4,   money: 10 },
  { name: "Воин",     xp: 3,   money: 5 },
  { name: "Витязь",   xp: 2,   money: 1 },
  { name: "Богатырь", xp: 1,   money: 0.5 },
  { name: "Князь",    xp: 0.5, money: 0 },
];

export const DIFFICULTY_DEFAULT = 0;

export function difficultyOf(value) {
  const at = Number.isInteger(value) ? value : DIFFICULTY_DEFAULT;
  return DIFFICULTY[at] ?? DIFFICULTY[DIFFICULTY_DEFAULT];
}

//: Подпись под выбором — чтобы ступень не выбиралась вслепую.
export function difficultyHint(value) {
  const step = difficultyOf(value);
  const money = step.money === 1 ? "деньги героя как есть"
    : step.money === 0 ? "без денег на старте"
      : `деньги на старте ×${step.money}`;
  return `опыт ×${step.xp} · ${money}`;
}
