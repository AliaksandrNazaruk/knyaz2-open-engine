# -*- coding: utf-8 -*-
"""
Реестр локаций: канон и его продолжение.

НОМЕР ЛОКАЦИИ РАВЕН НОМЕРУ КАРТЫ. В клетке карты мира под локацию отведён
один байт, и по нему же грузится карта: `enterHere` в клиенте передаёт
`cell & 0xFF` прямо как номер карты. Проверяется на самом каноне — локация
19 «Черный Бор» это карта 19, локация 33 «Борье» это карта 33.

Отсюда всё остальное. Канонные таблицы, у которых индекс — этот номер,
кончаются рано: имена (0x4616D4) и значки (0x4615CC) держат по 44 записи,
прибытия (0x460028) и постоянный свет (0x4617B0) — по 55. Локация проекта
идёт за ними, и всё про неё — имя, значок, клетка на карте мира, место
прибытия — приходит из `project/locations.json`.

Байт клетки ограничивает номера сверху: 255. Правило «150 + номер у донора»
укладывает все 90 донорских карт в 151…249.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from konung2.worldmap import LOCATION_SLOTS, MARKER_COUNT

#: Где лежит реестр относительно каталога проекта.
REGISTRY = Path("locations.json")

#: Канон владеет номерами до этого включительно: столько записей в таблицах
#: имён и значков. Дальше начинается проект.
CANON_LAST = MARKER_COUNT - 1

#: Выше не залезть: под локацию в клетке карты мира отведён один байт.
MAX_NUMBER = 0xFF

#: Необязательное поле ``replaces``: номер КАНОННОЙ локации, чью клетку
#: запись забирает себе. Нужно там, где обе игры описывают ОДНО И ТО ЖЕ
#: место мира: Чёрный Бор стоит в «Крови Титанов» и в «Продолжении легенды»
#: на одной клетке (17, 30) — сдвиг донорской карты мира приводит его туда
#: точь-в-точь. Клетка одна, байт под локацию один, и войти можно только в
#: одну из двух карт. Какую — это решение проекта, и оно должно быть
#: НАПИСАНО: без ``replaces`` сборка падает на «клетка уже занята».
REPLACES = "replaces"

#: Необязательное поле ``revealed``: снять с клетки канонный флаг «скрыта».
#: Шесть канонных локаций и две засады лежат в сетке со флагом 0x80, и их
#: значка нет, пока сюжет не вызовет открытие (VA 0x436908, у нас
#: ``openLocation``). Остальные 33 начинают с нуля: значок появляется, когда
#: отряд подойдёт. Проектная карта, занявшая скрытую клетку, наследует и
#: флаг — и остаётся недостижимой навсегда, если открывающего разговора у
#: этого героя нет. Поле выключает наследство: локация встаёт на общих
#: правах со всеми, туман по-прежнему свой.
REVEALED = "revealed"

#: Необязательное поле значка ``game``: из чьего INTERF.RES взят его номер.
#: Нет поля — канон, ``"legend"`` — донор. Двадцать одна локация проекта
#: несёт номер из донорской записи локации (+0x08), и шесть из них в канонном
#: листе означают ДРУГУЮ картинку; номер 265 у канона это и вовсе портрет —
#: лица идут с 261, поэтому на карте мира появлялось лицо.
MARKER_GAME = "game"
LEGEND = "legend"
CANON = "canon"
GAMES = frozenset({LEGEND, CANON})

#: Обязательные поля записи. Без любого из них локация выйдет калекой:
#: без клетки её нет на карте мира, без прибытия отряд встанет в угол карты.
#:
#: ЗНАЧОК ОБЯЗАН БЫТЬ НАЗВАН, НО МОЖЕТ БЫТЬ ПУСТЫМ (null). Локация без
#: значка законна и есть у обеих игр: наши морские 26/27 и его «Капище
#: Вотана» с «Лесом у Кирингхольма» стоят в сетке, но на карте не рисуются —
#: в них входят выходом с соседней карты или сюжетом, а клетка нужна лишь
#: точкой выхода «на глобальную». Ключ остаётся обязательным нарочно:
#: пустой значок должен быть РЕШЕНИЕМ, а не забытым полем. Выдумывать
#: спрайт локации, у которой его нет в данных, — враньё; так у «Леса у
#: Кирингхольма» появился значок 256, которого в его игре не существует.
REQUIRED = ("number", "name", "cell", "marker", "arrival")


def registry(project_dir: str | Path) -> list[dict[str, Any]]:
    """Локации проекта. Нет файла — пустой список, это законное состояние."""
    path = Path(project_dir) / REGISTRY
    if not path.is_file():
        return []
    document = json.loads(path.read_text(encoding="utf-8"))
    entries = document.get("locations", [])
    seen: set[int] = set()
    for entry in entries:
        missing = [key for key in REQUIRED if key not in entry]
        if missing:
            raise ValueError(f"{path}: у локации {entry.get('number')} "
                             f"нет полей {missing}")
        number = int(entry["number"])
        if not CANON_LAST < number <= MAX_NUMBER:
            raise ValueError(
                f"{path}: номер {number} вне проектного диапазона "
                f"{CANON_LAST + 1}…{MAX_NUMBER}. До {CANON_LAST} включительно "
                f"владеет канон, выше {MAX_NUMBER} не лезет байт клетки")
        if number in seen:
            raise ValueError(f"{path}: номер {number} объявлен дважды")
        seen.add(number)
        if len(entry["cell"]) != 2:
            raise ValueError(f"{path}: у локации {number} клетка не парой чисел")
        marker = entry["marker"]
        # Номер спрайта без банка ничего не значит: у локаций донора он взят
        # из ЕГО записи и указывает в ЕГО INTERF.RES. Одинаковые номера в двух
        # играх — разные картинки: канонный 265 это портрет (лица идут с 261),
        # донорский 265 — значок лагеря. Опечатка в банке молча вернула бы нас
        # к канону и снова нарисовала лицо на карте мира, поэтому падаем.
        if marker is not None and marker.get(MARKER_GAME, CANON) not in GAMES:
            raise ValueError(
                f"{path}: у локации {number} значок объявлен из игры "
                f"{marker[MARKER_GAME]!r}, а известны только {sorted(GAMES)}")
        replaces = entry.get(REPLACES)
        if replaces is not None and not 0 < int(replaces) <= CANON_LAST:
            raise ValueError(
                f"{path}: локация {number} объявила захват клетки локации "
                f"{replaces}, а вытеснять можно только канонную (1…{CANON_LAST})")
    return entries


def names(canon_names: list[str], entries: list[dict[str, Any]]) -> list[str]:
    """Имена локаций: канонные, дополненные проектными.

    Список, а не словарь: клиент берёт имя как `names[номер]`, и дырки
    заполняются пустыми строками. Канонные записи не трогаются — реестр
    просто не может назвать номер из канонного диапазона.
    """
    if not entries:
        return list(canon_names)
    out = list(canon_names)
    highest = max(int(entry["number"]) for entry in entries)
    out.extend([""] * (highest + 1 - len(out)))
    for entry in entries:
        out[int(entry["number"])] = str(entry["name"])
    return out


def markers(canon_markers: dict[str, Any],
            entries: list[dict[str, Any]]) -> dict[str, Any]:
    """Значки локаций: канонные плюс проектные, ключ — номер строкой.

    Запись с ``marker: null`` номера в словарь не кладёт — клиент рисует
    только то, что в словаре есть, и локация остаётся невидимой точкой
    сетки, как канонные морские бои.
    """
    out = dict(canon_markers)
    for entry in entries:
        if entry["marker"] is not None:
            out[str(entry["number"])] = dict(entry["marker"])
    return out


def arrivals(canon_arrivals: dict[str, Any],
             entries: list[dict[str, Any]]) -> dict[str, Any]:
    """Куда встаёт отряд, войдя на карту (VA 0x436430)."""
    out = dict(canon_arrivals)
    for entry in entries:
        place = entry["arrival"]
        out[str(entry["number"])] = {"row": int(place["row"]),
                                     "col": int(place["col"])}
    return out


def stamp(grid: list[list[int]], walk: list[list[int]],
          entries: list[dict[str, Any]], land_bit: int,
          sea_bit: int = 2, hidden_bit: int = 0) -> list[list[int]]:
    """Проставить номера локаций в клетки карты мира.

    Возвращает новую сетку: исходную не портим, её читают и другие.

    Номер занимает младший байт клетки, флаги знания — старший, и старший
    трогается ровно одним способом: полем ``revealed`` (см. `REVEALED`).

    Проверок три, и каждая ловит локацию, до которой нельзя дойти:
    клетка должна быть внутри сетки, быть проходимой и быть свободной.
    Локация на нарисованном море или поверх канонной — это не «странно
    выглядит», а недостижимое место, и узнать об этом надо при сборке.

    ЗАХВАТ КАНОННОЙ КЛЕТКИ ЗАКОНЕН, НО ТОЛЬКО ЗАЯВЛЕННЫЙ. Две игры описывают
    один мир, и одно место в нём бывает у обеих: Чёрный Бор канона и Чёрный
    Бор донора приходятся на одну клетку. Занять её может лишь одна карта,
    и запись обязана назвать ту, которую вытесняет, — ``"replaces": 19``.
    Чужой номер без спроса не затирается: так ловится настоящий промах,
    когда донорская клетка случайно легла на канонную деревню.

    МОРСКАЯ ЛОКАЦИЯ ЗАКОННА, НО ТОЛЬКО ЗАЯВЛЕННАЯ. У «Продолжения легенды»
    три «Боя с морскими разбойниками» стоят на воде, и это правильно: туда
    приплывают, а не приходят. Но проверку на сушу из-за них ослаблять
    нельзя — ею же ловятся настоящие промахи (его Капище Вотана и Священный
    утёс попали на нарисованное море). Поэтому вода разрешается только с
    явным ``"sea": true`` в записи: случайно так не выйдет.
    """
    out = [row[:] for row in grid]
    rows, cols = len(out), len(out[0]) if out else 0
    for entry in entries:
        number = int(entry["number"])
        row, col = (int(value) for value in entry["cell"])
        if not (0 <= row < rows and 0 <= col < cols):
            raise ValueError(f"локация {number}: клетка ({row},{col}) вне "
                             f"сетки {cols}x{rows}")
        by_sea = bool(entry.get("sea"))
        reachable = walk[row][col] & (sea_bit if by_sea else land_bit)
        if not reachable:
            what = "не море" if by_sea else "не суша"
            how = ("" if by_sea else
                   "; если туда приплывают, а не приходят — "
                   "поставьте в записи \"sea\": true")
            raise ValueError(f"локация {number}: клетка ({row},{col}) {what} "
                             f"— дойти до неё будет нельзя{how}")
        taken = out[row][col] & 0xFF
        replaces = entry.get(REPLACES)
        if replaces is not None and taken != replaces:
            # Заявка, которая ничего не вытесняет, — след прошлой раскладки.
            # Молчать нельзя: клетку могли передвинуть, и тогда обе локации
            # разъехались по карте мира, а заметит это только игрок.
            raise ValueError(f"локация {number}: объявлен захват клетки "
                             f"локации {replaces}, но в ({row},{col}) её нет "
                             f"({'пусто' if not taken else taken})")
        if taken and taken != number and taken != replaces:
            how = ("" if replaces is None else
                   f"; в записи объявлен захват локации {replaces}, "
                   f"а в клетке стоит {taken}")
            raise ValueError(f"локация {number}: клетка ({row},{col}) уже "
                             f"занята локацией {taken}{how}")
        out[row][col] = (out[row][col] & ~0xFF) | number
        if entry.get(REVEALED):
            if not hidden_bit:
                raise ValueError(
                    f"локация {number}: заявлено снятие флага «скрыта», а "
                    f"самого флага сборке не передали — правка ничего бы не "
                    f"сделала, и локация осталась бы невидимой")
            out[row][col] &= ~(hidden_bit << 24)
    return out


def canon_instead(entries: list[dict[str, Any]]) -> dict[str, int]:
    """Донорская локация -> канонная, чью клетку она заняла.

    Под локацию в клетке отведён ОДИН БАЙТ (движок иначе не умеет), поэтому
    две игры делят одно место мира: донорский Чёрный Бор сел на клетку
    канонного, объявив ``"replaces": 19``. Раньше значок вёл в донорский у
    всех, и канонный герой приходил в чужую деревню — тестер это и записал:
    «нет Велиславны, есть Ярополк, не Кровь Титанов канон».

    Байт остаётся один, а выбор делает клиент: канонному герою по этой
    таблице отдаётся канонный номер, донорскому — тот, что стоит в клетке.
    Это то же правило «дома читаешь свой мир», что уже применено к деревням
    и отрядам.
    """
    return {str(entry["number"]): int(entry[REPLACES])
            for entry in entries if entry.get(REPLACES) is not None}


def slots_needed(entries: list[dict[str, Any]]) -> int:
    """Сколько ячеек «локация открыта» понадобится (у движка их 55)."""
    highest = max((int(entry["number"]) for entry in entries), default=0)
    return max(LOCATION_SLOTS, highest + 1)
