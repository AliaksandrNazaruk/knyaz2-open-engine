# -*- coding: utf-8 -*-
"""Чистота клиента: мусору не дают заводиться заново.

Три средства в `tools/` ищут три вида хлама, и каждое уже нашло настоящий:

* ``dead_exports.js`` — экспорт без единого потребителя (нашлось четырнадцать);
* ``idle_calls.js`` — функцию зовут, а работы в ней нет (нашлась
  ``renderBrightCuts``, оставшаяся пустой после сведения выреза силуэта);
* ``write_only_fields.js`` — поле пишут, а читать некому (нашёлся счётчик
  ``waitTalk``, которого и в движке нет).

ПОРОГ, А НЕ НОЛЬ. Держать ноль нельзя: часть находок законна и остаётся
намеренно — ``clockReset`` зовёт стенд, ``selectUnit`` контрактный тест,
``roam`` ждёт непереносённый ИИ юнитов. Поэтому тест сторожит ЧИСЛО: расти
ему нельзя, убывать можно, и при убыли он же напомнит опустить порог.

Так уборка перестаёт быть разовой: новый мёртвый экспорт валит сборку в тот
же день, а не через полгода, когда его уже страшно трогать.
"""
from __future__ import annotations

import pathlib
import re
import shutil
import subprocess
import unittest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]

#: Сколько находок считается нормой сегодня. Каждая цифра — остаток, который
#: разобран руками и оставлен сознательно; их разбор лежит в сообщениях
#: коммитов 1edde85, 382654c и ad7fb61.
ПОРОГИ = {
    "dead_exports.js": 6,        # стенды, тесты и соседние модули
    "idle_calls.js": 0,          # пустышек не осталось
    # свойства DOM и Blender плюс roam; CSS-свойства style.* из
    # editor_live.js (alignContent, alignSelf, borderColor, borderRadius,
    # boxShadow, flexWrap, gridAutoRows, lineHeight, textDecoration,
    # transformOrigin): их «читает» браузер. Порог ходит вслед за
    # холстом: поле пака сперва просто грузится (растёт), потом
    # начинает рисоваться (падает) — так нашлись невидимые клады.
    # +1 — dataset.lv: им помечены свои вставки в макет, а читаются они
    # СЕЛЕКТОРОМ [data-lv="…"], которого средство не видит. Число ходит
    # вслед за холстом и вёрсткой: свойства style.* то появляются, то
    # уходят, когда правку берёт на себя браузер. 51 — панель клетки 1d
    # (borderRadius/lineHeight у чекбоксов); 52 — значок сборки 1h
    # (borderColor). Обратно 51: прозвище жителя (nick_id) перестало быть
    # полем-в-никуда — gametool.py писал его годами, а читать стало
    # некому лишь потому, что мы нигде не разбирали запись обратно;
    # теперь его отдаёт gamefile.map_units и выбирает редактор.
    #: 52-е поле — `fontWeight`: подсветка выбранного режима
    #: «Ставить/Снимать» на экране проходимости. Она выглядела
    #: декоративной — работала, но красил её макет, и «Ставить»
    #: была тёмной всегда. Как и соседние lineHeight,
    #: textDecoration, transformOrigin — это запись css-свойства,
    #: читать его обратно незачем.
    #: снова 50: с уходом строки-указателя чтение boxShadow исчезло,
    #: поле опять только пишется (мигание рамки больше не нужно).
    #: 50: ещё одно поле стало читаемым после доводки экрана «Кладов»
    #: (взведение кучи читает то, что раньше только писалось).
    #: После перевода имён редактора на латиницу таких полей стало
#: МЕНЬШЕ: часть кириллических «полей» была вовсе не полями, а
#: локальными именами, и детектор их больше не путает.
#: Прежнее 53-е — `gridAutoRows` на гриде карт. Запись как была, так и
    #: есть; детектор стал приписывать её файлу после того, как поиск
    #: зон переехал в контракт ЗОНЫ и локальные имена сменились. Это
    #: css-свойство, читать его обратно незачем — как lineHeight,
    #: textDecoration и fontWeight рядом.
    "write_only_fields.js": 50,
}


class ClientHygieneTest(unittest.TestCase):
    """Числа хлама не растут."""

    def прогнать(self, средство: str) -> int:
        node = shutil.which("node")
        if not node:
            self.skipTest("node не найден — средство не запустить")
        готово = subprocess.run(
            [node, f"tools/{средство}"], cwd=КОРЕНЬ,
            capture_output=True, text=True, encoding="utf-8", errors="replace")
        self.assertEqual(готово.returncode, 0,
                         f"{средство} не отработало: {готово.stderr[:400]}")
        #: Последняя строка вида «… : ЧИСЛО» — итог средства.
        числа = re.findall(r":\s*(\d+)\s*$", готово.stdout.strip(), re.M)
        return int(числа[-1]) if числа else 0

    def test_dead_exports_do_not_grow(self) -> None:
        self.проверить("dead_exports.js", "экспортов без потребителя")

    def test_idle_calls_do_not_grow(self) -> None:
        self.проверить("idle_calls.js", "пустышек")

    def test_write_only_fields_do_not_grow(self) -> None:
        self.проверить("write_only_fields.js", "полей, которые пишут и не читают")

    def проверить(self, средство: str, чего: str) -> None:
        сейчас = self.прогнать(средство)
        порог = ПОРОГИ[средство]
        self.assertLessEqual(
            сейчас, порог,
            f"{чего} стало больше: было {порог}, стало {сейчас}. "
            f"Разберите новое и уберите — либо, если находка законна, "
            f"поднимите порог в ПОРОГИ и объясните почему.")
        if сейчас < порог:
            self.fail(
                f"{чего} стало меньше: было {порог}, стало {сейчас}. "
                f"Опустите порог в ПОРОГИ — иначе он перестанет сторожить.")


if __name__ == "__main__":
    unittest.main()
