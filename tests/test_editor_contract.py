"""Контракт «макет ↔ живой слой» редактора.

ПОЧЕМУ ЭТОТ ФАЙЛ ОТДЕЛЬНЫЙ. Прежние тесты редактора проверяют, что в
исходнике есть нужные подстроки: 155 штук, 428 проверок. Они не способны
увидеть ни кнопку без подсветки, ни две стрелки, ведущие вперёд, ни
каталог, уехавший в полоску шириной 56 точек, — то есть ничего из того,
чем редактор оказался дырявым. Здесь проверяется не текст, а СВЯЗНОСТЬ
контракта: что таблица зон, экраны и селфчек говорят об одном и том же.

Поведение экранов проверяет живой прогон в браузере
(``await редактор.селфчек({ карта: 63 })``) — он открывает каждый экран
и смотрит, смонтированы ли блоки. Здесь же стережём то, что можно
проверить без браузера, чтобы контракт не разъехался между заходами.
"""
from __future__ import annotations

import json
import re
import subprocess
import unittest
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЖИВОСТЬ = КОРЕНЬ / "knyaz2" / "web" / "static" / "editor_live.js"


def живость() -> str:
    return ЖИВОСТЬ.read_text(encoding="utf-8")


def ключи_зон(текст: str) -> list[str]:
    """Ключи из таблицы ЗОНЫ — по строкам вида ``"имя": { экран:``."""
    начало = текст.index("const ZONES = {")
    конец = текст.index("\n};", начало)
    кусок = текст[начало:конец]
    return re.findall(r'^\s*"([^"]+)":\s*\{\s*экран:', кусок, re.M)


def экраны_зон(текст: str) -> dict[str, str]:
    начало = текст.index("const ZONES = {")
    конец = текст.index("\n};", начало)
    кусок = текст[начало:конец]
    return dict(re.findall(r'^\s*"([^"]+)":\s*\{\s*экран:\s*"([^"]+)"',
                           кусок, re.M))


class EditorContractTest(unittest.TestCase):
    """Связность контракта зон, экранов и селфчека."""

    def test_every_zone_names_a_real_screen(self) -> None:
        """Зона указывает на экран, который в редакторе есть.

        Опечатка в номере экрана раньше не стоила ничего: зона просто не
        находилась, а на её месте оставался макет — и это выглядело
        рабочим экраном.
        """
        текст = живость()
        таблица = экраны_зон(текст)
        self.assertGreaterEqual(len(таблица), 8)
        жизни = set(re.findall(r'"(1[a-z])":\s*screen1[a-z]', текст))
        self.assertGreaterEqual(len(жизни), 9, "таблица экранов не разобралась")
        for ключ, экран in таблица.items():
            self.assertIn(экран, жизни,
                          f"зона «{ключ}» указывает на экран {экран}, "
                          f"которого нет среди жизней")

    def test_zone_is_the_only_way_to_find_a_list(self) -> None:
        """Списки ищутся ТОЛЬКО через контракт, а не по месту.

        Догадки «возьми узел с наибольшим числом детей уже 480 точек»
        были разбросаны по экранам. Одна из них брала пустую полоску
        шириной 56 точек — и весь каталог объектов уезжал в неё. Теперь
        как искать сказано один раз, в ЗОНАХ.
        """
        текст = живость()
        #: ИМЯ ПЕРЕМЕННОЙ В ТЕСТЕ НЕ ЗАКРЕПЛЯЕМ. Проверки стояли на
        #: дословном «зонаОдинРаз(карточка,» — и рассыпались, едва имена
        #: перевели на латиницу. Тест обязан стеречь ПРАВИЛО, а не буквы:
        #: важно, что зона берётся через контракт и ровно один раз.
        прямые = re.findall(r'зонаОдинРаз\(\w+,\s*"([^"]+)"', текст)
        self.assertEqual(
            прямые, [],
            f"поиск зоны мимо контракта: {прямые} — заведите запись в ЗОНЫ "
            f"и зовите зона(карточка, ключ)")
        for ключ in ключи_зон(текст):
            вызовов = len(re.findall(
                r'(?:зона|zoneOf)\(\w+,\s*"' + re.escape(ключ) + r'"\)', текст))
            self.assertEqual(вызовов, 1,
                             f"зона «{ключ}» берётся {вызовов} раз, нужно один")

    def test_selfcheck_reads_the_same_contract(self) -> None:
        """Селфчек выводит ожидания из ЗОН, а не держит свою копию.

        Сперва он держал собственную таблицу «экран → метки». Это два
        списка одного знания, и разъезжаются они молча: добавил зону —
        проверять её никто не станет.
        """
        текст = живость()
        self.assertIn("function selfcheckExpectations()", текст)
        self.assertRegex(текст,
                         r"for \(const \[\w+, \w+\] of Object\.entries\(ZONES\)\)")
        self.assertNotIn("const SELFCHECK_WANTS", текст)
        #: органы сверх зон объявлены явно и не пустуют
        self.assertIn("const SELFCHECK_EXTRA = {", текст)
        for метка in ("кисть-область", "тип-воды"):
            self.assertIn(f'"{метка}"', текст)

    def test_editor_has_no_dead_code(self) -> None:
        """Ни функций без ссылок, ни полей, которые пишут и не читают.

        Замер делает `tools/editor_dead.js`. Сам инструмент дважды соврал,
        пока его не поправили: считал `жизнь1d` мёртвой (её зовут по
        имени из таблицы, а не вызовом) и принимал `===` за присваивание.
        Инструмент, которому верят, обязан быть честным первым.
        """
        готово = subprocess.run(
            ["node", str(КОРЕНЬ / "tools" / "editor_dead.js")],
            capture_output=True, text=True, encoding="utf-8", cwd=КОРЕНЬ)
        self.assertEqual(готово.returncode, 0, готово.stderr)
        вывод = готово.stdout
        мёртвых = re.search(r"без единого вызова: (\d+)", вывод)
        полей = re.search(r"не читают: (\d+)", вывод)
        self.assertIsNotNone(мёртвых, вывод)
        self.assertIsNotNone(полей, вывод)
        self.assertEqual(int(мёртвых.group(1)), 0,
                         f"появился мёртвый код:\n{вывод}")
        self.assertEqual(int(полей.group(1)), 0,
                         f"появилось поле, которое пишут и не читают:\n{вывод}")

    def test_geometric_guesses_do_not_multiply(self) -> None:
        """Догадок ПО ГЕОМЕТРИИ не становится больше.

        Сперва порог стоял на всех догадках разом — и первая же честная
        правка его сломала: чтобы погасить чужой инвентарь в панели кучи,
        понадобился поиск по заголовку «Состав · items». Порог был не
        про то.

        Опасна только одна порода. Поиск по ТОЧНОМУ ТЕКСТУ промахивается
        заметно: не нашлось — значит не нашлось, и промах уходит в
        плашку. А мерки ПО ГЕОМЕТРИИ («уже 470 точек», «больше всех
        детей», «такой-то фон») молча берут соседний узел и выдают его за
        нужный: так каталог объектов уехал в полоску шириной 56 точек, а
        бестиарий остался жить на «Деревне» и «Отрядах».

        Их десять. Новый экран должен объявлять зону в контракте ЗОНЫ, а
        не заводить очередную мерку на глаз.
        """
        готово = subprocess.run(
            ["node", str(КОРЕНЬ / "tools" / "editor_dead.js")],
            capture_output=True, text=True, encoding="utf-8", cwd=КОРЕНЬ)
        числа = re.search(r"догадок по геометрии: сравнений ширины (\d+), "
                          r"поиска по фону (\d+), всего (\d+)", готово.stdout)
        self.assertIsNotNone(числа, готово.stdout)
        self.assertLessEqual(
            int(числа.group(3)), 10,
            f"мерок по геометрии стало {числа.group(3)} — заведите зону в "
            f"контракте ЗОНЫ вместо новой мерки на глаз")


if __name__ == "__main__":
    unittest.main()
