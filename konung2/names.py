def slug(n):
    """Имя папки карты в проекте: 19 -> '19_chernyy_bor'."""
    tr = {
        'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e', 'ж': 'zh',
        'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
        'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'c',
        'ч': 'ch', 'ш': 'sh', 'щ': 'sch', 'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e',
        'ю': 'yu', 'я': 'ya', ' ': '_', '-': '_',
    }
    name = LOCATIONS.get(n, '') or 'free_slot'
    out = ''.join(tr.get(c, tr.get(c.lower(), c if c.isalnum() else '')) for c in name.lower())
    while '__' in out:
        out = out.replace('__', '_')
    return f"{n:02d}_{out.strip('_')}"
