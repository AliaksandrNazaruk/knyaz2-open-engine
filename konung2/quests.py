#: Вместимость отряда — не константа: девять это лишь потолок
#: (VA 0x434CD0). Считается из Харизмы вожака, байт unit+0xCC.
PARTY_CAPACITY_FROM = 0xCC
PARTY_CAPACITY_SHIFT, PARTY_CAPACITY_MAX = 4, 9
#: Цена в реплике названа десятками (VA 0x435097).
MONEY_STEP = 10
#: Облик игрока — байт unit+0xFC (VA 0x434EA0).
BODY_AT = 0xFC
#: Должности поселения: пять слов с +0x3D0 (VA 0x43552B).
OFFICIALS_AT, OFFICIALS_COUNT = 0x3D0, 5


def party_capacity(charisma: int) -> int:
    """Сколько человек влезет в отряд при такой Харизме (VA 0x434CD0)."""
    return min(PARTY_CAPACITY_MAX, (charisma >> PARTY_CAPACITY_SHIFT) + 1)


def handler_table(data: bytes | None = None) -> list[dict]:
    """Таблица обработчиков разговора: адрес и что о нём известно."""
    from .exetables import va_to_foff
    if data is None:
        with open(game_file('konung2.exe'), 'rb') as stream:
            data = stream.read()
    offset = va_to_foff(HANDLERS_VA)
    table = []
    for index in range(HANDLERS):
        address = struct.unpack_from('<I', data, offset + index * 4)[0]
        name, expected, note = HANDLER_NAMES.get(index, (None, None, ""))
        table.append({
            'index': index, 'address': address,
            'name': name, 'note': note,
            'verified': expected is not None and expected == address,
        })
    return table
