# -*- coding: utf-8 -*-
"""
QUESTS.RES ↔ проект. Диалоги, журнал квестов и структура диалоговых деревьев.

Формат восстановлен по загрузчику VA 0x43DAC6 — семь секций подряд, 469 000 байт:

    0x00000  0xFA00   узлы диалогов, 16000 dword      -> в память 0x632D90
    0x0FA00  0xBB80   таблица фраз, 6000 x 8          -> 0x642790
    0x1B580  0x5DC0   данные фраз А, 6000 dword       -> 0x64E310
    0x21340  0x5DC0   данные фраз Б, 6000 dword       -> 0x6540D0
    0x27100  0x0258   корни диалогов, 150 dword       -> 0x659E90
    0x27358  0x4B000  строки CP866 через \\0           -> 0x65A0E8
    0x72358  0x004B0  300 dword состояний квестов     -> 0x6A50E8

Пять первых таблиц — структура диалогов (кто что говорит и куда ведут
ответы); в проекте они пока хранятся одним двоичным куском, чтобы сборка
шла байт-в-байт. Тексты и состояния квестов редактируются как текст и JSON.

Встречается урезанный вариант файла на 308 400 байт — в нём только две
последние секции. Игра с таким файлом падает при любом разговоре с NPC:
движок читает текст как таблицы указателей.

В строках попадаются скрипт-команды движка, например
``MAP=14,34,54,0x00004FFF`` — сделать клетку (34,54) карты 14 пустой.
"""
import json
import os
import struct

from .paths import game_file

#: (имя, смещение, размер) пяти таблиц структуры диалогов
DIALOG_TABLES = [
    ('dialog_nodes', 0x00000, 0xFA00),
    ('phrase_table', 0x0FA00, 0xBB80),
    ('phrase_a',     0x1B580, 0x5DC0),
    ('phrase_b',     0x21340, 0x5DC0),
    ('dialog_roots', 0x27100, 0x00258),
]
DIALOG_SIZE = 0x27358            # суммарно 160 600 байт
BLOB_OFF, BLOB_SIZE = 0x27358, 0x4B000
STATE_OFF, STATE_SIZE = 0x72358, 0x4B0
TOTAL = 469000
TRUNCATED = 308400               # обрезанный вариант: только блоб + состояния
ENCODING = 'cp866'


class QuestsFile:
    def __init__(self, data):
        if len(data) == TOTAL:
            self.dialogs = bytes(data[:DIALOG_SIZE])
            self.blob = bytes(data[BLOB_OFF:BLOB_OFF + BLOB_SIZE])
            self.state = bytes(data[STATE_OFF:STATE_OFF + STATE_SIZE])
        elif len(data) == TRUNCATED:
            raise ValueError(
                f'QUESTS.RES обрезан: {len(data)} байт вместо {TOTAL}. '
                'Отсутствуют пять таблиц структуры диалогов — с таким файлом '
                'игра падает при любом разговоре. Нужен оригинал из дистрибутива.')
        else:
            raise ValueError(f'неизвестный размер QUESTS.RES: {len(data)}')

    @classmethod
    def from_game(cls):
        with open(game_file('QUESTS.RES'), 'rb') as f:
            return cls(f.read())

    # --- содержимое -----------------------------------------------------
    def strings(self):
        return [p.decode(ENCODING, errors='replace') for p in self.blob.split(b'\0')]

    def table(self, name):
        for n, off, size in DIALOG_TABLES:
            if n == name:
                return self.dialogs[off:off + size]
        raise KeyError(name)

    # --- проект ---------------------------------------------------------
    def unpack(self, textdir):
        os.makedirs(textdir, exist_ok=True)
        parts = self.strings()
        with open(os.path.join(textdir, 'quests.txt'), 'w', encoding='utf-8') as f:
            f.write('# Тексты «Князь 2». Формат: <номер><TAB><текст>\n')
            f.write('# Номера менять НЕЛЬЗЯ — на них ссылается таблица фраз.\n')
            f.write(f'# Лимит: суммарно {BLOB_SIZE} байт в CP866.\n')
            for i, s in enumerate(parts):
                if s:
                    f.write(f'{i}\t{s}\n')
        state = list(struct.unpack(f'<{STATE_SIZE//4}I', self.state))
        with open(os.path.join(textdir, 'quests_state.json'), 'w', encoding='utf-8') as f:
            json.dump({'quest_state': state}, f, ensure_ascii=False, indent=1)
        with open(os.path.join(textdir, 'dialogs.bin'), 'wb') as f:
            f.write(self.dialogs)
        return len(parts)

    @classmethod
    def pack(cls, textdir):
        rows = {}
        with open(os.path.join(textdir, 'quests.txt'), encoding='utf-8') as f:
            for line in f:
                line = line.rstrip('\n')
                if not line or line.startswith('#'):
                    continue
                num, _, text = line.partition('\t')
                rows[int(num)] = text.encode(ENCODING, errors='replace')
        n = max(rows) + 1 if rows else 0
        blob = b'\0'.join(rows.get(i, b'') for i in range(n))
        if len(blob) > BLOB_SIZE:
            raise ValueError(f'тексты не влезают: {len(blob)} > {BLOB_SIZE}, '
                             f'сократите на {len(blob)-BLOB_SIZE} байт')
        blob = blob.ljust(BLOB_SIZE, b'\0')
        with open(os.path.join(textdir, 'quests_state.json'), encoding='utf-8') as f:
            state = json.load(f)['quest_state']
        with open(os.path.join(textdir, 'dialogs.bin'), 'rb') as f:
            dialogs = f.read()
        assert len(dialogs) == DIALOG_SIZE, f'dialogs.bin: {len(dialogs)} != {DIALOG_SIZE}'
        return cls(dialogs + blob + struct.pack(f'<{len(state)}I', *state))

    def to_bytes(self):
        return self.dialogs + self.blob + self.state

    def save(self, path):
        with open(path, 'wb') as f:
            f.write(self.to_bytes())


# --- структура диалогов ---------------------------------------------------
#
# Разобрана по коду разговора: вход VA 0x4369A0, показ узла VA 0x00436478,
# исполнитель действий VA 0x435F44, вычислитель условий VA 0x436664.
#
#     корни    0x659E90   u16 на номер диалога; номер лежит в юните (+0xF2)
#     узлы     0x632D90   по 8 байт: i16 действие, следующий, условие, фраза
#     фразы    0x642790   по 8 байт: голос и смещение строки в блоке текстов
#     действия 0x64E310   список dword до 0x7FFFFFFF
#     условия  0x6540D0   такой же список, но со сборкой И/ИЛИ
#
# Узел с фразой -1 — не реплика, а строка перехода: движок идёт по таким,
# пока не найдёт ту, чьё условие выполнено, и прыгает по её «следующему».
# Узел с фразой — реплика собеседника, а ВАРИАНТЫ ОТВЕТА лежат сразу за ней
# подряд, пока у записей есть фраза; запись без фразы список закрывает.
#
# Команда действия и условия — одно и то же слово:
#
#     биты 0x3F000000 = 0x3000000  вызвать обработчик [0x462E90 + (слово & 0xFF)]
#                                  с аргументом (слово >> 8) & 0xFFFF
#     биты 0x3F000000 = 0x4000000  бит (слово & 0xFF) в байте собеседника +0xF7
#     биты 0x3F000000 = 0x5000000  старший бит состояния квеста [номер]
#     бит  0x80000000              в действии «поставить», в условии «не»
#     бит  0x40000000              в условии: И с предыдущим (иначе ИЛИ)
NODE_STRIDE = 8
#: Узлов ровно столько, сколько влезает в первую таблицу (0xFA00 / 8).
NODE_COUNT = 0xFA00 // NODE_STRIDE
PHRASE_STRIDE = 8
CMD_HANDLER, CMD_UNIT_FLAG, CMD_QUEST = 0x3000000, 0x4000000, 0x5000000
CMD_KIND_MASK, CMD_SET, CMD_AND = 0x3F000000, 0x80000000, 0x40000000
CMD_END = 0x7FFFFFFF


def _commands(data, offset, index):
    """Список команд действия или условия, начиная с указанного номера."""
    out = []
    position = offset + index * 4
    while position + 4 <= len(data):
        word = struct.unpack_from('<I', data, position)[0]
        if word == CMD_END:
            break
        kind = word & CMD_KIND_MASK
        command = {'raw': word, 'set': bool(word & CMD_SET), 'and': bool(word & CMD_AND)}
        if kind == CMD_HANDLER:
            # Аргумент движок передаёт ЗНАКОВЫМ: (short)(word >> 8) с
            # расширением до int (VA 0x435F44 и 0x436664). Поэтому 0xFFFF
            # приходит в обработчик как -1, а не как 65535.
            argument = (word >> 8) & 0xFFFF
            if argument >= 0x8000:
                argument -= 0x10000
            command.update(kind='handler', handler=word & 0xFF,
                           argument=argument)
        elif kind == CMD_UNIT_FLAG:
            command.update(kind='unit_flag', bit=word & 0xFF)
        elif kind == CMD_QUEST:
            command.update(kind='quest', quest=word & 0xFFFF)
        else:
            command.update(kind='unknown')
        out.append(command)
        position += 4
    return out


class Dialogs:
    """Диалоги QUESTS.RES: корни, узлы, фразы, действия и условия."""

    def __init__(self, data: bytes) -> None:
        self.data = data

    @classmethod
    def from_game(cls) -> 'Dialogs':
        with open(game_file('QUESTS.RES'), 'rb') as stream:
            return cls(stream.read())

    def root(self, dialog: int) -> int:
        return struct.unpack_from('<H', self.data, 0x27100 + dialog * 2)[0]

    def node(self, index: int) -> dict:
        action, following, condition, phrase = struct.unpack_from(
            '<4h', self.data, index * NODE_STRIDE)
        return {'index': index, 'action': action, 'next': following,
                'condition': condition, 'phrase': phrase}

    def phrase(self, index: int) -> dict:
        voice, offset = struct.unpack_from('<2i', self.data, 0x0FA00 + index * PHRASE_STRIDE)
        start = BLOB_OFF + offset
        end = self.data.index(b'\0', start)
        return {'voice': voice,
                'text': self.data[start:end].decode(ENCODING, 'replace')}

    def actions(self, index: int) -> list:
        return [] if index < 0 else _commands(self.data, 0x1B580, index)

    def conditions(self, index: int) -> list:
        return [] if index < 0 else _commands(self.data, 0x21340, index)

    def branches(self, index: int) -> list[dict]:
        """Развилка: подряд идущие записи «условие -> куда».

        Движок идёт по записям, пока у них ЕСТЬ условие и оно НЕ выполнено
        (VA 0x436478: ``while (условие != -1 && !выполнено) шаг += 8``).
        Смотрит он только на условие: запись без условия закрывает развилку,
        а вот поле ``next`` проверяется уже у ПОДОШЕДШЕЙ записи, поэтому
        непрошедшую запись с ``next = -1`` движок просто перешагивает.
        """
        out = []
        step = index
        while True:
            node = self.node(step)
            out.append({'node': step, 'condition': self.conditions(node['condition']),
                        'always': node['condition'] < 0, 'next': node['next']})
            if node['condition'] < 0:
                break
            step += 1
            if step >= NODE_COUNT:      # дальше узлов нет, начинается таблица фраз
                break
        return out

    def line(self, index: int) -> dict | None:
        """Реплика по номеру узла — без учёта условий, первой веткой."""
        seen = set()
        while 0 <= index and index not in seen:
            seen.add(index)
            node = self.node(index)
            if node['phrase'] != -1:
                options = []
                step = index + 1
                while True:
                    following = self.node(step)
                    if following['phrase'] == -1:
                        break
                    options.append({
                        'node': step,
                        'text': self.phrase(following['phrase'])['text'],
                        'next': following['next'],
                        'condition': self.conditions(following['condition']),
                        'actions': self.actions(following['action']),
                    })
                    step += 1
                return {'node': index,
                        'text': self.phrase(node['phrase'])['text'],
                        'actions': self.actions(node['action']),
                        'options': options}
            index = node['next']
        return None

    def tree(self, number: int, limit: int = 96) -> dict:
        """Весь диалог графом: реплики и развилки, как их видит движок.

        Условия здесь не считаются — они уезжают в клиент, потому что часть
        из них спрашивает мир: жив ли отряд события, стоит ли постройка.
        """
        nodes: dict[int, dict] = {}
        queue = [self.root(number)]
        while queue and len(nodes) < limit:
            index = queue.pop(0)
            if index < 0 or index in nodes:
                continue
            node = self.node(index)
            if node['phrase'] != -1:
                options = []
                step = index + 1
                while True:
                    following = self.node(step)
                    if following['phrase'] == -1:
                        break
                    answer = self.phrase(following['phrase'])
                    options.append({
                        'node': step,
                        'text': answer['text'],
                        # у реплик игрока озвучки в данных нет, но поле то же
                        **({'voice': answer['voice']} if answer['voice'] > 0 else {}),
                        'next': following['next'],
                        'condition': self.conditions(following['condition']),
                        'actions': self.actions(following['action']),
                    })
                    step += 1
                spoken = self.phrase(node['phrase'])
                nodes[index] = {'kind': 'line', 'node': index,
                                'text': spoken['text'],
                                # номер записи voices.res — реплика NPC звучит
                                # при входе в узел (VA 0x436478)
                                **({'voice': spoken['voice']}
                                   if spoken['voice'] > 0 else {}),
                                'actions': self.actions(node['action']),
                                'options': options}
                queue.extend(option['next'] for option in options)
            else:
                branches = self.branches(index)
                nodes[index] = {'kind': 'branch', 'node': index, 'branches': branches}
                queue.extend(branch['next'] for branch in branches)
        return {'number': number, 'root': self.root(number),
                'nodes': [nodes[key] for key in sorted(nodes)]}

    def dialog(self, number: int, limit: int = 64) -> list:
        """Весь диалог: реплики, до которых достают ответы."""
        start = self.line(self.root(number))
        if start is None:
            return []
        lines, queue, seen = [], [start], {start['node']}
        while queue and len(lines) < limit:
            line = queue.pop(0)
            lines.append(line)
            for option in line['options']:
                if option['next'] < 0:
                    continue
                following = self.line(option['next'])
                if following and following['node'] not in seen:
                    seen.add(following['node'])
                    queue.append(following)
        return lines


