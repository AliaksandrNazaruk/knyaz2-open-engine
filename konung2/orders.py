# -*- coding: utf-8 -*-
"""
Приказы, выбор отряда и щелчки по миру.

Разобрано по коду, ничего не подобрано.

БАЙТ ПРИКАЗА unit+0x16 делится пополам. Младшая половина — ЧТО ЮНИТ
ДЕЛАЕТ СЕЙЧАС, старшая — в каком он режиме; выдача приказа (VA 0x416574)
меняет только младшую, старшую сохраняет:

    unit+0x16 = вид | (unit+0x16 & 0xF0)
    unit+0x13 = строка цели, unit+0x15 = столбец цели

Номер цели в ``unit+0x10`` (юнит как есть, объект как −1−n, ноль — нет
цели) сама 0x416574 НЕ пишет: его ставят вызывающие. Щелчок по цели
(VA 0x421690) кладёт номер, а раздача приказа отряду (VA 0x4240BC) его
обнуляет.

Виды (младшая половина), какие встретились:

    0   приказа нет, юнит думает сам (VA 0x4111E8)
    1   к цели: подойти и бить
    2   подойти и ЗАГОВОРИТЬ
    3   подойти и ОБЫСКАТЬ (кучу или лежачего)
    6   просто идти в клетку

Старшая половина — не число, а БИТЫ, и движок проверяет их поодиночке:

    0x10  держаться за вожаком
    0x20  идёт по приказу игрока
    0x40  особое (поджог)

Проверку видно в «юнит думает» (VA 0x4111E8): когда действия нет и юнит
не занят приказом, движок смотрит ровно ``unit+0x16 & 0x10`` и, если бит
стоит, зовёт VA 0x41209C — «догнать вожака». Догонять начинают, отойдя на
ДЕСЯТЬ клеток в отряде игрока и на ПЯТЬ в чужом.

Отсюда знакомые числа: 0x10 — «идёт за вожаком», 0x30 — то же плюс бит
приказа, 0x26 — «иду, куда велели», 0x22 — «подойти и заговорить», 0x61 —
«поджечь постройку».

ПРИКАЗ ДОШЁЛ (VA 0x4115AC). Когда юнит стоит на клетке назначения, движок
смотрит младшую половину:

    2   если цель ближе семи строк И четырёх столбцов — начать разговор
        (VA 0x4369A0), иначе идти дальше
    3   куча или лежачий: опознать вещи, забрать деньги, открыть обмен

ВЫБОР ОТРЯДА (VA 0x423F80). Список 0x840B94, до девяти юнитов:

    без клавиши-добавки  список очищается, в нём остаётся один
    с добавкой           юнит дописывается, и список СОРТИРУЕТСЯ

Добавку включает клавиша (VA 0x438A00 ставит 0x849608 по нажатию и
снимает по отпусканию).

ПРИКАЗ ВСЕМ ВЫБРАННЫМ (VA 0x4240BC): каждому сбрасывается цель, ставится
флаг +0x19|0x40 и выдаётся приказ в ту же клетку.

ЩЕЛЧОК ПО МИРУ (VA 0x421690, ветка кода 0) — порядок проверок такой:

    открыто окно             ничего
    курсор «рука»            приказ 3 всем выбранным
    несём вещь               положить её на землю в клетке несущего
    под мышью СВОЙ           ВЫБРАТЬ его (заменить список или дополнить)
    под мышью ЛЕЖАЧИЙ        разговор с ним, если его номер меньше восьми
                             и мы не в бою, иначе просто подойти
    под мышью ЧУЖОЙ
        есть разговор и мы не в бою   приказ 2 «подойти и заговорить»
        иначе                          приказы всем выбранным
    под мышью КУЧА           идти к ней (цель отрицательная)
    пусто                    приказ 6 всем выбранным
"""
from __future__ import annotations

from .paths import game_file

#: Байт приказа и его половины.
ORDER_AT = 0x16
ORDER_KIND_MASK, ORDER_MODE_MASK = 0x0F, 0xF0
#: Виды приказа (младшая половина).
KIND_NONE, KIND_TARGET, KIND_TALK, KIND_TAKE, KIND_GO = 0, 1, 2, 3, 6
#: СТОЙ, С ТОБОЙ ГОВОРЯТ. Приказ 0x0C выдаётся не игроком, а СОБЕСЕДНИКУ, и
#: ровно в тот миг, когда игрок отдал приказ 2 (VA 0x410A08, случай 2):
#:
#:     цель+0x16 = 0x0C      весь байт целиком, старшая половина стирается
#:     цель+0xF5 = 100       счётчик
#:     цель+0x19 &= ~0x04    у не-твари снимается «оружие выбрано»
#:
#: Пока приказ держится (VA 0x413894, случай 0x0C), юнит только
#: поворачивается к игроку — своих дел не берёт вовсе: рассудок 0x4111E8
#: зовётся лишь при НУЛЕВОЙ младшей половине, а тут она 0x0C. Условие
#: удержания одно из двух: открыто окно разговора и это его собеседник,
#: либо у игрока приказ 2 нацелен на этого юнита. Отпало — 0x416E24
#: снимает приказ, и юнит идёт своей дорогой дальше.
KIND_WAIT_TALK = 0x0C
KIND_NAMES = {
    KIND_NONE: "сам", KIND_TARGET: "к цели", KIND_TALK: "заговорить",
    KIND_TAKE: "обыскать", KIND_GO: "идти",
    KIND_WAIT_TALK: "стоять, с ним говорят",
}
#: Старшая половина — биты, а не число.
MODE_FOLLOW, MODE_PLAYER, MODE_SPECIAL = 0x10, 0x20, 0x40
#: Знакомые сочетания целиком.
ORDER_FOLLOW = MODE_FOLLOW | KIND_NONE             # 0x10 идёт за вожаком
ORDER_FOLLOW_ORDERED = MODE_FOLLOW | MODE_PLAYER   # 0x30 он же, после приказа
ORDER_GO = MODE_PLAYER | KIND_GO                   # 0x26 иду, куда велели
ORDER_TALK = MODE_PLAYER | KIND_TALK               # 0x22 подойти и заговорить
ORDER_BURN = MODE_SPECIAL | MODE_PLAYER | KIND_TARGET   # 0x61 поджечь
#: Догонять вожака начинают, отойдя на столько клеток (VA 0x41209C).
FOLLOW_CELLS_OWN, FOLLOW_CELLS_OTHER = 10, 5
#: Дальше этого спутник не идёт, а БЕЖИТ — поднимается бит 0x80 (VA 0x4120C6).
FOLLOW_RUN_CELLS = 15

#: ТАБЛИЦА ПОСТРОЕНИЯ (VA 0x461BC4). Спутник идёт НЕ в клетку вожака, а
#: в одну из двенадцати клеток вокруг него:
#:
#:     строка  = i8 [0x461BC4 + место*2 + чётность*0xC0 + направление*0x18]
#:     столбец = i8 [0x461BC5 + место*2 + чётность*0xC0 + направление*0x18]
#:
#: ``направление`` — от СПУТНИКА к вожаку (VA 0x43B7D0), ``чётность`` —
#: чётность строки вожака (ряды сетки смещены), ``место`` — 0…11.
#: Перебор идёт с ослучайненного начала (``rand() % 12``) по кругу; клетка
#: годится, если она в пределах карты, проходима и лежит по ту же сторону
#: стены постройки, что и вожак (бит 0x200000 клетки совпадает). Не нашлось
#: за двенадцать — направление сдвигается, и так до четырёх заходов.
FORMATION_VA = 0x461BC4
FORMATION_SLOTS, FORMATION_DIRECTIONS, FORMATION_TRIES = 12, 8, 4
#: Бит клетки «внутри постройки», по которому сверяются вожак и место.
FORMATION_INSIDE_BIT = 0x200000


def formation(data: bytes | None = None) -> list[list[list[tuple[int, int]]]]:
    """Таблица построения: [чётность][направление][место] -> (drow, dcol)."""
    import struct as _struct
    from .exetables import va_to_foff
    if data is None:
        with open(game_file("konung2.exe"), "rb") as stream:
            data = stream.read()
    out = []
    for parity in range(2):
        rows = []
        for direction in range(FORMATION_DIRECTIONS):
            slots = []
            for slot in range(FORMATION_SLOTS):
                at = va_to_foff(FORMATION_VA + slot * 2 +
                                parity * 0xC0 + direction * 0x18)
                slots.append(tuple(_struct.unpack_from("<2b", data, at)))
            rows.append(slots)
        out.append(rows)
    return out

#: Цель приказа и клетка назначения.
TARGET_AT, DEST_ROW_AT, DEST_COL_AT = 0x10, 0x13, 0x15
#: Флаг «идёт по приказу» — другой байт.
BUSY_AT, BUSY_BIT = 0x19, 0x40
#: СПИСОК ВЫБОРА (0x840B94, девять указателей на записи юнитов).
#:
#: Держится отсортированным ПО АДРЕСУ записи, то есть по номеру слота
#: (VA 0x423F80, пузырёк). Пустым он не бывает: сняв последнего, движок
#: кладёт туда самого игрока (VA 0x43AE5C) — герой выбран всегда, когда
#: больше некого.
SELECTION_VA, SELECTION_MAX = 0x840B94, 9
#: Клавиша-добавка к выбору (скан-код 0x10, VA 0x438A34): с ней щелчок
#: ДОПОЛНЯЕТ выбор, а по уже выбранному — СНИМАЕТ его (VA 0x4217D8).
#: Без неё щелчок заменяет весь список одним юнитом.
ADD_FLAG_VA, ADD_SCANCODE = 0x849608, 0x10

#: КРУГ ПОД ВЫБРАННЫМ (VA 0x425DB4, строки 41…52). Рисуется ДО тела и
#: только когда сошлось всё сразу: юнит не зверь (``unit+0x1A & 0x40``
#: снят), режим 0x849628 выключен, сторона юнита совпадает со стороной
#: игрока (``unit+0x1B``) и юнит есть в списке выбора (VA 0x415040).
#:
#: Спрайт — из INTERF.RES, и он же ПОКАЗЫВАЕТ ЗДОРОВЬЕ: движок выбирает
#: один из трёх по ``unit+0x4E``. Это не тень: тень юнита рисуется другим
#: проходом, а круг появляется только под выбранными.
SELECTION_HEALTH_STEPS = (0x191, 0x321)
SELECTION_SPRITES = {"hurt": 172, "half": 126, "whole": 178}
#: Палитра круга — поле палитры записи 178 (VA 0x6B2BAC), индекс 1.
SELECTION_PALETTE = 1
#: Тот же круг рисуется списком в проходе земли (VA 0x424FD8) и в проходе
#: содержимого постройки (VA 0x424514), но там он пропускается, если у
#: клетки юнита поднят бит 0x20.
SELECTION_CELL_SKIP_BIT = 0x20

#: РАМКА МЫШЬЮ (VA 0x42A6E0). Тянется по экрану и ловит юнитов ОТРЯДА
#: ИГРОКА — перебор идёт непрерывным срезом от записи игрока на длину
#: отряда, а сравниваются экранные координаты юнита (+0x36 и +0x3E).
#: Правила: мёртвых (флаг 0x80) и типы 3, 0x0B, 0x0C рамка не берёт;
#: без клавиши-добавки список сперва очищается, но если рамка не поймала
#: НИКОГО, прежний выбор возвращается — пустым щелчком выбор не сбросить.
BAND_SKIP_FLAG_AT, BAND_SKIP_FLAG = 0x1A, 0x80
BAND_SKIP_TYPES = (3, 0x0B, 0x0C)
BAND_X_AT, BAND_Y_AT = 0x36, 0x3E

#: ПАНЕЛЬ ПЕРСОНАЖА идёт за ПЕРВЫМ ВЫБРАННЫМ (VA 0x4292DC и 0x423088):
#: указатель 0x849514 — это тот юнит, чьи вещи, гнёзда, вес и
#: характеристики показывает экран 3. Нет выбранных — показывается сам
#: игрок. Повторный щелчок по уже выбранному юниту открывает и закрывает
#: этот экран (VA 0x4217E8).
PANEL_UNIT_VA, PANEL_SCREEN = 0x849514, 3
#: Разговор начинается, только если цель ближе этого (VA 0x4115AC).
TALK_ROWS, TALK_COLS = 7, 4
#: Лежачий заговорит, если его номер разговора меньше этого.
CORPSE_TALK_BELOW = 8


def order_byte(kind: int, mode: int) -> int:
    """Собрать байт приказа: биты режима плюс вид действия."""
    return (mode & ORDER_MODE_MASK) | (kind & ORDER_KIND_MASK)


def order_kind(byte: int) -> int:
    """Что юнит делает сейчас."""
    return byte & ORDER_KIND_MASK


def order_mode(byte: int) -> int:
    """Биты режима как есть."""
    return byte & ORDER_MODE_MASK


def follows(byte: int) -> bool:
    """Держится ли юнит за вожаком (VA 0x4111E8 смотрит этот бит)."""
    return bool(byte & MODE_FOLLOW)


def follow_distance(own_side: bool) -> int:
    """С какого расстояния спутник начинает догонять вожака."""
    return FOLLOW_CELLS_OWN if own_side else FOLLOW_CELLS_OTHER


def give(byte: int, kind: int) -> int:
    """Выдать приказ: младшая половина меняется, старшая остаётся."""
    return (kind & ORDER_KIND_MASK) | (byte & ORDER_MODE_MASK)


def object_target(number: int) -> int:
    """Объект как цель приказа: движок держит их отрицательными."""
    return -1 - number


def can_talk(rows_apart: int, cols_apart: int) -> bool:
    """Достаточно ли близко подошли, чтобы заговорить."""
    return abs(rows_apart) < TALK_ROWS and abs(cols_apart) < TALK_COLS


