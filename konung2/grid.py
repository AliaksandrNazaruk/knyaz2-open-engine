# -*- coding: utf-8 -*-
"""
Сетка карты: занятость клеток и ссылки на объекты.

Сетка лежит в `.KN2` со смещения 0x09600 и грузится по адресу 0x5662BC:
256 строк по 160 клеток, клетка — одно 32-битное слово. Адрес клетки
движок считает как ``0x5662BC + row * 0x280 + col * 4`` (VA 0x410158).

Разбор полей снят с кода:

======  =========  ==============================================
Биты    Маска      Содержимое
======  =========  ==============================================
0…11    0x0000FFF  проходимость/занятость (VA 0x44146C): 0 — свободно,
                   0xFFF — стена/вода/пустота (непроходимо), иначе —
                   ссылка на юнита 0x7B3C08 (шаг 0x100), рантайм
14      0x0004000  флаг
15      0x0008000  занято постройкой
16…20   0x01F0000  индекс статического объекта карты + 1: по нему
                   прячется крыша, когда на клетке стоит член отряда
                   (VA 0x428282, массив 0x8A72F4 на 30 объектов)
21      0x0200000  флаг
22      0x0400000  флаг
======  =========  ==============================================

Биты 12, 13 и 23…31 в файлах карт не встречаются ни разу (проверено на
всех 52 картах: 2 129 920 клеток, объединение битов 0x007FCFFF).
В файлах младшие 12 бит — только 0x000 или 0xFFF; ссылки на юнитов движок
дописывает в рантайме.

Клетка — кирпич 58 × 16 экранных точек; нечётные ряды начинаются с x=0,
чётные сдвинуты на 29. Преобразования сняты с кода движка:

* клетка → якорь юнита (VA 0x43B974):
  ``x = col*58 + (row нечёт ? 29 : 58)``, ``y = row*16 + 16``
* пиксель → клетка (VA 0x43B9B0):
  ``row = y >> 4``, ``col = (row нечёт ? x : x - 29) // 58``

Наложение на отрисованную карту 19 подтверждает: клетки 0xFFF обнимают
подошвы стен с разрывом в дверных проёмах, клетки с индексом здания
выстилают интерьеры.
"""
from __future__ import annotations

import struct

GRID_AT = 0x09600
GRID_ROWS, GRID_COLS, GRID_STRIDE = 256, 160, 0x280
CELL_W, CELL_H = 58, 16

REF_MASK = 0x00000FFF        # ссылка на запись; 0xFFF и 0 — пусто
REF_EMPTY = 0x00000FFF
#: Проходимость (VA 0x4414A7, поиск пути): клетка свободна, когда младшие
#: 12 бит нулевые. Стены и вода несут 0xFFF, клетки внутри построек — нули,
#: поэтому в здания можно заходить.
PASSABLE_MASK = 0x00000FFF
#: Единственный бит клетки, чью роль подтверждает код: по нему стрела
#: считает, что попала в стену или постройку (VA 0x41FDD0).
SOLID = 0x00004000
FLAG_4000 = SOLID            # прежнее безымянное имя того же бита
#: Бит 15 в коде нигде не проверяется: маска 0xF000 в 0x4171CC лишь
#: сохраняет биты 12…15 скопом при очистке ссылки. «Занято постройкой» —
#: наше наблюдение по файлам карт, а не разбор кода, поэтому и имя такое.
BUILT_BY_MAPS = 0x00008000
BUILT = BUILT_BY_MAPS
UNIT_MASK, UNIT_SHIFT = 0x001F0000, 16
FLAG_200000 = 0x00200000
FLAG_400000 = 0x00400000

#: Записи, на которые ссылаются младшие 12 бит (VA 0x4108A6).
CELL_REF_ARRAY, CELL_REF_STRIDE = 0x7B3C08, 0x100


def cell(kn2, row, col):
    """Сырое слово клетки."""
    return struct.unpack_from('<I', kn2.data, GRID_AT + row * GRID_STRIDE + col * 4)[0]


def set_cell(kn2, row, col, value):
    struct.pack_into('<I', kn2.data, GRID_AT + row * GRID_STRIDE + col * 4, value)


def decode(value):
    """Разложить клетку на поля."""
    ref = value & REF_MASK
    return {
        'ref': None if ref in (0, REF_EMPTY) else ref,
        'built': bool(value & BUILT),
        'unit': (value & UNIT_MASK) >> UNIT_SHIFT or None,
        'flags': [name for name, bit in (('0x4000', FLAG_4000),
                                         ('0x200000', FLAG_200000),
                                         ('0x400000', FLAG_400000))
                  if value & bit],
        'raw': value,
    }


def cells(kn2, only_used=True):
    """Клетки карты: (row, col, разбор)."""
    out = []
    for row in range(GRID_ROWS):
        base = GRID_AT + row * GRID_STRIDE
        for col in range(GRID_COLS):
            value = struct.unpack_from('<I', kn2.data, base + col * 4)[0]
            if value or not only_used:
                out.append((row, col, decode(value)))
    return out


def cell_position(row, col):
    """Якорь юнита в клетке (точка ног), формула движка VA 0x43B974."""
    return col * CELL_W + (29 if row & 1 else CELL_W), row * CELL_H + CELL_H


def pixel_to_cell(x, y):
    """Клетка по мировой точке (VA 0x43B9B0).

    Клетки — РОМБЫ, а не кирпичи, поэтому первая оценка ``y / 16`` и
    ``x / 58`` только называет полосу. Дальше движок берёт вертикальное
    ребро этой полосы и двумя перекрёстными произведениями проверяет,
    не лежит ли точка за диагональю; если лежит — строка уменьшается, а
    столбец сдвигается по чётности строки. В конце строка зажимается в
    0…255, столбец в 0…159.

    Все деления целочисленные с усечением К НУЛЮ, как в C: при ``x < 29``
    столбец выходит нулевым, а не −1.
    """
    x, y = int(x), int(y)
    row = int(y / CELL_H)
    if row & 1:
        col = int(x / CELL_W)
        edge = col * CELL_W + 29
    else:
        col = int((x - 29) / CELL_W)
        edge = col * CELL_W + CELL_W
    bottom = (row + 1) * CELL_H
    top = bottom - CELL_H
    if x == edge:
        pass                                    # ровно на ребре — как есть
    elif x < edge:
        if (y - top) * (x - (edge - 29)) < (edge - x) * (bottom - y):
            row -= 1
            if not row & 1:
                col -= 1
    else:
        if (bottom - y) * (edge - x) < (x - (edge + 29)) * (y - top):
            if not row & 1:
                col += 1                        # столбец правит СТАРАЯ чётность
            row -= 1
    row = min(max(row, 0), GRID_ROWS - 1)
    col = min(max(col, 0), GRID_COLS - 1)
    return row, col


def occupied(kn2):
    """Клетки, занятые постройками."""
    return [(r, c) for r, c, v in cells(kn2) if v['built']]
