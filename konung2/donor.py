#: Владыка, ключи, Амулет Дракона, Доспех Дракона…) — и они уезжают в
#: хвост канонного каталога. Хвост влезает в байт класса записи предмета:
#: 211 + 15 = 226 < 256.
PROJECT_ITEM_BASE = 211


def item_class_map() -> dict[int, int]:
    """Его номер класса предмета -> наш.

    Совпавшее имя — канонный номер; своих кладём в хвост по возрастанию
    ЕГО номера, чтобы соответствие не плавало между сборками.

    Имена в каталогах ПОВТОРЯЮТСЯ и означают разные предметы: «Груз для
    купца» это классы за 1000 и за 2500, «Ожерелье» — за 80 и за 230, и
    так в обеих играх. Счёт одноимённых при этом РАЗНЫЙ (наших «Грузов»
    три, его — два), поэтому голый порядковый номер спаривает чужие: его
    груз за 1000 лёг бы на наш за 500. В одноимённой группе сначала
    забираются точные пары по цене и весу, остаток — по порядку, лишние
    его — в хвост как собственные.
    """
    from collections import defaultdict

    from .items import read_items
    from .profile import LEGEND
    ours: dict[str, list] = defaultdict(list)
    for item in read_items():
        ours[item.name.lower()].append(item)
    theirs: dict[str, list] = defaultdict(list)
    for record in read_items(profile=LEGEND):
        theirs[record.name.lower()].append(record)

    out: dict[int, int] = {}
    spare = []
    for key, group in theirs.items():
        candidates = list(ours.get(key) or [])
        rest = []
        for record in group:
            exact = next((item for item in candidates
                          if item.price == record.price
                          and item.weight == record.weight), None)
            if exact is not None:
                out[record.index] = exact.index
                candidates.remove(exact)
            else:
                rest.append(record)
        for record in rest:
            if candidates:
                out[record.index] = candidates.pop(0).index
            else:
                spare.append(record.index)
    for tail, his_index in enumerate(sorted(spare), start=PROJECT_ITEM_BASE):
        out[his_index] = tail
    return out


def shared_class_kinds() -> dict[int, int]:
    """Виды записей ОБЩИХ классов по его мирам — под НАШИМИ номерами.

    Канонный `gamefile.class_kinds` знает вид только у классов, которые
    лежат вещами в канонных мирах; у прочих (Финики, Нож для
    жертвоприношений, Неразменный пятак, Сын Луны, Грамота на корабль…)
    вид остаётся пустым, и применение спотыкается о гейт группы 11.
    Донорские миры несут этим классам вид — доносим его переводом
    номеров, НЕ перекрывая канонный (setdefault на приёмнике).
    """
    import struct as _struct

    from .gamefile import T_ITEMS
    from .profile import LEGEND

    class_map = item_class_map()
    kinds: dict[int, int] = {}
    for world in range(9):
        try:
            with open(LEGEND.file(f"GAME.{world}"), "rb") as stream:
                data = stream.read()
        except OSError:
            continue
        for index in range(1, T_ITEMS.count):
            record = data[T_ITEMS.offset + index * T_ITEMS.size:][:T_ITEMS.size]
            if len(record) < 4 or record[0] == 0xFF:
                continue
            our_num = class_map.get(record[3])
            if our_num is not None and our_num < PROJECT_ITEM_BASE:
                kinds.setdefault(our_num, record[0])
    return kinds


def tail_classes() -> list[tuple]:
    """Собственные классы донора под нашими хвостовыми номерами (211+).

    Возвращает пары «запись класса с НАШИМ номером, вид записи» — для
    каталога пака: деревья разговоров уже зовут эти классы переведёнными
    номерами (Браслет Владыка, три Ключа, Книга Мудрых, Амулет и Доспех
    Дракона…), и без записей класса «дать»/«есть»/«забрать» молчат.

    Вид записи — по его вещам миров, тем же правилом, что канонный
    ``gamefile.class_kinds``: байт +0 записи предмета, класс в +3. Миров
    у донора больше шести — читается столько его GAME.x, сколько есть.
    """
    from dataclasses import replace

    from .gamefile import T_ITEMS
    from .items import read_items
    from .profile import LEGEND

    class_map = item_class_map()
    by_index = {item.index: item for item in read_items(profile=LEGEND)}
    kinds: dict[int, int] = {}
    for world in range(9):
        try:
            with open(LEGEND.file(f"GAME.{world}"), "rb") as stream:
                data = stream.read()
        except OSError:
            continue
        for index in range(1, T_ITEMS.count):
            record = data[T_ITEMS.offset + index * T_ITEMS.size:][:T_ITEMS.size]
            if len(record) < 4 or record[0] == 0xFF:
                continue
            kinds.setdefault(record[3], record[0])
    out = []
    for his, ours in sorted(class_map.items(), key=lambda pair: pair[1]):
        if ours < PROJECT_ITEM_BASE:
            continue
        rec_ = by_index.get(his)
        if rec_ is None:
            continue
        kind_v = kinds.get(his)
        # ОТСТУПЛЕНИЕ, И ОНО ПОМЕЧЕНО: «Браслет Владыка» (его класс 3)
        # лежит в его мирах видом 11 (сюжетное), но его же обработчик
        # «надето украшение класса» (0x4384B0) сверяет ПЯТЬ СЛОТОВ
        # УКРАШЕНИЙ — 148 проверок Грани Махкама требуют НОСИТЬ браслет.
        # Как вид 11 попадает в слот у донора — не разобрано (вероятно,
        # сюжет кладёт запись прямо в слот); у нас надевание идёт по
        # виду, поэтому браслету ставится вид «браслет» (7), как его же
        # Браслетам 66…68. Сверить живым донором при случае.
        if his == 3:
            kind_v = 7
        out.append((replace(rec_, index=ours), kind_v))
    return out


