def _nest_record(data: bytes, slot: int) -> bytes:
    import struct as _struct
    off, size = _struct.unpack_from("<II", data, slot * 8)
    return data[off:off + size]


def shared_nests() -> set[int]:
    """Гнёзда объектов, побайтно равные в обеих играх (30..509)."""
    from .paths import game_file
    ours = Path(game_file("OBJECTS.RES")).read_bytes()
    theirs = Path(donor_file("objects.res")).read_bytes()
    return {slot for slot in range(30, CANON_LAST_SLOT + 1)
            if _nest_record(ours, slot) == _nest_record(theirs, slot)}


def shared_palettes() -> set[int]:
    """Палитры, побайтно равные в обеих играх."""
    from .paths import game_file
    block = PALETTE_SLOTS * 512
    ours = Path(game_file("GRAPH.RES")).read_bytes()[:block]
    theirs = Path(donor_file("graph.res")).read_bytes()[:block]
    return {index for index in range(PALETTE_SLOTS)
            if ours[index * 512:(index + 1) * 512]
            == theirs[index * 512:(index + 1) * 512]}


def shared_tiles() -> set[int]:
    """Плитки земли, побайтно равные в обеих играх (0..CANON_LAST_TILE)."""
    from .graph import GraphRes
    from .paths import game_file

    ours = GraphRes(Path(game_file("GRAPH.RES")).read_bytes())
    theirs = graph()

    def body(source, tile: int) -> bytes | None:
        entry = source.tile_entry(tile)
        if not entry:
            return None
        off, size = entry
        return source.data[off:off + size]

    return {tile for tile in range(CANON_LAST_TILE + 1)
            if body(ours, tile) == body(theirs, tile)}

