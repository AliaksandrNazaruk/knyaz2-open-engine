#: НЕПРОХОДИМОСТЬ У ДОНОРА — ОДИН БИТ, А У НАС ДВЕНАДЦАТЬ.
#:
#: Наш формат держит её в младших 12 битах младшего слова клетки, и там
#: ровно одно значение: 0xFFF. То есть это флаг, записанный единицами, а не
#: число. Донор тот же флаг перенёс в бит 0x1000, а младшие двенадцать
#: обнулил: во всех 90 его картах нет НИ ОДНОЙ клетки с ненулевыми младшими
#: битами.
#:
#: Без перевода донорская карта приезжает без единой стены — герой ходит
#: насквозь, а «ближайшая проходимая клетка» оказывается любой непустой,
#: то есть и посреди дома. Ровно это и было видно в Дубках.
#:
#: Перевод снят с общей карты 19 «Черный Бор», которая есть в обеих играх:
#: флаг 0x1000 совпадает с нашей непроходимостью на 88.6% клеток, а весь
#: остаток объясняется тем, что у донора там достроена хижина знахаря и
#: занято на 1225 клеток больше.
DONOR_BLOCKED = 0x1000
CANON_BLOCKED = 0x0FFF

#: СТАРШИЕ ФЛАГИ КЛЕТКИ У ДОНОРА СДВИНУТЫ НА БИТ ВВЕРХ.
#:
#: Наши биты: 21 — «юнита рисует проход постройки» (маршрутная клетка),
#: 22 — «юнит статичной палитрой» (дневной интерьер). Донор держит те же
#: флаги в 22 и 23. Доказано на общем «Чёрном Боре» (наша 19 — его 19):
#: его бит 23 совпал с нашим 22 на всех 1055 клетках (100% в обе стороны),
#: его бит 22 — с нашим 21 на 378 клетках из 378 своих (остаток канона —
#: достроенная у донора хижина знахаря). Выше бита 23 во всех 90 его
#: картах пусто.
#:
#: Его СОБСТВЕННЫЙ бит 21 занят только на картах 4, 5 и 26 и нашего
#: смысла не несёт — без перевода он приезжал в пак ложными маршрутными
#: клетками, а настоящие терялись: на всех донорских деревнях routed был
#: пуст, юнит на пороге дома рисовался общим проходом сцены раньше самой
#: постройки, и пол ложился поверх него («захожу в казарму — и я под
#: полом»).
#: ПОЧЕМУ ФЛАГИ «СДВИНУТЫ»: У НЕГО ШИРЕ ПОЛЕ НОМЕРА ПОСТРОЙКИ.
#:
#: У канона номер занимает пять бит (16..20), и оттого построек на карте не
#: больше тридцати одной — больше и не бывало, у нас их максимум тринадцать.
#: У донора поле шестибитное (16..21), а флаги стоят следом, в 22 и 23. Это
#: не два разных наблюдения, а одно: флаги «выше на бит» ровно потому, что
#: номер «шире на бит».
#:
#: Замер по сырым картам: в его Кирингхольме по пяти битам находится 30
#: разных номеров, по шести — 58, и построек там ровно 58. На нашем Борье
#: наоборот: по пяти 10 при девяти постройках, по шести 20 — шестой бит у
#: нас занят флагом.
#:
#: ПЕРЕВОДИТЬ СТАРШЕЕ СЛОВО НЕЛЬЗЯ. Прежняя запись резала номер по 0x1F и
#: сдвигала флаги вниз: постройка 38 (0xE6) становилась постройкой 6
#: (0x66). На Кирингхольме так теряли клетки 29 построек из 58, в Тиграте
#: 21 из 47 — а без клеток крыша не прячется и юнит рисуется поверх дома.
#: Поэтому старшее слово остаётся ЕГО, а читается по его раскладке
#: (`konung2.world.model.LEGEND_CELLS`).
DONOR_CELL_OBJECT = 0x003F      # биты 16..21: номер объекта + 1
DONOR_CELL_ROUTED = 0x0040      # бит 22: юнита рисует проход постройки
DONOR_CELL_BRIGHT = 0x0080      # бит 23: юнит статичной палитрой


def to_canon_cells(raw: bytes) -> bytes:
    """Перевести клетки донорской карты: ТОЛЬКО проходимость.

    Старшее слово остаётся донорским — оно и не переводимо: шестибитный
    номер постройки в наши пять бит не влезает.
    """
    from .kn2 import GRID_H, GRID_ROW, GRID_W, SEC_GRID
    data = bytearray(raw)
    for row in range(GRID_H):
        for col in range(GRID_W):
            at = SEC_GRID[0] + row * GRID_ROW + col * 4
            low, high = struct.unpack_from("<HH", data, at)
            if low & DONOR_BLOCKED:
                low = (low & ~DONOR_BLOCKED) | CANON_BLOCKED
                struct.pack_into("<HH", data, at, low, high)
    return bytes(data)


def soft_cells(number: int) -> list[tuple[int, int]]:
    """Клетки, глухие ТОЛЬКО донорским битом 0x1000 (низ у него пуст).

    После перевода `to_canon_cells` они неотличимы от канонной стены
    0xFFF, а различие каноничное: его поисковик запрещает ШАГ на такую
    клетку (маска 0x1FFF в 0x4459F5), но канонный отказ «цель — стена»
    (низ == 0xFFF, снят с 0x441441) её НЕ ловит — поэтому оригинал
    доводит юнита до цели на глухой клетке (финиш волны не проверяется).
    Так стоит третья бочка Кирингхольма (куча 54, диалог 270). Пак несёт
    эти клетки списком `terrain.blocked_soft` — подмножеством blocked.
    """
    from .kn2 import GRID_H, GRID_ROW, GRID_W, SEC_GRID
    raw = Path(donor_file(f"{number}.kn2")).read_bytes()
    out = []
    for row in range(GRID_H):
        for col in range(GRID_W):
            at = SEC_GRID[0] + row * GRID_ROW + col * 4
            low, = struct.unpack_from("<H", raw, at)
            if low & DONOR_BLOCKED and not (low & CANON_BLOCKED):
                out.append((row, col))
    return out


def map_data(number: int, translate: bool = True) -> tuple[bytes, int]:
    """Карта донора в нашем формате и сколько записей обстановки сверх наших.

    ХВОСТ БОЛЬШЕ НЕ ОБРЕЗАЕТСЯ. Раньше карта резалась до MAP_SIZE, и вместе
    с хвостом пропадала обстановка построек с тридцатой по шестьдесят
    первую: в Кирингхольме 26 домов становились пустыми внутри, в Тиграте
    15, и семь сундуков теряли своё гнездо (номер постройки лежит в записи
    кучи, +0x09). Второе число — сколько таких записей ЗАНЯТО; оно
    осталось, чтобы перенос по-прежнему говорил, где карта крупнее нашей.

    ``translate=False`` отдаёт карту как есть — нужно, чтобы сравнивать
    донорские клетки с донорскими же.
    """
    raw = Path(donor_file(f"{number}.kn2")).read_bytes()
    return (to_canon_cells(raw) if translate else raw), extra_zones(raw)
