def sections(blob: bytes) -> list[tuple[str, int, int, int]]:
    """Секции PE из самого файла: имя, RVA, размер в файле, смещение.

    Наш ``exetables.py`` держит их константами, снятыми вручную. Разбор
    заголовка воспроизводит эти константы в точности (проверяется тестом),
    поэтому чужому файлу можно верить так же.
    """
    if blob[:2] != b"MZ":
        raise ValueError("не исполняемый файл: нет MZ")
    at = struct.unpack_from("<I", blob, 0x3C)[0]
    if blob[at:at + 4] != b"PE\0\0":
        raise ValueError(f"по 0x{at:X} нет подписи PE")
    count = struct.unpack_from("<H", blob, at + 6)[0]
    optional_size = struct.unpack_from("<H", blob, at + 20)[0]
    table = at + 24 + optional_size
    out = []
    for index in range(count):
        entry = table + index * 40
        name = blob[entry:entry + 8].rstrip(b"\0").decode("ascii", "replace")
        _, rva, raw_size, raw_at = struct.unpack_from("<IIII", blob, entry + 8)
        if raw_at and raw_size:
            out.append((name, rva, raw_size, raw_at))
    return out


class DonorExe:
    """Строковые таблицы чужого exe."""

    def __init__(self, blob: bytes) -> None:
        self.blob = blob
        self.sections = sections(blob)

    @classmethod
    def load(cls) -> "DonorExe":
        with open(donor_file(DONOR_EXE), "rb") as stream:
            return cls(stream.read())

    def va_to_foff(self, va: int) -> int | None:
        rva = va - IMAGE_BASE
        for _, section_rva, size, at in self.sections:
            if section_rva <= rva < section_rva + size:
                return at + (rva - section_rva)
        return None

    def string_at(self, va: int, limit: int = 120) -> str:
        """Строка по адресу; не строка — пустая. Служебные байты не пускаем."""
        if not IMAGE_BASE < va < IMAGE_BASE + 0x400000:
            return ""
        at = self.va_to_foff(va)
        if at is None:
            return ""
        end = self.blob.find(b"\0", at, at + limit)
        if end <= at:
            return ""
        raw = self.blob[at:end]
        if any(byte < 0x20 for byte in raw):
            return ""
        return raw.decode(ENCODING, "replace")

    def location_names(self) -> list[str]:
        """Названия локаций донора, индекс — номер локации."""
        return [self.string_at(struct.unpack_from(
                    "<I", self.blob,
                    DONOR_LOCATIONS_AT + index * DONOR_LOCATION_STRIDE)[0])
                for index in range(DONOR_LOCATION_COUNT)]

    def npc_names(self) -> list[str]:
        """Имена персонажей донора, индекс — номер вида."""
        return [self.string_at(struct.unpack_from(
                    "<I", self.blob, DONOR_NPC_NAMES_AT + index * 4)[0])
                for index in range(DONOR_NPC_NAME_COUNT)]


