# -*- coding: utf-8 -*-
"""
Постройки: стройка, пожар и зажигательные стрелы.

Разобрано по коду, ничего не подобрано.

СОСТОЯНИЕ ПОСТРОЙКИ — байт +1 её записи в поселении (запись восемь байт с
+0x18: вид, состояние, номер объекта карты словом, и счётчик словом по
+6). Это не «стоит / не стоит», а ступень лестницы:

    0, 1, 2   строится
    3         стоит
    4, 5      горит
    6         пепелище, а на следующем ходу место снова пустое

Что это именно лестница, видно по картинке: движок берёт её как
``спрайт вида + состояние`` (VA 0x4171CC), и в таблице видов каждому виду
отведено ровно семь подряд идущих номеров — кузницы 224, 231, 238, казармы
238, 245, 252, 259, колодцы 95, 102, 109.

ХОД СТРОЙКИ И ПОЖАРА (VA 0x41C944, тот же мировой такт, что грызёт
отравой). Для каждой постройки со счётчиком больше нуля:

    состояние < 3   счётчик минус один; на нуле состояние плюс один, и
                    если это ещё не 3, счётчик снова
                    ``срок постройки * 60 / число работников``
    состояние >= 3  то же самое, но шаг берётся из другого поля вида и на
                    число работников не делится: пожар не торопят
    состояние 6     место очищается (состояние 0) и снова ставится срок
                    постройки — деревня отстраивается заново

Работников считает та же функция; если отряд деревни в бою, их ноль и
стройка стоит. Вид 0xFF — место пустое, движок читает его как
отрицательный байт и пропускает.

МАСЛО (класс 87). Оно не про урон: движок требует, чтобы цель была
БОЕПРИПАСОМ (вид 0x0C), и ставит ему ноль в поле +0x02 записи —
то самое, где иначе лежит номер особого урона, а у чистых стрел 0xFF.
Этот ноль читают ровно два места, и оба — про прицел:

    VA 0x428B88  вид курсора: если у выбранного есть метательное,
                 боеприпас и он намаслен, над постройкой курсор особый
    VA 0x421690  щелчок: приказ 0x61 с ОТРИЦАТЕЛЬНОЙ целью, а
                 отрицательная цель — это номер объекта карты, взятый
                 как −1−n (VA 0x410A08 читает её так же)

ПОДЖОГ (VA 0x41FDD0). Стрела с такой целью летит в объект; на клетке со
стеной движок проверяет попадание по самой картинке объекта и, если
попал, ищет объект в списке построек поселения:

    с вероятностью 21 из 100:  состояние = 3, счётчик = 1

То есть горит не сразу: счётчик единица — и ближайший мировой такт
переводит постройку в состояние 4. Промахнувшаяся стрела ничего не
поджигает, зато деревня в любом случае поднимает тревогу против стороны
стрелка (VA 0x4159DC ставит флаги +0x49C).
"""
from __future__ import annotations

#: Запись постройки в поселении.
BUILDINGS_AT, BUILDING_ENTRY = 0x18, 8
SPECIAL_SLOTS = 7
KIND_AT, STATE_AT, OBJECT_AT, TIMER_AT = 0, 1, 2, 6
EMPTY_KIND = 0xFF

#: Лестница состояний.
STATE_BUILDING = (0, 1, 2)
STATE_READY = 3
STATE_BURNING = (4, 5)
STATE_ASHES = 6
STATE_SPRITES = 7

#: Пожар: попадание зажигательной стрелы поджигает не всегда.
#: «Строительные навыки» — навык 18: байт юнита +0xE4 при блоке навыков
#: с +0xD2. Максимум по отряду деревни считает VA 0x432C9C.
BUILD_SKILL = 18

IGNITE_CHANCE = 21
#: Поджог ставит счётчик в единицу — гореть начинает со следующего такта.
IGNITE_TIMER = 1
#: Срок постройки берётся из вида и делится на число работников.
BUILD_MINUTE = 60

#: Масло: класс зелья и что оно пишет в запись боеприпаса.
OIL_CLASS = 87
OIL_MARK_AT, OIL_MARK, OIL_CLEAN = 0x02, 0, 0xFF
#: Боеприпас — вид записи 0x0C.
AMMO_KIND = 0x0C
#: Приказ «поджечь»: младшая половина байта +0x16 та же, что у «идти к
#: цели», а цель отрицательная — номер объекта карты как −1−n.
ORDER_BURN = 0x61
#: Курсор над постройкой, когда есть чем поджечь (VA 0x428B88).
CURSOR_BURN = 4
#: Флаги тревоги поселения (VA 0x4159DC).
ALARM_FLAGS_AT = 0x49C


def object_target(number: int) -> int:
    """Номер объекта как цель юнита: движок держит их отрицательными."""
    return -1 - number


def target_object(target: int) -> int | None:
    """Обратно: какой объект имеет в виду отрицательная цель."""
    return None if target >= 0 else -1 - target


def sprite_of(kind: dict, state: int) -> int:
    """Картинка постройки: у каждого вида семь подряд, по одной на ступень."""
    return kind["sprite"] + max(0, min(STATE_SPRITES - 1, state))


#: КАЗНА ВЛАДЕНИЯ (VA 0x41D530…0x41D745, формула снята дизасмом). Раз в
#: 0x2760 единиц времени 0x84962C (|время − метка +0x14| > 0x275F) и только
#: при СНЯТОМ бите 0x10 в +0x49C в казну +0x10 капает доход:
#:
#:     round(богатство(+0x00) · 50 · sqrt(навык «Управление деревней»
#:           ГЕРОЯ, +0xE5) + жители·10 + 1)
#:
#: порезанный делителем из сетки «статус +0x49D × байт +0x4A0» (столбцы:
#: байт 0 / байт 1 / байт от двух; деление усечением к нулю):
#:
#:     статус 0:  /4  /2  /1
#:     статус 1:  /8  /4  /2
#:     статус 2:  /16 /8  /4
#:
#: Жители — численность отряда деревни (байт +0x1C записи отряда).
TREASURY_PERIOD = 0x2760
TREASURY_WEALTH_SCALE = 50
TREASURY_PER_PERSON = 10
TREASURY_BLOCK_BIT = 0x10
TREASURY_DIVIDERS = ((4, 2, 1), (8, 4, 2), (16, 8, 4))

#: МАСТЕРСКАЯ (VA 0x417BD8, зовётся мировым тактом 0x41C944 раз за тик).
#: Мастер — юнит из +0x3D6, его навык — «Кузнечное дело» (+0xE3). Видов
#: продукции 39: 0…2 — стрелы (классы 202…204, пачка 30), 3…4 — болты
#: (классы 206…207, пачка 30), 5…38 — снаряжение культуры старейшины
#: (класс = культура·34 + 100 + вид − 5). Порог доступности вида И
#: прочность откованного — колонка +0x08 его класса. Свободный вид с
#: порогом не выше навыка берётся в заказ, срок ПЕРВОГО заказа:
#:
#:     round(порог · 60 / sqrt(навык/10 + 1))            (0x417CF3: fsqrt)
#:
#: готовое ложится в счётчик вида (+0x44E), после отковки мастер растёт:
#: навык = round(sqrt(порог·2 + навык² + 10)), кап 100. Когда все
#: доступные виды в запасе, раздача жителям: жребий rand % 8 не меньше
#: порога сетки статусов (статус 1: 7/6/4 по байту +0x4A0; иначе 6/4/0),
#: и только пока на карте деревни нет живого отряда события (0x435214);
#: НЕ зверям (бит 0x40 породы); стрелы — в пустой боеприпас, снаряжение —
#: в слот вида, если пусто или защита класса хуже (старая вещь пропадает);
#: требования проверяет 0x418648. ВЫДАВ, движок тут же куёт то же самое:
#: сток вида обнуляется, и срок ПЕРЕЗАКАЗА считается ДРУГОЙ формулой —
#: единица прибавляется ПОСЛЕ корня (0x417F42 и 0x41802A):
#:
#:     round(прочность · 60 / (sqrt(навык/10) + 1))
#:
#: прочность — та же колонка +0x08 класса (числитель 0x45DAF8 = база
#: классовой таблицы 0x45DAF0 + 8).
WORKSHOP_GOODS = 39
WORKSHOP_AMMO_CLASSES = (202, 203, 204, 206, 207)
WORKSHOP_STACK = 30
WORKSHOP_CULTURE_BASE, WORKSHOP_CULTURE_STEP = 100, 34
