# -*- coding: utf-8 -*-
"""
Расстояние в клетках.

Движок меряет его одной функцией (VA 0x43B670), и меряет НЕ по прямой:

    a = |разница строк|;  b = |разница столбцов|
    берётся большее, и если меньшее больше единицы, к нему прибавляется
    единица

То есть это «ход королём» плюс поправка на диагональ. По этой мерке
считается всё: дальность удара и выстрела, зрение, догон вожака (десять
клеток своим, пять чужим) и близость для разговора.

Сетка карты вытянутая — столбец шире строки, — поэтому мерить пикселями
и делить на размер клетки нельзя: получится совсем другое число.
"""
from __future__ import annotations


def cell_range(row1: int, col1: int, row2: int, col2: int) -> int:
    """Расстояние в клетках так, как его считает движок."""
    rows = abs(row1 - row2)
    cols = abs(col1 - col2)
    if rows < cols:
        return cols + 1 if rows > 1 else cols
    return rows + 1 if cols > 1 else rows


def rules() -> dict:
    """Правило меры — для content pack."""
    return {"policy": "konung2_exe_0x43b670", "diagonal_bonus": 1}
