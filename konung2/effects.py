WISDOM_XP_SHIFT, WISDOM_XP_SCALE = 5, 100.0
WISDOM_XP_SCALE_VA = 0x450243

#: БАЙТ ``unit+0xF8`` — временный ЗНАКОВЫЙ бонус точности. Его читает одно
#: место движка: расчёт точности 0x41ADD8 прибавляет его, ПОКА тикает
#: ``unit+0x4A``. Пишут его сами зелья: Брага, Зелье, Эликсир и Вино кладут
#: ноль, и только Чистая слеза — ``round(sqrt(k) · 0.1)`` (0x41DDCF: fild k;
