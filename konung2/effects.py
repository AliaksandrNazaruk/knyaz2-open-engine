# -*- coding: utf-8 -*-
"""
Отрава и зелья.

Разобрано по коду, ничего не подобрано.

ЗАПИСЬ ПРЕДМЕТА. Отрава живёт не в классе, а в самом предмете: таблица
0x6F956C, по шестнадцать байт на запись.

    +0x00 u8    вид (0xFF — запись свободна)
    +0x02 i8    особый урон: номер записи таблицы 0x4624F8, отрицательное —
                нет (там сила против конкретной породы: 5000 против 'S',
                3500 против 'I' и так далее)
    +0x03 u8    номер класса
    +0x04 f32   прочность, у стопок — целое КОЛИЧЕСТВО, у зелий — крепость
    +0x08 f32   прочность когда новое
    +0x0C u16   ОТРАВА
    +0x0E u16   —

ОТКУДА ОТРАВА БЕРЁТСЯ В УДАРЕ. Перед расчётом урона движок кладёт её в
глобаль 0x849704:

    ближний бой   VA 0x41A7D0: +0x0C записи предмета в руке
    выстрел       VA 0x41A52C: +0x16 записи снаряда, а туда её кладёт сам
                  выстрел (VA 0x41BB10) из +0x0C записи БОЕПРИПАСА
    зверь         VA 0x41A7D0 и 0x41BB10: байт unit+0xF6 — своя отрава
                  твари; у плевка (порода 'S') она же

ЧТО ОНА ДЕЛАЕТ. При удачном попадании расчёт урона (VA 0x41BF54, тем же
занят 0x41C194) прибавляет её цели:

    цель+0x52 += 0x849704

Дальше в мировом такте (VA 0x41C944) отравленный юнит теряет здоровье:

    если unit+0x52 != 0:  unit+0x4E -= unit+0x52,  и на здоровье < 1 смерть

Такт этот идёт не каждый кадр: тело функции работает при
``счётчик кадров & 0x0F == 0``, то есть КАЖДЫЙ ШЕСТНАДЦАТЫЙ кадр главного
цикла (VA 0x438A00 — там же подряд снаряды, действия юнитов и мир).

Сама отрава не проходит: во всём коде её только прибавляют — снимает
единственно противоядие.

ЗЕЛЬЯ. Номер класса И ЕСТЬ код действия (VA 0x41D954, switch по +0x03
записи; классы меньше 83 действия не имеют). Выпитое зелье становится
классом 83 «Пустая банка», а +0x04 записи — это его крепость, которая
тратится:

    84 Непонятная смесь   здоровье пополам (но не в ноль)
    85 Лечебный бальзам   лечит, не выше 1600; тратит крепость тем больше,
                          чем сильнее ранен
    86 Яд                 отравить: без цели — себя (unit+0x52), с целью —
                          НАМАЗАТЬ ПРЕДМЕТ, то есть записать в его +0x0C
                          (годятся вид 0 и 0x0C — оружие и стрелы)
    87 Масло              мажет стрелы: ставит им +0x02 в ноль
    88 Противоядие        снимает отраву: unit+0x52 уменьшается, ниже нуля
                          не уходит
    89 Брага              на время (+0x4A): ЛОВКОСТЬ −3k, а обаяние, сила
                          и выносливость +k; прежние значения прячутся
                          в +0xC6 (сила действия k — Ловкость/3, но не
                          больше крепости)
    90 Зелье              на время: ловкость, сила и выносливость +k, плюс
                          здоровье на 160·крепость, не выше 1600
    91 Чистая слеза       на время: бонус точности unit+0xF8 =
                          round(sqrt(k)*0.1) (читает 0x41ADD8, пока тикает
                          +0x4A) и глобальный флаг свечения 0x849610 — как
                          у Факела. Облик (тело +0xFC) НЕ меняется
    92 Эликсир Мудрости   слабее шести не действует; срок вдвое дольше,
                          сила −5k (не ниже 1), здоровье −160k (не ниже
                          160), зато даётся опыт

ПОРТРЕТ. Раненая часть портрета перекрашивается (VA 0x4305A4): здоровому
красным, отравленному — лиловым. Сдвиги каналов идут в 0x44293F, а какой
из них какой, видно по сборке таблиц (VA 0x4427C0: красный сдвигается на
11, зелёный на 5) — то есть (красный +50, зелёный −30, синий −30), а у
отравленного синий не вниз, а +50.
"""
from __future__ import annotations

from .paths import game_file

#: Отрава: в предмете и в юните.
ITEM_POISON_AT, UNIT_POISON_AT = 0x0C, 0x52
#: Своя отрава твари.
UNIT_VENOM_AT = 0xF6
#: Глобаль, через которую отрава едет от оружия к цели.
POISON_GLOBAL_VA = 0x849704
#: Здоровье и его предел.
UNIT_HEALTH_AT, HEALTH_MAX = 0x4E, 0x640
#: Мировой такт работает каждый шестнадцатый кадр (VA 0x41C944).
WORLD_TICK_MASK = 0x0F
WORLD_TICK_EVERY = WORLD_TICK_MASK + 1
#: Класс выпитого зелья и первый класс, у которого вообще есть действие.
EMPTY_JAR_CLASS, FIRST_EFFECT_CLASS = 83, 84
#: Классы зелий по действию.
POTION_HALVE, POTION_HEAL, POTION_POISON, POTION_OIL = 84, 85, 86, 87
POTION_ANTIDOTE, POTION_BOOZE, POTION_BREW = 88, 89, 90
POTION_TEAR, POTION_WISDOM = 91, 92
#: Перекраска раненой части портрета: (красный, зелёный, синий).
PORTRAIT_HURT = (50, -30, -30)
PORTRAIT_POISONED = (50, -30, 50)

#: Зелье тратится КРЕПОСТЬЮ (float в записи предмета, +0x04), а не «выпил —
#: и пусто». Каждое действие берёт свою долю, вычитает её из крепости, и
#: банка становится пустой (класс 83) только когда крепости осталось меньше
#: порога. Числа — восьмибайтовые константы из exe (VA 0x41D9F1…0x41DBEB).
POTION_NUMBERS_VA = {
    "heal_base": 0x4501EB,      # 100.0  сколько «стоит» лечение целого
    "heal_step": 0x4501F3,      # 0.1    множитель цены лечения
    "heal_gain": 0x4501FB,      # 160.0  сколько здоровья даёт единица крепости
    "heal_spent": 0x450203,     # 0.01   ниже этого банка пустеет
    "smear_spent": 0x45020B,    # 0.01   порог у намазанного яда
    "oil_needs": 0x450213,      # 10.0   меньше этого маслом не помажешь
    "antidote_step": 0x45021B,  # 0.1    доля отравы, снимаемая за раз
    "antidote_gain": 0x450223,  # 10.0   во сколько крепость снимает отраву
    "antidote_spent": 0x45022B,  # 0.01   порог у противоядия
}
#: Здоровье делится на это, прежде чем считать цену лечения (VA 0x41DA04):
#: чем сильнее ранен, тем дороже каждая единица крепости.
HEAL_HEALTH_DIVISOR = 16
#: Вид записи боеприпаса: только его и можно смазать маслом (VA 0x41DB65).
AMMO_KIND = 0x0C
#: Метка масла — байт +0x02 записи боеприпаса; у чистых стрел там 0xFF.
OIL_MARK_AT = 0x02
#: Отрава, намазанная на предмет, — слово +0x0C его записи. Если округление
#: дало ноль, а крепости хватало, движок пишет единицу (VA 0x41DB03).
ITEM_SMEAR_AT = 0x0C

#: ВРЕМЕННЫЕ ЗЕЛЬЯ (классы 89…92). Все четверо работают одинаково по кругу:
#: пока ``unit+0x4A`` не ноль, второе такое зелье не действует; перед первым
#: движок прячет шесть базовых характеристик из ``unit+0xC0`` в ``unit+0xC6``
#: и ставит срок в ``unit+0x4A``. Сила действия — округлённая крепость.
#:
#: Разобрано по VA 0x41DC14…0x41DE20. Индексы характеристик от ``+0xC0``:
#: 0 Харизма, 1 Ловкость, 2 Интеллект, 3 Обучаемость, 4 Сила, 5 Выносливость.
TEMP_LOCK_AT = 0x4A
TEMP_SAVED_AT = 0xC6
TEMP_SAVED_SIZE = 6
#: Срок: сила действия на это число (у Эликсира Мудрости вдвое дольше).
TEMP_TICKS, TEMP_TICKS_LONG = 0x1E, 0x3C
#: Эликсир Мудрости слабее шести не действует вовсе (VA 0x41DE0A).
WISDOM_MIN = 6
#: Сколько здоровья даёт единица крепости Зелью (та же 160, что у бальзама).
BREW_HEALTH_VA = 0x450233
#: Брага: Ловкость делится на это, и она же уходит вниз втрое (VA 0x41DC23).
BOOZE_DIVISOR, BOOZE_DRAIN = 3, 3
#: Мудрость: Сила падает на пять за единицу, но не ниже единицы; здоровье
#: падает на 160 за единицу, но не ниже 160 (VA 0x41DE2D).
WISDOM_STRENGTH_DRAIN, WISDOM_HEALTH_DRAIN, WISDOM_HEALTH_FLOOR = 5, 0xA0, 0xA0
#: Опыт Эликсира: ``round(sqrt(k − 5) · 100)`` — снято дизасмом хвоста ветки
