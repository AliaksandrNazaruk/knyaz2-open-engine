TEAR_LOOK_AT = 0xF8
TEAR_ACCURACY_SCALE = 0.1
TEAR_ACCURACY_SCALE_VA = 0x45023B
#: Слеза же ставит ГЛОБАЛЬНЫЙ флаг свечения 0x849610 (0x41DD86) — тот самый,
#: что зажигает «Факел» (класс 46, ветка 0x2E в 0x436C48, предмет при этом
#: НЕ тратится). Флаг сбрасывает загрузчик карты (0x43DF48) и читают два
#: рендер-прохода кругов выделения (0x424514, 0x424FD8): при флаге круг
#: рисуется со сдвигом палитры DAT_0058E300 и дымкой-спрайтом 0x6A5598.
#: Облика Слеза НЕ меняет: облик — байт ``unit+0xFC`` (тело), его пишет
