def potion_numbers(data: bytes | None = None) -> dict[str, float]:
    """Числа зелий прямо из exe."""
    import struct as _struct
    from .exetables import va_to_foff
    if data is None:
        with open(game_file("konung2.exe"), "rb") as stream:
            data = stream.read()
    return {name: _struct.unpack_from("<d", data, va_to_foff(va))[0]
            for name, va in POTION_NUMBERS_VA.items()}


