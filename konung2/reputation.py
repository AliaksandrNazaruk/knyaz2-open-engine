# -*- coding: utf-8 -*-
"""
Репутация — счёт добрых и злых дел «Продолжения легенды».

В КАНОНЕ ЕЁ НЕТ ВОВСЕ. Строка «Репутация» есть только в exe донора
(0x4527FD, cp866), рядом с «Уровень» (0x4527F5), и рисуются они одной
функцией экрана героя (VA 0x00433C30): подпись на 658, значение на 786.
В konung2.exe такой строки нет ни одной. Это его собственная механика, и
без неё восемь сотен мест его разговоров ведут себя не так.

ЧТО ЭТО. Одно знаковое число на всю игру, глобал `0x0087F410`. Разговоры
его двигают и о нём спрашивают:

    обработчик 49 (наш 177)   репутация += довод      VA 0x00436A14
    обработчик  8 (наш 136)   репутация >= довода     VA 0x00438120

Оно уходит в сохранение (VA 0x004258A4 пишет, 0x00425158 читает — четыре
байта вторым полем) и потому переживает выход из игры.

СТАРТ У КАЖДОГО СВОЙ. При выборе персонажа (VA 0x0043C4AC) движок кладёт
в счёт значение из таблицы `0x00465A28` по номеру героя. Четыре записи:
Иззарк −30, Велиславна 0, Драгомир −100, Гильдис +30. Читается это как
характер: Драгомир начинает в военном лагере Повелителя, Гильдис — с
чистой славой.

ЗА ЧТО МЕНЯЕТСЯ. Начисление при убийстве (VA 0x00418554) требует, чтобы
убийца был нашей стороны (байт +0x1B у него и у игрока совпал), и дальше
смотрит на жертву:

* у жертвы ЕСТЬ разговор (байт +0xF2 не 0xFF) — цена по таблице
  `0x0045B0D4` с индексом по номеру разговора;
* разговора НЕТ, порода (+0x1A) с битом 0x40, тело (+0xFC) 15 —
  репутация ПРИСВАИВАЕТСЯ −140, а не уменьшается;
* то же с телом 14 — репутация уменьшается на 70.

Тела 15 и 14 — это не звери: 15 носят знатные мужи (Всеслав, Глеб, Крок),
14 — женщины. То есть вторая ветвь наказывает за убийство БЕЗЫМЯННОГО
знатного и безымянной женщины, и цены её согласуются с первой: у
именованного князя по таблице −120, у безымянного −140; у именованной
женщины −60, у безымянной −70.

ПРОВЕРКА ТАБЛИЦЫ. Значения сошлись с именами по всему паку сразу:
Королева Нежити +120, Чёрный маг +50, Предводитель Жёлтых собак +30,
Глеб/Всеслав/Иоанн −120, Жрец Вотана −50, женщины −60, рядовой
именованный −5. Шестнадцать разных цен, и ни одна не выпала из смысла.

ЧЬИ НОМЕРА. Индекс таблицы — номер разговора В ЕГО НУМЕРАЦИИ, а у нас
номера обеих игр лежат вперемешку и различаются полем `game`. Поэтому
цена ищется по ПАРЕ «игра + номер», и канонной жертве цены нет вовсе:
в её игре механики не существует.
"""
from __future__ import annotations

from typing import Any

from konung2 import donor
from konung2.profile import LEGEND

#: Цена убийства по номеру разговора. Движок читает `*(int *)(0x45B0D1 + N)
#: >> 0x18` — то есть ЗНАКОВЫЙ байт по 0x45B0D4 + N.
KILL_COST_VA = 0x0045B0D4

#: Стартовая репутация по номеру героя донора, четыре слова.
START_VA = 0x00465A28
START_COUNT = 4

#: Безымянные, у кого убийство наказывается отдельно (VA 0x00418554).
#: У тела 15 репутация ИМЕННО ПРИСВАИВАЕТСЯ: `DAT_0087f410 = -0x8c`.
NAMELESS_NOBLE_BODY = 15
NAMELESS_NOBLE_SET = -140
NAMELESS_WOMAN_BODY = 14
NAMELESS_WOMAN_ADD = -70

#: Разговоров у него меньше двух сотен, а дальше в таблице лежат чужие
#: данные с ритмом `0 0 0 0 0 1 1 1 1`. Берём с запасом ровно столько,
#: сколько байт может выбрать беззнаковый индекс.
KILL_COST_COUNT = 256


def _signed(value: int) -> int:
    return value - 256 if value >= 128 else value


def kill_costs() -> dict[int, int]:
    """Цены убийства по номеру разговора донора; нули опущены."""
    data = LEGEND.exe_bytes()
    at = LEGEND.va_to_foff(KILL_COST_VA)
    if at is None:
        return {}
    out = {}
    for number in range(KILL_COST_COUNT):
        cost = _signed(data[at + number])
        if cost:
            out[number] = cost
    return out


def starts() -> list[int]:
    """Стартовая репутация четырёх героев донора, по его нумерации."""
    import struct

    data = LEGEND.exe_bytes()
    at = LEGEND.va_to_foff(START_VA)
    if at is None:
        return [0] * START_COUNT
    return list(struct.unpack_from(f"<{START_COUNT}i", data, at))


def start_for(game: str, native_world: int) -> int:
    """Старт героя нашего слота: канону — ноль, его четвёрке — таблица.

    КАНОНУ НОЛЬ НЕ ОТ ЛЕНИ. В «Крови Титанов» репутации нет, и никакого
    её значения для канонного героя в природе не существует; ноль — это
    «счёт ещё не открыт», а не подобранное число.
    """
    if game != "legend":
        return 0
    table = starts()
    return table[native_world] if 0 <= native_world < len(table) else 0


def export() -> dict[str, Any]:
    """Раздел `reputation` для shared.json."""
    if not donor.available():
        return {}
    return {
        # Ключи строками: JSON других не знает, а клиенту нужен разбор
        # в число — он его и делает при загрузке.
        "kill_costs": {str(number): cost
                       for number, cost in kill_costs().items()},
        "nameless": {
            "noble_body": NAMELESS_NOBLE_BODY,
            "noble_set": NAMELESS_NOBLE_SET,
            "woman_body": NAMELESS_WOMAN_BODY,
            "woman_add": NAMELESS_WOMAN_ADD,
        },
    }
